/// Буферы постоянных слотов: ждём `release`, чтобы знать, в какой можно писать.
impl Dispatch<WlBuffer, Занятость> for Config {
    fn event(
        _: &mut Self,
        _: &WlBuffer,
        event: <WlBuffer as Proxy>::Event,
        занят: &Занятость,
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
        if let wayland_client::protocol::wl_buffer::Event::Release = event {
            // Насыщенное вычитание, а не `fetch_sub`: лишний release (например,
            // от поверхности, которую композитор снёс вместе с выходом) не должен
            // прокрутить счётчик через ноль в usize::MAX — слот тогда навсегда
            // считался бы занятым и обои замерли бы.
            let _ = занят.fetch_update(Ordering::Relaxed, Ordering::Relaxed, |n| {
                Some(n.saturating_sub(1))
            });
        }
    }
}

