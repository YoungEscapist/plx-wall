// ── Размер меню: РАНТАЙМОВЫЙ ────────────────────────────────────────────────
//
// Раньше меню было фиксированным окошком 740×576 посреди экрана: четыре
// колонки, три видимых ряда, всё остальное — прокруткой. На 2560×1080 это
// восьмая часть экрана, и выбирать обои приходилось в замочную скважину.
// Теперь выбор занимает ЭКРАН целиком (минус поле по краям), а число колонок и
// рядов считается от того, сколько влезло.
//
// Значения — атомики, а не поля Config: размеры спрашивают и свободные
// функции раскладки (`tab_rects`, `card_rect`, `ui_cells`), которым Config не
// передан, и протаскивать его туда ради двух чисел — шум на десятки сигнатур.
// Ставятся один раз, когда стал известен размер выхода.
use std::sync::atomic::{AtomicU32, Ordering as ПорядокАтомика};

static МЕНЮ_W: AtomicU32 = AtomicU32::new(740);
static МЕНЮ_H: AtomicU32 = AtomicU32::new(576);
/// Высота ВЫХОДА (не меню). Нужна отдельно, потому что высота меню теперь
/// считается ОТ ленты, а не наоборот: узнать «сколько там экрана» из ui_h()
/// стало нельзя.
static ЭКРАН_H: AtomicU32 = AtomicU32::new(1080);

/// Поле от края экрана до края меню.
const МЕНЮ_ПОЛЕ: u32 = 64;

fn ui_w() -> u32 { МЕНЮ_W.load(ПорядокАтомика::Relaxed) }
fn ui_h() -> u32 { МЕНЮ_H.load(ПорядокАтомика::Relaxed) }

/// Подогнать меню под экран. Возвращает true, если размер изменился, — тогда
/// буферы надо пересоздать (см. render_overlay).
///
/// **Меню больше НЕ во весь экран.** Оно было им, пока внутри лежала сетка
/// карточек: рядов много, и они экран заполняли. Ленте нужен один ряд, и на
/// полном экране вокруг него оставалось поле в две трети высоты — пустота, в
/// которой лента терялась. Теперь меню это ПОЛОСА: во всю ширину (минус поле)
/// и ровно такой высоты, сколько нужно ленте. По вертикали её центрирует сам
/// layer-shell — поверхность без якорей встаёт посреди выхода.
fn установить_размер_меню(sw: u32, sh: u32) -> bool {
    let прежние = (ui_w(), ui_h());
    // На совсем маленьком выходе поле съело бы всё меню целиком.
    let w = sw.saturating_sub(МЕНЮ_ПОЛЕ * 2).max(360);
    // Порядок важен: `карта_h()` спрашивает ui_w() и ЭКРАН_H, поэтому оба
    // должны быть уже записаны.
    МЕНЮ_W.store(w, ПорядокАтомика::Relaxed);
    ЭКРАН_H.store(sh.max(1), ПорядокАтомика::Relaxed);
    let h = (MY + карта_h() + ЛЕНТА_НИЗ)
        .min(sh.saturating_sub(16).max(160))
        .max(160);
    МЕНЮ_H.store(h, ПорядокАтомика::Relaxed);
    прежние != (w, h)
}

// ── Лента ────────────────────────────────────────────────────────────────────
//
// Сетка квадратиков 155×155 заменена на ЛЕНТУ: один ряд крупных карточек 16:9,
// листающийся вбок. Так просил Ярик 24.08.2026, и причина не только во вкусе:
// обои — это картинка 16:9, а квадратная карточка показывала её обрезанной по
// бокам, то есть врала о том, что ты выбираешь. В ряду из четырёх карточек по
// 568 px обои видно целиком и крупно, а не почтовой маркой.

/// Отношение сторон карточки — то же, что у экрана.
const КАРТА_W_К_H: (u32, u32) = (16, 9);
/// Пределы высоты карточки. Верхний нужен, чтобы на 4K лента не выродилась в
/// две исполинские карточки; нижний — чтобы на маленьком выходе от неё
/// осталось хоть что-то узнаваемое.
const КАРТА_H_МАКС: u32 = 340;
const КАРТА_H_МИН: u32 = 110;
/// Полоса под лентой: прокрутка и воздух под ней.
const ЛЕНТА_НИЗ: u32 = 44;
/// Поле по бокам ленты — под стрелки листания. Их место резервируется ЗАРАНЕЕ,
/// а не отдаётся тому, что осталось: иначе на широком выходе карточки съедали
/// всю ширину, и стрелка ложилась поверх крайней карточки.
const ЛЕНТА_БОК: u32 = ARROW + 16;

/// Высота карточки ленты.
///
/// Считается от ЭКРАНА, а не от меню: высота меню сама выводится отсюда
/// (см. `установить_размер_меню`), и спрашивать её здесь значило бы замкнуть
/// круг. Три ограничителя, каждый по своей причине:
///  · по ширине — две карточки обязаны влезать всегда, иначе «лента»
///    превращается в один слайд;
///  · по экрану — лента остаётся ПОЛОСОЙ поверх рабочего стола, а не
///    занавесом на пол-экрана;
///  · потолок КАРТА_H_МАКС — чтобы на 4K не вышло две исполинские карточки.
fn карта_h() -> u32 {
    let по_ширине = (ui_w().saturating_sub(ЛЕНТА_БОК * 2 + GAP) / 2)
        * КАРТА_W_К_H.1 / КАРТА_W_К_H.0;
    let экран = ЭКРАН_H.load(ПорядокАтомика::Relaxed);
    let по_экрану = (экран * 2 / 5).max(КАРТА_H_МИН);
    по_ширине.min(по_экрану).min(КАРТА_H_МАКС).max(КАРТА_H_МИН)
}

/// Ширина карточки ленты.
fn карта_w() -> u32 {
    (карта_h() * КАРТА_W_К_H.0 / КАРТА_W_К_H.1).max(1)
}

/// Сколько карточек видно в ленте разом.
fn видно_карт() -> u32 {
    let доступно = ui_w().saturating_sub(ЛЕНТА_БОК * 2);
    ((доступно + GAP) / (карта_w() + GAP)).max(1)
}

/// Левый край первой карточки — лента стоит по центру меню.
fn лента_x() -> u32 {
    let n = видно_карт();
    let ширина = n * карта_w() + (n - 1) * GAP;
    (ui_w().saturating_sub(ширина)) / 2
}

/// Верх карточек: лента висит по центру между полосой кнопок и прокруткой.
fn лента_y() -> u32 {
    let поле = ui_h().saturating_sub(MY + ЛЕНТА_НИЗ);
    MY + поле.saturating_sub(карта_h()) / 2
}

