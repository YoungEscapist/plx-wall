// ── Layer setup ──────────────────────────────────────────────────────────────

fn setup_layers(state: &mut Config) {
    let Some(ref compositor) = state.compositor else { return };
    let Some(ref layer_shell) = state.layer_shell else { return };
    let Some(ref qh) = state.qh else { return };
    let Some((ref output, _, _)) = state.outputs.first() else { return };

    // ── Background — обои, СВОЯ поверхность на каждом выходе ─────────────────
    //
    // Зовётся заново при появлении каждого нового выхода, поэтому заводим фон
    // только тем, у кого его ещё нет: повторный вызов не должен плодить вторую
    // поверхность на том же мониторе.
    let выходы: Vec<WlOutput> = state.outputs.iter().map(|(o, _, _)| o.clone()).collect();
    for выход in выходы {
        if state.фоны.iter().any(|ф| ф.выход.id() == выход.id()) {
            continue;
        }
        let bg = compositor.create_surface(qh, ());
        let layer = layer_shell.get_layer_surface(
            &bg, Some(&выход), zwlr_layer_shell_v1::Layer::Background,
            "dwall".to_string(), qh, (),
        );
        // set_size(0,0) + якорь по всем краям = «во весь этот выход»; настоящий
        // размер придёт в configure, у каждого монитора свой.
        layer.set_size(0, 0);
        layer.set_anchor(zwlr_layer_surface_v1::Anchor::all());
        layer.set_exclusive_zone(-1);
        // Viewport заводим один раз на всю жизнь поверхности; прямоугольники
        // задаются на каждом кадре (см. `показать_на_фонах`).
        let viewport = state.viewporter.as_ref().map(|vp| vp.get_viewport(&bg, qh, ()));
        bg.commit();
        state.фоны.push(Фон {
            выход,
            surface: bg,
            layer,
            viewport,
            configured: false,
            размер: (0, 0),
        });
    }

    // Overlay заводим только один раз и только на первом выходе: меню выбора
    // обоев — это одно окно, показывать его копиями на каждом мониторе не надо.
    if state.ol_surface.is_some() {
        return;
    }

    // Overlay — UI выбора.
    //
    // Размер задаём ТОЛЬКО через set_size, без якорей: буфер у нас ровно
    // ui_w()×ui_h(), а якорь по всем четырём краям заставил бы композитор
    // растянуть поверхность на весь выход, и она разъехалась бы с буфером.
    // Без якорей layer-shell центрирует поверхность на выходе — что нам и надо.
    let ol = compositor.create_surface(qh, ());
    let ol_layer = layer_shell.get_layer_surface(
        &ol, Some(output), zwlr_layer_shell_v1::Layer::Overlay,
        "dwall-overlay".to_string(), qh, (),
    );
    ol_layer.set_size(ui_w(), ui_h());
    ol_layer.set_exclusive_zone(-1);
    // Клавиатуру просим ТОЛЬКО когда меню открыто (см. главный цикл).
    //
    // Раньше OnDemand стоял здесь, при создании поверхности, — «без клавиатуры
    // оверлей нечем закрыть с клавиш». Но поверхность заводится сразу при
    // старте dwall и живёт всегда: закрытое меню — это прозрачный кадр с
    // пустым регионом ввода, а не отсутствие слоя. Композитор честно отдавал
    // клавиатуру тому, кто её просит, и весь ввод уходил в невидимое меню.
    // На десктопе это маскировалось (первый клик по окну возвращает фокус), а
    // на свежем входе в сеанс кликать не по чему — выглядело как намертво
    // зависший сеанс при играющих обоях (31.08.2026).
    ol.commit();
    state.ol_surface = Some(ol);
    state.ol_layer = Some(ol_layer);
}

// ── Background rendering ─────────────────────────────────────────────────────

/// Прицепить готовый буфер ко ВСЕМ фоновым поверхностям и вернуть, скольким
/// из них он достался.
///
/// Возвращённое число — это [`Занятость`] буфера: композитор пришлёт по одному
/// `release` на каждую поверхность, и писать в буфер снова можно только после
/// последнего. Ноль значит «показать было некому» — звавший обязан считать, что
/// кадр не ушёл (буфер остаётся свободным).
///
/// Кадр у всех мониторов ОДИН, различаются только прямоугольники viewport:
/// `src` берёт из кадра центральный кусок под пропорцию этого экрана, `dst`
/// растягивает его на весь экран. Это тот же закон «заполнить», что раньше
/// исполнял `blit_scaled`, только считает его видеокарта.
///
/// **Без `wp_viewporter` показываем только на первом выходе.** Тогда буфер
/// заведён размером с экран и растянут на процессоре под ОДИН конкретный
/// монитор; отдать его второму, у которого размер другой, значит показать
/// разъехавшуюся с экраном картинку. Прежнее одноэкранное поведение — честный
/// откат для композиторов без viewporter (в dawn он есть).
fn показать_на_фонах(state: &mut Config, буфер: &WlBuffer, кw: u32, кh: u32) -> usize {
    if кw == 0 || кh == 0 {
        return 0;
    }
    let есть_viewport = state.фоны.iter().any(|ф| ф.viewport.is_some());
    let сейчас = std::time::Instant::now();
    let mut отдано = 0usize;

    for (i, фон) in state.фоны.iter().enumerate() {
        if !фон.configured {
            continue;
        }
        let (эw, эh) = фон.размер;
        if эw == 0 || эh == 0 {
            continue;
        }
        match фон.viewport.as_ref() {
            Some(vp) => {
                let k = (эw as f64 / кw as f64).max(эh as f64 / кh as f64);
                let вид_w = (эw as f64 / k).min(кw as f64).max(1.0);
                let вид_h = (эh as f64 / k).min(кh as f64).max(1.0);
                vp.set_source((кw as f64 - вид_w) / 2.0, (кh as f64 - вид_h) / 2.0, вид_w, вид_h);
                vp.set_destination(эw as i32, эh as i32);
            }
            // Без viewporter — только первый выход, см. доктекст.
            None if i == 0 && !есть_viewport => {}
            None => continue,
        }
        // Кадровый callback у КАЖДОЙ поверхности: по нему понимаем, видно ли
        // обои. Молчание всех сразу и есть «нас не видно» — главный цикл тогда
        // перестаёт забирать кадры, декодер встаёт, видеокарта отдыхает. Пока
        // отвечает хоть один монитор, обои продолжают идти на нём.
        if let Some(qh) = state.qh.as_ref() {
            фон.surface.frame(qh, ());
        }
        фон.surface.attach(Some(буфер), 0, 0);
        // Порча — в координатах БУФЕРА, а он размером с кадр, не с экран.
        фон.surface.damage_buffer(0, 0, кw as i32, кh as i32);
        фон.surface.commit();
        отдано += 1;
    }

    if отдано > 0 {
        state.кадр_заказан = Some(сейчас);
    }
    отдано
}

fn render_wallpaper(state: &mut Config) {
    // Пока не подтверждён первый configure, attach запрещён протоколом. Ждём
    // хотя бы одну готовую поверхность: остальные подтянутся своим configure и
    // получат кадр следующим же вызовом.
    let Some(первый) = state.фоны.iter().find(|ф| ф.configured && ф.размер.0 > 0) else {
        return;
    };
    // Размер ПЕРВОГО готового экрана. С viewporter он ни на что не влияет —
    // буфер равен кадру, а под каждый монитор кроит его свой viewport. Нужен
    // только прежнему пути без viewporter, где кадр растягивается на процессоре
    // и потому годится ровно для одного экрана.
    let (w, h) = первый.размер;
    if w == 0 || h == 0 { return; }

    // ── Размер буфера ───────────────────────────────────────────────────────
    // С wp_viewporter буфер равен размеру КАДРА, а не экрана: композитор сам
    // растянет его на видеокарте. Это и есть вся оптимизация. Живые обои
    // 1280×720 на экране 3840×2160 — это 3.7 МБ на кадр вместо 33 МБ, и ни
    // одного масштабирования на процессоре: мы просто копируем кадр как есть.
    //
    // Замер 09.08.2026 до правки: ffmpeg растягивал сам — 264% CPU; после
    // переноса растягивания в dwall (blit_scaled) — 21% у ffmpeg и 48% у
    // dwall. Теперь растягивать не должен никто из них.
    //
    // Без viewporter (другой композитор) всё как раньше — буфер размером с
    // экран, растягиваем сами.
    let по_viewport = state.фоны.iter().any(|ф| ф.viewport.is_some());
    // Кадр, залитый декодером прямо в общую память, задаёт размер сам: своего
    // `img` у него нет и быть не должно — весь смысл в том, что кадр нигде,
    // кроме слота, не лежит.
    let (bw, bh) = match (state.кадр_слота, по_viewport, state.img.as_ref()) {
        (Some((_, dw, dh)), _, _) if dw > 0 && dh > 0 => (dw, dh),
        (_, true, Some((iw, ih, _))) if *iw > 0 && *ih > 0 => (*iw, *ih),
        _ => (w, h),
    };
    let buf_size = (bw * bh * 4) as usize;

    // ── Два постоянных буфера вместо нового на каждый кадр ──────────────────
    // Пишем всегда в тот, что не показан сейчас. Раньше каждый кадр создавал
    // memfd, mmap, пул и wl_buffer — на живых обоях это десятки раз в секунду.
    if state.bg_dims != (bw, bh) || state.bg_slots.len() < 2 {
        state.bg_slots.clear();
        let (Some(shm), Some(qh)) = (state.shm.as_ref(), state.qh.as_ref()) else { return };
        let Some(slots) = make_slots(shm, qh, bw, bh) else { return };
        state.bg_slots = slots;
        state.bg_dims = (bw, bh);
        state.bg_slot = 0;
        // Кэш растянутой картинки считался под старый размер.
        state.scaled = None;
    }

    // Статичные обои готовим ОДИН раз: растягиваем под выход и переводим в
    // BGRA. Дальше и обычная перерисовка, и каждый кадр перехода — это просто
    // копирование готового буфера.
    //
    // Считаем в локальную переменную, а не прямо в state.scaled: пока живо
    // заимствование state.img, писать в state нельзя.
    // В режиме viewport кэш не нужен вовсе: буфер равен размеру картинки, и
    // «растягивание» сводится к копированию.
    let новый_кэш = if !по_viewport && state.anim.is_none() && state.scaled.is_none() {
        let bgra = state.img_bgra;
        state.img.as_ref().and_then(|(iw, ih, px)| {
            let mut кадр = if *iw == w && *ih == h && px.len() >= buf_size {
                px[..buf_size].to_vec()
            } else {
                resize(*iw, *ih, px, w, h)
            };
            if !bgra {
                for c in кадр.chunks_exact_mut(4) { c.swap(0, 2); }
            }
            (кадр.len() >= buf_size).then_some(кадр)
        })
    } else {
        None
    };
    if новый_кэш.is_some() {
        state.scaled = новый_кэш;
    }

    // Пишем только в тот буфер, который композитор уже отпустил. Раньше слоты
    // чередовались вслепую, и на живых обоях можно было попасть в буфер,
    // который прямо сейчас читают, — это видно как рваные прямоугольные куски
    // соседнего кадра.
    //
    // Свободного нет — не рисуем, но и не забываем: у живых обоев кадр можно
    // просто потерять, а вот единственный кадр статичной картинки потерять
    // нельзя, иначе обои так и не появятся. Флаг заставит главный цикл
    // повторить попытку.
    // Кадр от декодера уже лежит в своём слоте — его и показываем, ничего не
    // заполняя. Это и есть вся экономия: кадр приходит из ffmpeg сразу в ту
    // память, которую заберёт композитор.
    let готовый = state.кадр_слота.and_then(|(i, _, _)| (i < state.bg_slots.len()).then_some(i));
    let next = match готовый {
        Some(i) => i,
        None => match take_free_slot(&state.bg_slots, state.bg_slot) {
            Some(i) => i,
            None => {
                state.bg_pending = true;
                return;
            }
        },
    };
    state.bg_pending = false;
    state.bg_slot = next;
    let slot = &state.bg_slots[state.bg_slot];
    let dst = unsafe { std::slice::from_raw_parts_mut(slot.ptr, slot.len) };

    if готовый.is_some() {
        // Заполнять нечего. Дальше по коду — переход и viewport, они работают
        // поверх уже лежащего кадра.
    } else {
    match state.img {
        // Статичные обои идут через кэш: во время перехода кадр собирается
        // заново каждые ~16 мс, а Lanczos на 4K столько раз не потянуть.
        Some(_) if state.anim.is_none() && state.scaled.is_some() => {
            let кэш = state.scaled.as_ref().unwrap();
            if кэш.len() >= buf_size {
                dst.copy_from_slice(&кэш[..buf_size]);
            }
        }
        // Кадр уже нужного размера — просто копируем. Ни масштабирования, ни
        // свопа: самый дешёвый путь, ради него всё. С viewporter сюда попадает
        // ЛЮБОЙ кадр, потому что буфер под него и заведён.
        Some((iw, ih, ref px)) if iw == bw && ih == bh && px.len() >= buf_size => {
            dst.copy_from_slice(&px[..buf_size]);
            if !state.img_bgra {
                for c in dst.chunks_exact_mut(4) { c.swap(0, 2); }
            }
        }
        // Размер не совпал.
        //
        // Для АНИМАЦИИ масштабируем сами, прямо в разделяемую память: крейт
        // image на каждый кадр копировал исходник, заводил ещё один буфер на
        // весь экран и отдавал его нам третьей копией — 33 МБ туда-сюда по
        // десять раз в секунду. Свой блит по ближайшему соседу с заранее
        // посчитанной таблицей столбцов пишет ровно один раз и никаких
        // аллокаций не делает.
        Some((iw, ih, ref px)) if state.anim.is_some() && iw > 0 && ih > 0 => {
            blit_scaled(px, iw, ih, dst, bw, bh, state.img_bgra);
        }
        // Статичная картинка — путь прежний, качественный: она масштабируется
        // один раз при выборе, экономить тут нечего.
        Some((iw, ih, ref px)) => {
            let mut rgba = resize(iw, ih, px, bw, bh);
            if !state.img_bgra {
                for c in rgba.chunks_exact_mut(4) { c.swap(0, 2); }
            }
            if rgba.len() < buf_size { return; }
            dst.copy_from_slice(&rgba[..buf_size]);
        }
        None => dst.fill(35),
    }
    }

    // ── Плавный переход ─────────────────────────────────────────────────────
    // В dst уже лежит НОВЫЙ кадр; подмешиваем к нему снимок старого. Смешиваем
    // прямо на месте — лишний буфер на весь экран (это десятки мегабайт) тут
    // ни к чему.
    if let Some(fade) = state.fade.as_mut() {
        // Снимок сделан под ПРОШЛЫЕ обои, а у новых свой размер кадра (с
        // viewporter это обычное дело). Подгоняем один раз за переход, а не на
        // каждом кадре: дальше размеры уже совпадут.
        if !fade.ждём && fade.dims != (bw, bh) && fade.dims.0 > 0 && fade.dims.1 > 0 {
            let mut подогнан = vec![0u8; buf_size];
            blit_scaled(
                &fade.from, fade.dims.0, fade.dims.1,
                &mut подогнан, bw, bh,
                true, // в буферах уже BGRA, менять местами нечего
            );
            fade.from = подогнан;
            fade.dims = (bw, bh);
        }
        if fade.ждём {
            // Новые обои ещё не готовы — показываем старый кадр как есть.
        } else if fade.from.len() >= dst.len() {
            let начало = *fade.start.get_or_insert_with(std::time::Instant::now);
            let прошло = начало.elapsed().as_millis() as u64;
            if прошло >= FADE_MS {
                state.fade = None;
            } else {
                // Сглаживание по краям (smoothstep): линейное появление на
                // глаз начинается рывком и так же обрывается.
                let t = прошло as f32 / FADE_MS as f32;
                let t = t * t * (3.0 - 2.0 * t);
                let новый = (t * 256.0) as u32;
                let старый = 256 - новый;
                for (d, s) in dst.iter_mut().zip(fade.from.iter()) {
                    *d = (((*d as u32) * новый + (*s as u32) * старый) >> 8) as u8;
                }
            }
        } else {
            // Снимок не того размера (экран переключили посреди перехода) —
            // показываем новые обои сразу, без смешивания.
            state.fade = None;
        }
    }

    // ── Показать на всех мониторах ──────────────────────────────────────────
    // Кадр один, а прямоугольники viewport у каждого экрана свои — раскладку
    // и кадровый callback делает `показать_на_фонах`.
    //
    // Композитор не обязан отвечать на callback: dawn молчит, пока обои целиком
    // накрыты полноэкранным окном (см. Dawn::wallpaper_hidden). Молчание всех
    // поверхностей и есть «нас не видно»: главный цикл перестаёт забирать кадры,
    // очередь декодера (ёмкостью 1) переполняется, ffmpeg упирается в трубу и
    // встаёт. Запрос при этом не пропадает — он ждёт в поверхности и приедет
    // первым же кадром, когда обои снова покажутся.
    let буфер = state.bg_slots[state.bg_slot].buffer.clone();
    let отдано = показать_на_фонах(state, &буфер, bw, bh);
    // Показать было некому (все поверхности ещё без configure) — буфер остаётся
    // свободным, кадр повторится следующим вызовом.
    if отдано > 0 {
        state.bg_slots[state.bg_slot].занят.store(отдано, Ordering::Relaxed);
    }
}

/// Завести `wl_buffer` поверх готовых dmabuf-дескрипторов.
///
/// `None` — композитор такое сочетание формата с модификатором не объявлял, и
/// создавать буфер НЕЛЬЗЯ: `create_immed` в этом случае отвечает не отказом, а
/// протокольной ошибкой, то есть мгновенно убивает клиента.
fn создать_dmabuf_буфер(
    state: &Config,
    описание: &hwvideo::ОписаниеПоверхности,
) -> Option<(WlBuffer, Занятость)> {
    let dmabuf = state.dmabuf.as_ref()?;
    let qh = state.qh.as_ref()?;

    if !state.dmabuf_форматы.contains(&(описание.fourcc, описание.модификатор)) {
        eprintln!(
            "dwall: композитор не объявил формат {:?} с модификатором {:#x}",
            std::str::from_utf8(&описание.fourcc.to_le_bytes()).unwrap_or("?").trim_end(),
            описание.модификатор,
        );
        return None;
    }

    let params = dmabuf.create_params(qh, ());
    let (hi, lo) = (
        (описание.модификатор >> 32) as u32,
        (описание.модификатор & 0xffff_ffff) as u32,
    );
    for (номер, плоскость) in описание.плоскости.iter().enumerate() {
        params.add(
            плоскость.fd.as_fd(),
            номер as u32,
            плоскость.сдвиг,
            плоскость.шаг,
            hi,
            lo,
        );
    }

    // create_immed, а не create: буфер нужен здесь и сейчас, а ждать ответа
    // композитора в главном цикле — это лишний круг диспетчеризации на каждую
    // новую поверхность. Сочетание формата с модификатором мы уже проверили
    // выше, так что протокольной ошибке взяться неоткуда.
    let занят: Занятость = std::sync::Arc::new(AtomicUsize::new(0));
    let буфер = params.create_immed(
        описание.ширина as i32,
        описание.высота as i32,
        описание.fourcc,
        zwp_linux_buffer_params_v1::Flags::empty(),
        qh,
        занят.clone(),
    );
    // Заготовка своё отработала: буфер от неё уже не зависит.
    params.destroy();

    Some((буфер, занят))
}

/// Сколько раз пробуем поднять умерший декодер, прежде чем сдаться.
const ПОПЫТОК_ПОДНЯТЬ: u32 = 5;

/// Поток декодера живых обоев кончился — записать это и назначить перезапуск.
///
/// **Почему это вообще функция, а не `state.hw = None`.** Именно так здесь и
/// было, в обеих ветках `Disconnected` (аппаратной и ffmpeg'овой), молча и
/// навсегда: канал закрылся — живые обои просто переставали существовать, на
/// экране оставался последний кадр, в логе не было ни строки. Снаружи это
/// выглядит как «обои иногда перестают быть анимированными», и починить это
/// «иногда» было нечем, потому что и жалоба, и причина оставались без следа.
///
/// Умереть поток может по-разному и не по нашей вине: битый кадр в середине
/// ролика, отвалившаяся поверхность VAAPI, драйвер, потерявший контекст после
/// долгой паузы. Все эти случаи лечатся одним и тем же — поднять декодер
/// заново с того же файла, чем ниже и занимается [`перезапустить_живые`].
///
/// Отсрочка растёт (1, 2, 4, 8, 16 с): если файл битый насовсем, мы не
/// перезапускаем ffmpeg по десять раз в секунду, а через [`ПОПЫТОК_ПОДНЯТЬ`]
/// попыток сдаёмся вовсе и говорим об этом прямо.
fn декодер_умер(state: &mut Config, откуда: &str) {
    state.hw = None;
    state.anim = None;
    if state.живые_путь.is_none() {
        return;
    }
    let попытка = state.живые_рестарт.map(|(_, n)| n).unwrap_or(0) + 1;
    if попытка > ПОПЫТОК_ПОДНЯТЬ {
        eprintln!(
            "dwall: декодер ({откуда}) умирает раз за разом — живые обои выключены, \
             на экране останется последний кадр",
        );
        state.живые_путь = None;
        state.живые_рестарт = None;
        return;
    }
    let отсрочка = std::time::Duration::from_secs(1u64 << (попытка - 1));
    eprintln!(
        "dwall: декодер ({откуда}) кончился — поднимаем заново через {:?} (попытка {попытка})",
        отсрочка,
    );
    state.живые_рестарт = Some((std::time::Instant::now() + отсрочка, попытка));
}

/// Сколько `wl_buffer` живых обоев держим на композиторе одновременно.
///
/// Пул поверхностей у декодера — единицы (`initial_pool_size = 8`), так что в
/// здоровом случае предел не срабатывает ни разу. Он про НЕздоровый.
///
/// Замер 24.08.2026 в живом сеансе: за 36 секунд показа живых обоев dawn набрал
/// **741 дескриптор dmabuf** (при мягком лимите процесса 1024) и 352 пары
/// буферов по 8 и 4.25 МиБ — то есть новый `wl_buffer` заводился на КАЖДЫЙ
/// кадр, а старый не уничтожался никогда: `hw_буферы` только росла. Кончалось
/// это дважды: у dawn падал `pactl` с «Too many open files», а у видеокарты
/// (8 ГБ, из них 2.4 держит dota2) кончалась память — `gbm_bo_create` начинал
/// возвращать EINVAL, ядро писало `Failed to allocate NVKMS memory for GEM
/// object`, и композитор переставал показывать кадры вовсе.
///
/// Причина найдена и вылечена по месту (флаш на обороте ролика, см.
/// hwvideo.rs), а предел остался страховкой: любой другой повод сменить номера
/// упрётся в него, а не в лимит дескрипторов композитора. Пул — 8 поверхностей,
/// так что 16 даёт запас ровно в одно поколение.
const ПРЕДЕЛ_HW_БУФЕРОВ: usize = 16;

/// Уничтожить устаревшие буферы, которые композитор наконец отпустил.
fn вынести_hw_мусор(state: &mut Config) {
    state.hw_мусор.retain(|(буфер, занят)| {
        if занят.load(Ordering::Relaxed) == 0 {
            буфер.destroy();
            false
        } else {
            true
        }
    });
}

/// Выбросить самые старые буферы живых обоев, если их накопилось больше предела.
///
/// Уничтожать можно только те, что композитор уже отпустил (`свободен`): буфер
/// на экране выдернуть — это рябь на обоях. Занятые уходят в конец очереди и
/// дождутся следующего раза.
///
/// Вычеркнуть номер надо И из общего с декодером списка `известные`, иначе
/// декодер решит, что главный цикл про поверхность знает, описание больше не
/// пришлёт — и кадры с этим номером молча перестанут показываться.
fn подрезать_hw_буферы(state: &mut Config) {
    let Some(hw) = state.hw.as_ref() else { return };
    let известные = hw.известные.clone();
    let mut попыток = state.hw_порядок.len();
    while state.hw_буферы.len() > ПРЕДЕЛ_HW_БУФЕРОВ && попыток > 0 {
        попыток -= 1;
        let Some(номер) = state.hw_порядок.pop_front() else { break };
        let свободен = match state.hw_буферы.get(&номер) {
            Some((_, занят)) => занят.load(Ordering::Relaxed) == 0,
            // Уже убрали другим путём — просто выкидываем из очереди.
            None => continue,
        };
        if !свободен {
            state.hw_порядок.push_back(номер);
            continue;
        }
        if let Some((буфер, _)) = state.hw_буферы.remove(&номер) {
            буфер.destroy();
        }
        if let Ok(mut с) = известные.lock() {
            с.remove(&номер);
        }
        // Один раз за жизнь процесса: сам факт срабатывания и означает, что
        // номера поверхностей текут (см. ПРЕДЕЛ_HW_БУФЕРОВ). Без этой строки
        // утечка снова стала бы видна только по чужим симптомам — замёрзшему
        // экрану и «Too many open files» в логе композитора.
        static РАЗ: std::sync::Once = std::sync::Once::new();
        РАЗ.call_once(|| {
            eprintln!("dwall: поверхности живых обоев не переиспользуются — \
                       держим не больше {} буферов", ПРЕДЕЛ_HW_БУФЕРОВ);
        });
    }
}

/// Поднять декодер живых обоев заново, тем же файлом.
///
/// Это НЕ смена обоев: ни палитры, ни плавного перехода, ни записи выбора в
/// конфиг здесь нет (всё это делает `start_load_wallpaper`, и повторять его на
/// каждой икоте драйвера значило бы пересчитывать палитру и мигать переходом
/// на ровном месте). Меняется ровно одно — вместо мёртвого потока появляется
/// живой, и кадры снова начинают приходить.
fn перезапустить_живые(state: &mut Config) {
    let Some(путь) = state.живые_путь.clone() else { return };
    let (w, h) = state.outputs.first().map(|(_, w, h)| (*w, *h)).unwrap_or((0, 0));
    if w == 0 || h == 0 {
        return;
    }
    // Буферы прошлых поверхностей уничтожаем явно: номера поверхностей у
    // нового декодера свои, и старые пары «буфер + флаг» никогда больше не
    // совпадут — без этого на композиторе оседал бы лишний пул на каждый
    // перезапуск (прокси wayland-client в Drop серверу не шлёт ничего).
    state.hw_на_экране.clear();
    for (буфер, _) in state.hw_буферы.values() {
        буфер.destroy();
    }
    state.hw_буферы.clear();
    state.hw_порядок.clear();
    for (буфер, _) in state.hw_мусор.drain(..) {
        буфер.destroy();
    }
    state.кадр_слота = None;

    if is_video(&путь) && state.dmabuf.is_some() {
        if let Some(hw) = hwvideo::запустить(&путь, hwvideo::УЗЕЛ_ПО_УМОЛЧАНИЮ) {
            state.hw = Some(hw);
            state.hw_срок = std::time::Instant::now();
            return;
        }
    }
    if is_video(&путь) || путь.to_lowercase().ends_with(".gif") {
        state.anim = start_anim(&путь, w, h);
    }
}

/// Показать очередной кадр аппаратных живых обоев.
///
/// Здесь нет ни единого касания пикселей: кадр приехал готовым буфером в
/// видеопамяти, и вся работа — прицепить его к поверхности.
fn показать_hw_кадр(state: &mut Config) {
    // Кадры, которые композитор снял с показа, отпускаем: пока держатель жив,
    // декодер не может забрать поверхность обратно в пул.
    state.hw_на_экране.retain(|(занят, _)| занят.load(Ordering::Relaxed) != 0);

    // Пока не подтверждён первый configure, attach запрещён протоколом. Ждём
    // хотя бы одну готовую поверхность — остальные подхватятся своим configure.
    if !state.фоны.iter().any(|ф| ф.configured) {
        return;
    }
    let сейчас = std::time::Instant::now();
    if сейчас < state.hw_срок {
        return;
    }

    // Забираем кадр. Первый кадр забран ещё при запуске декодера — там по нему
    // проверялось, что видеокарта вообще потянула этот кодек (см. hwvideo.rs),
    // и показать его надо прежде всего остального.
    let первый = state.hw.as_mut().and_then(|hw| hw.первый.take());
    let кадр = match первый {
        Some(кадр) => кадр,
        None => match state.hw.as_ref().map(|hw| hw.rx.try_recv()) {
            Some(Ok(кадр)) => кадр,
            Some(Err(std::sync::mpsc::TryRecvError::Empty)) => return,
            // Поток декодера кончился (битый файл, карта отказала на середине).
            // Не «живых обоев больше нет», а «поднимаем заново» — см. декодер_умер.
            Some(Err(std::sync::mpsc::TryRecvError::Disconnected)) => {
                декодер_умер(state, "видеокарта");
                return;
            }
            None => return,
        },
    };

    // Кадр приехал — значит декодер жив, и счётчик неудачных подъёмов можно
    // обнулить. Иначе пять икот драйвера за неделю сложились бы в «сдаёмся».
    state.живые_рестарт = None;

    // Срок следующего кадра отсчитываем от срока текущего, а не от «сейчас»:
    // иначе к каждому кадру прибавлялось бы опоздание главного цикла, и ролик
    // на 60 к/с полз бы медленнее реального времени. Отстали больше чем на
    // кадр — догонять нечем, начинаем отсчёт заново.
    state.hw_срок = if сейчас.duration_since(state.hw_срок) > кадр.шаг {
        сейчас + кадр.шаг
    } else {
        state.hw_срок + кадр.шаг
    };

    // Поверхность, которую видим впервые, — заводим под неё буфер. Дальше она
    // будет узнаваться по номеру, и протокольной работы не останется вовсе.
    if let Some(описание) = кадр.описание.as_ref() {
        match создать_dmabuf_буфер(state, описание) {
            Some(пара) => {
                // Описание на УЖЕ известный номер значит одно: пул поверхностей
                // пересобрался (оборот ролика — см. флаш в hwvideo.rs), и номер
                // достался другой поверхности. Прежний буфер показывает чужую
                // память, и жить ему ровно до release от композитора.
                if let Some(старый) = state.hw_буферы.insert(описание.surface_id, пара) {
                    state.hw_мусор.push(старый);
                } else {
                    state.hw_порядок.push_back(описание.surface_id);
                }
                вынести_hw_мусор(state);
                подрезать_hw_буферы(state);
            }
            None => {
                // Композитор такого не примет — уходим на путь через ffmpeg.
                eprintln!("dwall: dmabuf не принят композитором, откат на ffmpeg");
                state.hw = None;
                state.hw_на_экране.clear();
                let (w, h) = state.outputs.first().map(|(_, w, h)| (*w, *h)).unwrap_or((0, 0));
                let путь = state.wallpapers.get(state.current).cloned();
                if let (Some(путь), true) = (путь, w > 0 && h > 0) {
                    state.anim = start_anim(&путь, w, h);
                }
                return;
            }
        }
    }

    let Some((буфер, занят)) = state.hw_буферы.get(&кадр.surface_id) else { return };
    let (буфер, занят) = (буфер.clone(), занят.clone());

    // Размер кадра; раскладку по мониторам (тот же закон «заполнить») делает
    // `показать_на_фонах` — у каждого экрана свой viewport.
    let (кw, кh) = match state.hw.as_ref().map(|hw| hw.размер) {
        Some((кw, кh)) if кw > 0 && кh > 0 => (кw, кh),
        _ => return,
    };

    let отдано = показать_на_фонах(state, &буфер, кw, кh);
    if отдано == 0 {
        // Показать некому — кадр не ушёл, держатель не нужен: пусть декодер
        // забирает поверхность обратно в пул.
        return;
    }
    занят.store(отдано, Ordering::Relaxed);

    // Держим поверхность занятой, пока композитор не отпустит буфер со ВСЕХ
    // мониторов (счётчик дойдёт до нуля).
    state.hw_на_экране.push((занят, кадр.держатель));
}

/// Отдать декодеру видео свободные слоты общей памяти.
///
/// Он пишет кадр прямо в них (см. [`залить_кадр`]), поэтому слот можно
/// одалживать, только когда его отпустили ВСЕ мониторы (счётчик [`Занятость`]
/// дошёл до нуля) и когда он не показан прямо сейчас. Пока обои закрыты
/// полноэкранным окном, не одалживаем вовсе — декодер встаёт на `recv`, ffmpeg
/// упирается в трубу и засыпает.
///
/// Слоты заводятся здесь же, по размеру кадра из [`Anim::dims`]: декодеру они
/// нужны ДО первого кадра, а render_wallpaper узнаёт размер только из готового.
fn одолжить_слоты(state: &mut Config) {
    let Some((dw, dh)) = state.anim.as_ref().map(|a| a.dims) else { return };
    if dw == 0 || dh == 0 || !state.видно
        || !state.фоны.iter().any(|ф| ф.viewport.is_some())
    {
        // Без viewporter кадр надо ещё растянуть под экран, то есть через
        // буфер — тогда работает прежний путь с копированием.
        return;
    }
    if state.bg_dims != (dw, dh) || state.bg_slots.len() < 2 {
        let (Some(shm), Some(qh)) = (state.shm.as_ref(), state.qh.as_ref()) else { return };
        let Some(slots) = make_slots(shm, qh, dw, dh) else { return };
        state.bg_slots = slots;
        state.bg_dims = (dw, dh);
        state.bg_slot = 0;
        state.кадр_слота = None;
        state.scaled = None;
        state.слоты_у_декодера = vec![false; state.bg_slots.len()];
    }
    if state.слоты_у_декодера.len() != state.bg_slots.len() {
        state.слоты_у_декодера = vec![false; state.bg_slots.len()];
    }

    let показан = state.bg_slot;
    let есть_кадр = state.кадр_слота.map(|(i, _, _)| i);
    for i in 0..state.bg_slots.len() {
        if state.слоты_у_декодера[i] || Some(i) == есть_кадр {
            continue;
        }
        // Показанный слот держит композитор — он же убавит счётчик при release.
        if i == показан && state.bg_slots[i].занят.load(Ordering::Relaxed) != 0 {
            continue;
        }
        if state.bg_slots[i].занят.load(Ordering::Relaxed) != 0 {
            continue;
        }
        let Ok(fd) = state.bg_slots[i].fd.try_clone() else { continue };
        let Some(anim) = state.anim.as_ref() else { return };
        if anim.слоты.send(Заём { индекс: i, fd }).is_ok() {
            state.слоты_у_декодера[i] = true;
        }
    }
}

/// Снять то, что сейчас на экране, — с этого кадра пойдёт переход к новым
/// обоям.
///
/// Берём содержимое ПОКАЗАННОГО буфера, а не исходную картинку: во-первых, он
/// уже растянут под выход и переведён в BGRA (смешивать можно байт в байт),
/// во-вторых, у живых обоев исходного кадра как файла попросту не существует.
fn начать_переход(state: &mut Config) {
    let (w, h) = match state.outputs.first() {
        Some((_, w, h)) => (*w, *h),
        None => return,
    };
    // Первый запуск: буферов ещё нет, показывать переход не от чего.
    //
    // Раньше здесь стояла ещё и проверка bg_dims == (w, h). С viewporter она
    // отключала бы переход НАВСЕГДА: буфер теперь равен размеру кадра, а не
    // экрана, и совпадать с ним не обязан. Снимок берём какой есть и запоминаем
    // его размер — подгонит его render_wallpaper, один раз за переход.
    if w == 0 || h == 0 || state.bg_slots.is_empty() {
        state.fade = None;
        return;
    }
    let Some(slot) = state.bg_slots.get(state.bg_slot) else { return };
    let текущий = unsafe { std::slice::from_raw_parts(slot.ptr, slot.len) }.to_vec();
    state.fade = Some(Fade {
        from: текущий,
        dims: state.bg_dims,
        start: None,
        ждём: true,
    });
}

// ── Overlay rendering ────────────────────────────────────────────────────────

/// Готовит (один раз) постоянную пару буферов под меню и возвращает индекс
/// свободного. None — буферов нет или композитор ещё не отпустил ни один.
fn overlay_slot(state: &mut Config) -> Option<usize> {
    if state.ol_slots.len() < 2 {
        let (shm, qh) = (state.shm.as_ref()?, state.qh.as_ref()?);
        state.ol_slots = make_slots(shm, qh, ui_w(), ui_h())?;
        state.ol_slot = 0;
    }
    let next = take_free_slot(&state.ol_slots, state.ol_slot)?;
    state.ol_slot = next;
    Some(next)
}

/// Спрятать меню, НЕ размапливая поверхность.
///
/// Раньше здесь стоял `attach(None)` — по протоколу это размап, и после него
/// layer-поверхность возвращается в исходное состояние: следующий буфер
/// прикреплять нельзя, пока не придёт НОВЫЙ configure, а его никто не
/// запрашивал. Итог: меню открывалось ровно один раз, а на втором-третьем
/// круге вместе с ним пропадали и обои. Теперь рисуем полностью прозрачный
/// буфер того же размера и снимаем регион ввода, чтобы невидимое меню не
/// съедало клики по окнам под ним.
fn hide_overlay(state: &mut Config) -> bool {
    // До первого ack прикреплять буфер запрещено протоколом — за это
    // композитор убивает клиента («must ack the initial configure before
    // attaching buffer»), и dwall уходит в цикл перезапусков.
    //
    // Проверка стояла только в render_overlay, а сюда ведёт вторая дорога:
    // значок загрузки при ЗАКРЫТОМ меню (см. плашка_загрузки ниже). Пока
    // фоновая работа при старте была только у статичных обоев, поймать это
    // было почти нечем — картинка успевала загрузиться позже первого
    // configure. С живыми обоями окно стало шире: у них в фоне считается кадр
    // для плавного перехода, и спиннер зажигается в первые же миллисекунды,
    // ещё до ответа композитора.
    if !state.ol_configured { return false; }
    let Some(idx) = overlay_slot(state) else { return false };
    let Some(compositor) = state.compositor.clone() else { return false };
    let Some(qh) = state.qh.clone() else { return false };
    let Some(surface) = state.ol_surface.clone() else { return false };

    // Пустой регион ввода: клики проходят насквозь.
    let region = compositor.create_region(&qh, ());
    surface.set_input_region(Some(&region));
    region.destroy();

    // Меню спрятано, но загрузка идти может — тогда в пустом кадре остаётся
    // один значок. Иначе после Win+W на тяжёлых обоях (4K-PNG декодируется
    // сотни миллисекунд) экран просто ничего не отвечал: непонятно, поймало
    // нажатие или нет.
    let значок = state.спиннер_виден.then(|| плашка_загрузки(state.спиннер_фаза));

    let slot = &state.ol_slots[idx];
    match &значок {
        Some(pixels) => unsafe {
            let буфер = std::slice::from_raw_parts_mut(slot.ptr, slot.len);
            let сколько = pixels.len().min(буфер.len());
            буфер[..сколько].copy_from_slice(&pixels[..сколько]);
            буфер[сколько..].fill(0);
        },
        None => unsafe { std::slice::from_raw_parts_mut(slot.ptr, slot.len).fill(0) },
    }
    // Меню живёт ровно на одной поверхности — держатель у буфера один.
    slot.занят.store(1, Ordering::Relaxed);
    surface.attach(Some(&slot.buffer), 0, 0);
    surface.damage_buffer(0, 0, ui_w() as i32, ui_h() as i32);
    surface.commit();
    true
}

/// Рисует меню. `false` — не вышло (нет поверхности или оба буфера ещё у
/// композитора); тогда главный цикл оставляет пометку и повторит.
fn render_overlay(state: &mut Config) -> bool {
    if !state.ol_configured { return false; }
    if state.ol_surface.is_none() || state.shm.is_none()
        || state.qh.is_none() || state.compositor.is_none()
    {
        return false;
    }

    let buf_size = (ui_w() * ui_h() * 4) as usize;
    let mut pixels = vec![0u8; buf_size];

    // Подсветки: цель ставится тому, что под курсором, всё прочее гаснет.
    // Считаем ДО отрисовки, чтобы кадр и подсветка не расходились на кадр.
    обновить_подсветки(state);

    // Насколько меню на месте. `мягко` убирает рывок на старте: сама
    // экспонента трогается резко, и меню будто выстреливало.
    let t = ui::мягко(state.открытие.значение());
    let mut холст = ui::Холст::новый(&mut pixels, ui_w(), ui_h());
    холст.сдвиг_y = ((1.0 - t) * ВЫЕЗД).round() as i32;
    холст.общая_альфа = t;

    // ── Стекло ───────────────────────────────────────────────────────────────
    // Тень кладётся ПЕРВОЙ и снаружи формы: она отделяет меню от обоев там,
    // где яркость совпала, — без неё полупрозрачная полоса на светлых обоях
    // просто теряется.
    let верх = ui::Цвет::из_argb(ФОН_ВЕРХ);
    let низ = ui::Цвет::из_argb(ФОН_НИЗ);
    // Фон идёт ПЕРВЫМ и заменой: буфер только что обнулён, смешивать не с чем,
    // а это миллион пикселей на кадр. Тень кладётся следом — она рисуется
    // строго СНАРУЖИ формы и фон не задевает, так что порядок ей безразличен.
    холст.замена = true;
    холст.скругл_с(0, 0, ui_w(), ui_h(), CORNER, |доля| верх.между(низ, доля));
    холст.замена = false;
    холст.тень(0, 4, ui_w(), ui_h().saturating_sub(4), CORNER, 18, ui::Цвет::из_argb(ТЕНЬ));
    холст.кант(0, 0, ui_w(), ui_h(), CORNER, 1.0, ui::Цвет::из_argb(КАНТ));
    // Блик по верхней кромке — от него стекло читается выпуклым.
    холст.скругл(CORNER as i32, 0, ui_w().saturating_sub(CORNER * 2), 1, 0,
                 ui::Цвет::из_argb(БЛИК));

    // ── Вкладки ──────────────────────────────────────────────────────────────
    // Полоска под выбранной вкладкой ЕДЕТ к новой, а не перескакивает: цель
    // ставится здесь, а движение считает главный цикл.
    let места = tab_rects();
    let выбранная = ВКЛАДКИ.iter().position(|в| *в == state.вкладка).unwrap_or(0);
    state.подчёркивание.к(места[выбранная].0 as f32);
    for (i, (tx, ty)) in места.iter().enumerate() {
        let выбрана = i == выбранная;
        let подсветка = state.подсветки.значение(ui::Что::Вкладка(i));
        кнопка_полосы(&mut холст, *tx, *ty, ARROW, выбрана, подсветка);
        let цвет = цвет_значка(выбрана, подсветка);
        draw_tab_icon(&mut холст, ВКЛАДКИ[i], *tx, *ty, цвет);
    }
    {
        // Одна полоска на все вкладки — та самая, что едет.
        let x = state.подчёркивание.значение().round() as i32;
        холст.скругл(x, (места[0].1 + ARROW + 3) as i32, ARROW, 2, 1,
                     ui::Цвет::из_argb(SEL_COLOR));
    }

    // Кнопка поиска. Когда запрос задан, она подсвечена — иначе непонятно,
    // почему в сетке не «лучшее», а что-то другое.
    {
        let (sx, sy) = search_rect();
        let ищем = !state.запрос.is_empty();
        let подсветка = state.подсветки.значение(ui::Что::Поиск);
        кнопка_полосы(&mut холст, sx, sy, ARROW, ищем, подсветка);
        draw_search_icon(&mut холст, sx, sy, цвет_значка(ищем, подсветка));
        if ищем {
            холст.скругл(sx as i32, (sy + ARROW + 3) as i32, ARROW, 2, 1,
                         ui::Цвет::из_argb(SEL_COLOR));
        }
    }

    // Кнопка фильтров — только на сетевых вкладках: свои обои сужать нечем.
    if state.вкладка != Вкладка::Мои {
        let (fx, fy) = filter_rect();
        let сужено = state.фильтры.заданы();
        let подсветка = state.подсветки.значение(ui::Что::Фильтр);
        кнопка_полосы(&mut холст, fx, fy, ARROW, сужено, подсветка);
        draw_filter_icon(&mut холст, fx, fy, цвет_значка(сужено, подсветка));
        if сужено {
            холст.скругл(fx as i32, (fy + ARROW + 3) as i32, ARROW, 2, 1,
                         ui::Цвет::из_argb(SEL_COLOR));
        }
    }

    // ── Ряд источников ───────────────────────────────────────────────────────
    if источники_видны(state.вкладка) {
        let подписи = подписи_источников(state.вкладка);
        for (i, (x, y, ш)) in источник_rects(state.вкладка).into_iter().enumerate() {
            let выбран = источник_выбран(state, i);
            let подсветка = state.подсветки.значение(ui::Что::Источник(i));
            let фон = ui::Цвет::из_argb(if выбран { HOVER_COLOR } else { PLUS_COLOR })
                .между(ui::Цвет::из_argb(HOVER_COLOR), подсветка);
            холст.скругл(x as i32, y as i32, ш, ARROW, ARROW / 2, фон);
            if выбран {
                холст.кант(x as i32, y as i32, ш, ARROW, ARROW / 2, 1.2,
                           ui::Цвет::из_argb(SEL_COLOR));
            }
            холст.текст_по_центру(
                x as i32, y as i32, ш, ARROW,
                подписи[i], КЕГЛЬ,
                if выбран { ui::Начертание::Полужирное } else { ui::Начертание::Обычное },
                цвет_значка(выбран, подсветка),
            );
        }
    }

    // Значок загрузки — в ряду кнопок. Заводится и гаснет главным циклом
    // (см. спиннер_виден), здесь только рисуем.
    if state.спиннер_виден {
        let (sx, sy) = спиннер_место(state.вкладка);
        нарисовать_спиннер(&mut холст, sx, sy, ARROW, state.спиннер_фаза);
    }

    // Полоска состояния сети: серая — идёт запрос, красная — не вышло.
    if state.вкладка != Вкладка::Мои && (state.сетевая_работа || state.сетевая_ошибка) {
        let (x, y) = tab_rects()[0];
        let ширина = ui_w() - 2 * x;
        let цвет = if state.сетевая_ошибка { 0xFFBF5A5A } else { 0x80FFFFFF };
        холст.скругл(x as i32, (y + ARROW + 8) as i32, ширина, 2, 1,
                     ui::Цвет::из_argb(цвет));
    }

    // ── Карточки ─────────────────────────────────────────────────────────────
    let сетевая = state.вкладка != Вкладка::Мои;
    let n = state.wallpapers.len();
    let (кw, кh) = (карта_w(), карта_h());
    // Лента режется своим прямоугольником: при листании крайние карточки
    // наполовину за ним, и без обрезки они лезли бы на стрелки и за кромку
    // меню. Обрезку снимаем сразу после карточек — прокрутке и кнопкам она
    // не нужна.
    холст.обрезка = Some(лента_rect());
    let ячейки = ячейки_сейчас(state);
    for (idx, x, y) in ячейки {
        let подсветка = state.подсветки.значение(ui::Что::Карта(idx));
        let свои = !сетевая && idx < n;
        let плюс = !сетевая && idx >= n;

        // Карточка чуть приподнимается под курсором. Двигать её целиком
        // нельзя — уехала бы мимо своей области нажатия; поэтому «подъём»
        // делает не сдвиг, а тень под ней и более светлый фон.
        if подсветка > 0.01 {
            холст.тень(x, y as i32 + 2, кw, кh, CORNER,
                       (10.0 * подсветка) as u32,
                       ui::Цвет::из_argb(ТЕНЬ).с_прозрачностью(подсветка));
        }
        let основа = ui::Цвет::из_argb(if плюс { PLUS_COLOR } else { CARD_COLOR });
        let фон = основа.между(ui::Цвет::из_argb(HOVER_COLOR), подсветка);
        холст.скругл(x, y as i32, кw, кh, CORNER, фон);

        let миниатюра = if сетевая {
            state.сетевые_миниатюры.get(idx)
        } else if свои {
            state.thumbnails.get(idx)
        } else {
            None
        };
        if let Some(thumb) = миниатюра {
            draw_thumbnail(&mut холст, x, y as i32, кw, кh, thumb);
        }
        if плюс {
            // Плюс рисуется по МЕНЬШЕЙ стороне: он квадратный, а карточка нет,
            // и по ширине его перекладины разъехались бы за края.
            draw_plus(&mut холст, x + (кw - кh) as i32 / 2, y as i32, кh,
                      ui::Цвет::из_argb(ТЕКСТ_ТИХО)
                          .между(ui::Цвет::из_argb(ТЕКСТ_ЯРКО), подсветка));
        }

        // Нынешние обои обведены кантом во всю карточку, а не помечены точкой
        // в углу: на карточке 568×320 точка теряется, а кант виден с другого
        // конца ленты.
        if свои && idx == state.current {
            нарисовать_кант(&mut холст, x, y as i32, кw, кh, ui::Цвет::из_argb(SEL_COLOR));
        } else if подсветка > 0.01 {
            нарисовать_кант(&mut холст, x, y as i32, кw, кh,
                            ui::Цвет::из_argb(SEL_COLOR).с_прозрачностью(подсветка));
        }

        // Крестик удаления — только у своих обоев и только под курсором,
        // чтобы лента не пестрела крестиками. Проявляется вместе с подсветкой.
        if свои && подсветка > 0.01 {
            let dx = x + (кw - DEL_SIZE - 8) as i32;
            let dy = y as i32 + 8;
            let крестик = state.подсветки.значение(ui::Что::Крестик(idx));
            холст.скругл(dx, dy, DEL_SIZE, DEL_SIZE, DEL_SIZE / 2,
                         ui::Цвет::из_argb(DEL_BG)
                             .между(ui::Цвет::из_argb(0xE6C0392B), крестик)
                             .с_прозрачностью(подсветка));
            let было = холст.общая_альфа;
            холст.общая_альфа = было * подсветка;
            draw_cross(&mut холст, dx, dy, DEL_SIZE);
            холст.общая_альфа = было;
        }
    }
    холст.обрезка = None;

    нарисовать_прокрутку(
        &mut холст,
        state.лента.значение(),
        &|что| state.подсветки.значение(что),
        предел_прокрутки(state),
        карточек(state),
    );

    // RGBA → BGRA
    for chunk in pixels.chunks_exact_mut(4) { chunk.swap(0, 2); }
    отдать_меню(state, pixels, buf_size)
}

/// Фон кнопки в верхней полосе: выбранная светлее, наведённая — плавно между.
fn кнопка_полосы(холст: &mut ui::Холст, x: u32, y: u32, сторона: u32, выбрана: bool, подсветка: f32) {
    let основа = ui::Цвет::из_argb(if выбрана { HOVER_COLOR } else { CARD_COLOR });
    let фон = основа.между(ui::Цвет::из_argb(HOVER_COLOR), подсветка);
    холст.скругл(x as i32, y as i32, сторона, сторона, УГОЛ_КНОПКИ, фон);
    if выбрана {
        холст.кант(x as i32, y as i32, сторона, сторона, УГОЛ_КНОПКИ, 1.0,
                   ui::Цвет::из_argb(КАНТ));
    }
}

/// Цвет значка или подписи: у выбранного яркий, у прочего приглушённый, под
/// курсором — плавно между ними.
fn цвет_значка(выбран: bool, подсветка: f32) -> ui::Цвет {
    let тихо = ui::Цвет::из_argb(ТЕКСТ_ТИХО);
    let ярко = ui::Цвет::из_argb(ТЕКСТ_ЯРКО);
    if выбран { ярко } else { тихо.между(ярко, подсветка) }
}

/// Расставить цели подсветок по тому, где сейчас курсор.
///
/// Одним местом на всё меню: раньше наведение спрашивалось прямо в отрисовке
/// (`is_hover`) и было мгновенным — плавным его не сделать, не собрав все
/// элементы в одном списке.
fn обновить_подсветки(state: &mut Config) {
    let под_курсором = что_под_курсором(state);
    state.подсветки.погасить_кроме(под_курсором);
    if let Some(что) = под_курсором {
        state.подсветки.к(что, 1.0);
        // Карточка под крестиком светится вместе с ним: иначе, наведясь на
        // крестик, человек терял из виду, какую именно карточку удаляет.
        if let ui::Что::Крестик(i) = что {
            state.подсветки.к(ui::Что::Карта(i), 1.0);
        }
    }
}

/// Что именно сейчас под курсором. Порядок проверок тот же, что у попаданий
/// в [`build_ui_layout`]: сначала мелкое поверх, потом крупное под ним.
fn что_под_курсором(state: &Config) -> Option<ui::Что> {
    if !state.overlay_visible {
        return None;
    }
    let (cx, cy) = (state.cursor_x, state.cursor_y);
    if cx < 0.0 || cy < 0.0 {
        return None;
    }
    let (cx, cy) = (cx as u32, cy as u32);
    let внутри = |x: u32, y: u32, w: u32, h: u32| cx >= x && cx < x + w && cy >= y && cy < y + h;

    for (i, (tx, ty)) in tab_rects().iter().enumerate() {
        if внутри(*tx, *ty, ARROW, ARROW) {
            return Some(ui::Что::Вкладка(i));
        }
    }
    let (sx, sy) = search_rect();
    if внутри(sx, sy, ARROW, ARROW) {
        return Some(ui::Что::Поиск);
    }
    if state.вкладка != Вкладка::Мои {
        let (fx, fy) = filter_rect();
        if внутри(fx, fy, ARROW, ARROW) {
            return Some(ui::Что::Фильтр);
        }
    }
    if источники_видны(state.вкладка) {
        for (i, (x, y, ш)) in источник_rects(state.вкладка).into_iter().enumerate() {
            if внутри(x, y, ш, ARROW) {
                return Some(ui::Что::Источник(i));
            }
        }
    }
    if предел_прокрутки(state) > 0 {
        let [(лx, лy), (пx, пy)] = arrow_rects();
        if внутри(лx, лy, ARROW, ARROW) {
            return Some(ui::Что::Стрелка(false));
        }
        if внутри(пx, пy, ARROW, ARROW) {
            return Some(ui::Что::Стрелка(true));
        }
    }
    // Карточки — по той же дробной позиции, по какой они нарисованы, и только
    // внутри прямоугольника ленты: половину уехавшей карточки видно не
    // полностью, и «наводиться» на её невидимую часть нельзя.
    let (кw, кh) = (карта_w(), карта_h());
    let свои = state.вкладка == Вкладка::Мои;
    let n = state.wallpapers.len();
    let (лx, лy, лш, лв) = лента_rect();
    if (cx as i32) < лx || (cx as i32) >= лx + лш as i32
        || (cy as i32) < лy || (cy as i32) >= лy + лв as i32
    {
        return None;
    }
    let внутри_зн = |x: i32, y: i32, w: u32, h: u32| {
        (cx as i32) >= x && (cx as i32) < x + w as i32
            && (cy as i32) >= y && (cy as i32) < y + h as i32
    };
    for (idx, x, y) in ячейки_сейчас(state) {
        if свои
            && idx < n
            && внутри_зн(x + (кw - DEL_SIZE - 8) as i32, y as i32 + 8, DEL_SIZE, DEL_SIZE)
        {
            return Some(ui::Что::Крестик(idx));
        }
        if внутри_зн(x, y as i32, кw, кh) {
            return Some(ui::Что::Карта(idx));
        }
    }
    None
}

/// Полоса прокрутки и стрелки. Рисуются одинаково на всех вкладках, поэтому
/// живут отдельно: раньше эта арифметика была вписана прямо в render_overlay,
/// и сетевой сетке пришлось бы её дублировать.
fn нарисовать_прокрутку(
    холст: &mut ui::Холст,
    // Дробная позиция ленты — та же, по которой нарисованы карточки. Целое
    // значение показывало бы бегунок скачками, пока лента едет плавно.
    scroll: f32,
    // Подсветка отдельным замыканием, а не через `&Config`: так эту же
    // отрисовку зовёт снимок ленты из тестов, у которого никакого Config нет.
    подсветка: &dyn Fn(ui::Что) -> f32,
    макс: u32,
    всего_карточек: usize,
) {
    // Стрелки рисуем ВСЕГДА, даже когда листать некуда: у ленты они стоят по
    // краям карточек и держат её форму. Погашенная стрелка честно показывает,
    // что дальше ничего нет, — исчезнувшая просто оставляет дыру.
    let [(лев_x, лев_y), (прав_x, прав_y)] = arrow_rects();
    for (ax, ay, вправо, доступна) in [
        (лев_x, лев_y, false, scroll > 0.01),
        (прав_x, прав_y, true, scroll < макс as f32 - 0.01),
    ] {
        let п = подсветка(ui::Что::Стрелка(вправо));
        let фон = ui::Цвет::из_argb(CARD_COLOR).между(ui::Цвет::из_argb(HOVER_COLOR), п);
        холст.скругл(ax as i32, ay as i32, ARROW, ARROW, ARROW / 2, фон);
        // Недоступная стрелка гасится не другим цветом, а прозрачностью: так
        // она заведомо тише всего, что рядом, при любой яркости обоев.
        let цвет = ui::Цвет::из_argb(ТЕКСТ_ЯРКО)
            .с_прозрачностью(if доступна { 1.0 } else { 0.32 });
        draw_arrow_h(холст, ax, ay, ARROW, вправо, цвет);
    }

    if макс == 0 { return; }

    // Полоса прокрутки — ПОД лентой и во всю её ширину: лента листается вбок,
    // и вертикальная полоса у правого поля показывала бы движение поперёк
    // того, которое видно.
    let ширина_ленты = видно_карт() * карта_w() + (видно_карт() - 1) * GAP;
    let track_x = лента_x() as i32;
    let track_y = (лента_y() + карта_h() + GAP + 6) as i32;
    холст.скругл(track_x, track_y, ширина_ленты, SB_W, SB_W / 2,
                 ui::Цвет::из_argb(SB_COLOR));

    // Бегунок: доля видимой части от всей ленты.
    let всего = рядов(всего_карточек).max(1);
    let ширина = (ширина_ленты * видно_карт() / всего).max(32).min(ширина_ленты);
    let свободно = ширина_ленты - ширина;
    let смещение = (свободно as f32 * scroll / макс as f32).round().max(0.0) as u32;
    холст.скругл(track_x + смещение as i32, track_y, ширина, SB_W, SB_W / 2,
                 ui::Цвет::из_argb(SB_THUMB_COLOR));
}

/// Треугольник стрелки, смотрящий влево или вправо. Та же арифметика, что у
/// `draw_arrow`, только оси переставлены: у ленты листают вбок.
fn draw_arrow_h(холст: &mut ui::Холст, x: u32, y: u32, size: u32, вправо: bool, цвет: ui::Цвет) {
    let половина = size / 2;
    for col in 0..половина {
        let высота = (половина - col) * 2;
        if высота == 0 { continue; }
        let cx = if вправо { x + size / 4 + col } else { x + size - size / 4 - col };
        let cy = y + size / 2 - высота / 2;
        холст.скругл(cx as i32, cy as i32, 1, высота, 0, цвет);
    }
}

/// Отдать готовый кадр меню композитору. `false` — оба буфера ещё заняты,
/// главный цикл повторит.
fn отдать_меню(state: &mut Config, pixels: Vec<u8>, buf_size: usize) -> bool {
    let Some(idx) = overlay_slot(state) else { return false };
    let Some(compositor) = state.compositor.clone() else { return false };
    let Some(qh) = state.qh.clone() else { return false };
    let Some(surface) = state.ol_surface.clone() else { return false };

    let slot = &state.ol_slots[idx];
    unsafe { std::slice::from_raw_parts_mut(slot.ptr, slot.len) }
        .copy_from_slice(&pixels[..buf_size]);
    // Регион ввода — на всю площадь, пока меню открыто. Пока оно ЗАКРЫВАЕТСЯ
    // (флаг уже снят, картинка ещё уезжает), регион пустой: иначе те две
    // десятых секунды, что доигрывается анимация, клики уходили бы в
    // невидимое меню вместо окна под ним.
    let region = compositor.create_region(&qh, ());
    if state.overlay_visible {
        region.add(0, 0, ui_w() as i32, ui_h() as i32);
    }
    surface.set_input_region(Some(&region));
    region.destroy();
    // Меню живёт ровно на одной поверхности — держатель у буфера один.
    slot.занят.store(1, Ordering::Relaxed);
    surface.attach(Some(&slot.buffer), 0, 0);
    surface.damage_buffer(0, 0, ui_w() as i32, ui_h() as i32);
    surface.commit();
    true
}

