impl Dispatch<ZwlrLayerSurfaceV1, ()> for Config {
    fn event(
        state: &mut Self,
        surface: &ZwlrLayerSurfaceV1,
        event: zwlr_layer_surface_v1::Event,
        _: &(),
        _conn: &Connection,
        _qh: &QueueHandle<Self>,
    ) {
        match event {
            zwlr_layer_surface_v1::Event::Configure { serial, width, height } => {
                surface.ack_configure(serial);
                let id = surface.id();
                // Configure приходит на КОНКРЕТНУЮ поверхность — по ней и
                // находим её фон. Размер запоминаем свой у каждого монитора:
                // раньше он писался в outputs.first() без разбора, то есть
                // configure второго экрана затирал размер первого.
                let фон = state.фоны.iter_mut().find(|ф| ф.layer.id() == id);
                if let Some(фон) = фон {
                    // Размер обоев берём из configure, а не из wl_output.Mode:
                    // Mode отдаёт физические пиксели режима, а layer-shell —
                    // логический размер, который композитор реально отвёл. При
                    // scale != 1 это разные числа, и буфер разъезжался бы с экраном.
                    let mut changed = !фон.configured;
                    if width > 0 && height > 0 && фон.размер != (width, height) {
                        фон.размер = (width, height);
                        changed = true;
                    }
                    фон.configured = true;
                    // Первый ack — рисуем в любом случае: до него мы не имели
                    // права трогать буфер, значит фон ещё пуст.
                    if changed { render_wallpaper(state); }
                } else if state.ol_layer.as_ref().map(|l| l.id()) == Some(id) {
                    state.ol_configured = true;
                    if state.overlay_visible { render_overlay(state); }
                }
            }
            // Композитор снёс поверхность (выход отключили, шелл закрылся).
            // Держать на неё ссылку нельзя: следующий commit — протокольная
            // ошибка и дисконнект. Обнуляем, setup_layers создаст заново.
            zwlr_layer_surface_v1::Event::Closed => {
                let id = surface.id();
                if let Some(i) = state.фоны.iter().position(|ф| ф.layer.id() == id) {
                    // Уносим фон целиком: и layer, и поверхность, и viewport.
                    // Если выход просто отключили, его wl_output уйдёт следом и
                    // второй раз фон никто не заведёт; если поверхность снёс сам
                    // шелл — её пересоздаст setup_layers из главного цикла.
                    let фон = state.фоны.remove(i);
                    if let Some(vp) = фон.viewport.as_ref() { vp.destroy(); }
                    фон.layer.destroy();
                    фон.surface.destroy();
                } else if state.ol_layer.as_ref().map(|l| l.id()) == Some(id) {
                    state.ol_layer = None;
                    state.ol_surface = None;
                    state.ol_configured = false;
                    state.overlay_visible = false;
                }
            }
            _ => {}
        }
    }
}

