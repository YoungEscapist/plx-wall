/// Глобал linux-dmabuf: копим объявленные композитором сочетания
/// «формат + модификатор».
///
/// Версия 3 шлёт их событиями `modifier` сразу после привязки. Устаревшее
/// `format` (версия 1) игнорируем: модификатора в нём нет, а без модификатора
