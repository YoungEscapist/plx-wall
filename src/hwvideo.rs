//! Аппаратное декодирование живых обоев прямо в dmabuf — без единого
//! копирования пикселей через процессор.
//!
//! ## Зачем это вообще
//!
//! Раньше живые обои работали так: dwall запускал `ffmpeg`, тот декодировал
//! ролик программно, переводил кадр в BGRA и гнал сырые пиксели в трубу, а
//! dwall перекладывал их в общую память. Замер 15.08.2026 на этой машине
//! (i7-10510U, экран 3840×2160, обои h264 2560×1440@60):
//!
//! | этап | цена на 5 с видео |
//! |---|---|
//! | программный декод h264 | 9.8 с CPU |
//! | перевод nv12 → BGRA | 4.9 с CPU |
//! | запись в трубу | 1.3 с CPU |
//! | **итого у ffmpeg** | **15.7 с CPU (~330% ядра)** |
//! | перекладывание трубы в shm у dwall | ещё ~54% ядра |
//!
//! Плюс сам композитор каждый кадр заливал 14.7 МБ общей памяти в текстуру.
//! Итого живые обои съедали больше трёх ядер из четырёх — на ноутбуке с
//! пассивным теплопакетом 15 Вт.
//!
//! Ключевой замер, ради которого всё и переписано: тот же ролик, декодированный
//! видеокартой и НЕ выгруженный в системную память, стоит **0.65 с CPU** на те
//! же 5 с видео — в 24 раза дешевле. Всю цену создавала не работа декодера, а
//! перетаскивание пикселей туда-обратно через процессор.
//!
//! ## Как теперь
//!
//! Кадр вообще не покидает видеопамять:
//!
//! ```text
//!   libavcodec + VAAPI ──> VASurface ──> av_hwframe_map ──> dmabuf-fd
//!                                                             │
//!                            zwp_linux_dmabuf_v1 ─────────────┘
//!                                     └──> wl_buffer ──> композитор показывает
//! ```
//!
//! Процессор трогает только заголовки пакетов и дескрипторы — самих пикселей
//! он не видит ни разу.
//!
//! ## Чего здесь сознательно нет
//!
//! Программного отката: если видеокарта не может (нет VAAPI, экзотический
//! кодек), модуль честно возвращает `None`, и вызывающий остаётся на старом
//! пути через процесс ffmpeg (см. `start_anim`). Смысл в том, чтобы обои
//! работали везде, а дёшево — там, где железо это умеет.

use crate::ffmpeg_sys as ff;
use std::collections::HashSet;
use std::ffi::CString;
use std::os::fd::{FromRawFd, OwnedFd};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::mpsc::{sync_channel, Receiver, SyncSender};
use std::sync::Arc;
use std::time::Duration;

/// Одна плоскость кадра в dmabuf: чей файловый дескриптор, с каким сдвигом и
/// шагом строки лежат её байты.
pub struct Плоскость {
    pub fd: OwnedFd,
    pub сдвиг: u32,
    pub шаг: u32,
}

/// Описание нового кадра-поверхности, которого главный цикл ещё не видел.
///
/// Приходит РОВНО ОДИН РАЗ на каждую поверхность из пула декодера: VAAPI
/// крутит десяток-другой поверхностей по кругу, и заводить на каждый кадр новый
/// `wl_buffer` (а это протокольные запросы и dup дескрипторов 60 раз в секунду)
/// незачем — главный цикл кэширует буферы по `surface_id`.
pub struct ОписаниеПоверхности {
    pub surface_id: usize,
    pub ширина: u32,
    pub высота: u32,
    /// Код формата DRM (`DRM_FORMAT_*`), обычно NV12 — в нём VAAPI и декодирует.
    pub fourcc: u32,
    pub модификатор: u64,
    pub плоскости: Vec<Плоскость>,
}

/// Кадр, готовый к показу.
pub struct ГотовыйКадр {
    /// Какую поверхность показывать.
    pub surface_id: usize,
    /// Заполнено только для поверхности, которую главный цикл видит впервые.
    pub описание: Option<ОписаниеПоверхности>,
    /// Сколько этот кадр должен провисеть на экране.
    pub шаг: Duration,
    /// Держит поверхность занятой, пока кадр на экране.
    ///
    /// Пока эта штука жива, libavcodec не отдаст поверхность обратно в пул и не
    /// перезапишет её следующим кадром. Уронить её нужно РОВНО тогда, когда
    /// композитор пришлёт `wl_buffer::release`, — иначе декодер нарисует поверх
    /// того, что прямо сейчас на экране, и обои пойдут рябью.
    pub держатель: Держатель,
}

/// Ссылка на кадр libavcodec, продлевающая жизнь видеопамяти под ним.
///
/// Своих методов нет: вся её работа — существовать, пока кадр на экране, и
/// освободить поверхность в `Drop`.
pub struct Держатель {
    frame: *mut ff::AVFrame,
    /// Отображение в DRM_PRIME. Держит те самые dmabuf-дескрипторы; умереть
    /// должно вместе с кадром, а не раньше.
    mapped: *mut ff::AVFrame,
}

// Указатели ведут на кадры libavcodec, которые никто, кроме владельца
// Держателя, не трогает: поток декодера отдал их насовсем вместе со ссылкой.
unsafe impl Send for Держатель {}

impl Drop for Держатель {
    fn drop(&mut self) {
        unsafe {
            if !self.mapped.is_null() {
                ff::av_frame_free(&mut self.mapped);
            }
            if !self.frame.is_null() {
                ff::av_frame_free(&mut self.frame);
            }
        }
    }
}

/// Живой аппаратный декодер обоев.
pub struct HwВидео {
    /// Кадры от потока декодера. Ёмкость 1 и есть тормоз всего конвейера: пока
    /// главный цикл не забрал кадр, декодер стоит на `send` и не тратит ничего.
    /// Обои закрыли полноэкранным окном — главный цикл перестал забирать кадры,
    /// и декодер уснул сам, без единой строчки про «поставить на паузу».
    pub rx: Receiver<ГотовыйКадр>,
    /// Размер кадра. Нужен заранее — под него настраивается viewport.
    pub размер: (u32, u32),
    /// Самый первый кадр: он уже забран из канала при запуске (см. `запустить`)
    /// и ждёт своей очереди. Главный цикл обязан показать его прежде, чем
    /// брать что-то из `rx`, иначе ролик начнётся со второго кадра.
    pub первый: Option<ГотовыйКадр>,
    /// Просьба потоку декодера закончиться (обои сменили).
    стоп: Arc<AtomicBool>,
}

impl Drop for HwВидео {
    fn drop(&mut self) {
        self.стоп.store(true, Ordering::SeqCst);
        // Поток может стоять на `send` в канал, который мы сейчас закроем;
        // `send` вернёт ошибку, поток увидит её и выйдет сам.
    }
}

/// Собрать код формата DRM из четырёх букв (`DRM_FORMAT_*`).
const fn fourcc(a: u8, b: u8, c: u8, d: u8) -> u32 {
    (a as u32) | ((b as u32) << 8) | ((c as u32) << 16) | ((d as u32) << 24)
}

const DRM_FORMAT_R8: u32 = fourcc(b'R', b'8', b' ', b' ');
const DRM_FORMAT_GR88: u32 = fourcc(b'G', b'R', b'8', b'8');
const DRM_FORMAT_NV12: u32 = fourcc(b'N', b'V', b'1', b'2');

/// Бит «ближайший сосед» в маске флагов `sws_getContext`.
///
/// Задан числом СОЗНАТЕЛЬНО. В ffmpeg 9 старые макросы `SWS_POINT` и прочие из
/// публичных заголовков убрали, а появившийся вместо них `SwsScaler` — это
/// порядковые номера (POINT там 3), и в маску флагов они не годятся: 3 читается
/// как два алгоритма сразу, и swscale отвечает «Exactly one scaler algorithm
/// must be chosen, got 3» и не создаёт контекст (проверено 15.08.2026).
/// Сама же маска в swscale не менялась двадцать лет и стабильна по ABI.
///
/// Выбор алгоритма здесь всё равно ни на что не влияет: размер источника и
/// приёмника совпадают, масштабирования нет, и swscale идёт своим отдельным
/// путём для чистой смены формата.
const SWS_POINT: i32 = 0x10;

/// Формат, в котором просим кадры у декодера.
///
/// Вызывается libavcodec'ом, когда тот выбирает, куда складывать кадры.
/// Предпочитаем VAAPI — тогда кадр рождается сразу в видеопамяти и дальше
/// только отображается в dmabuf. Нет его в списке (частый случай — AV1 на
/// Comet Lake, где аппаратного декодера AV1 нет вовсе) — соглашаемся на
/// программный формат: кадр мы потом сами загрузим в поверхность (см.
/// [`Загрузка`]), и это всё равно втрое дешевле, чем гнать BGRA через трубу.
unsafe extern "C" fn выбрать_формат(
    _ctx: *mut ff::AVCodecContext,
    форматы: *const ff::AVPixelFormat,
) -> ff::AVPixelFormat {
    unsafe {
        let mut п = форматы;
        while *п != ff::AVPixelFormat_AV_PIX_FMT_NONE {
            if *п == ff::AVPixelFormat_AV_PIX_FMT_VAAPI {
                return ff::AVPixelFormat_AV_PIX_FMT_VAAPI;
            }
            п = п.add(1);
        }
        // Первый в списке — то, что декодер предлагает сам (для AV1 это
        // yuv420p от dav1d).
        *форматы
    }
}

/// Расшифровать код возврата libav в человеческий текст.
fn ошибка(код: i32) -> String {
    let mut буфер = [0i8; 256];
    unsafe {
        if ff::av_strerror(код, буфер.as_mut_ptr(), буфер.len()) < 0 {
            return format!("код {код}");
        }
        std::ffi::CStr::from_ptr(буфер.as_ptr()).to_string_lossy().into_owned()
    }
}

/// Загрузка программно декодированного кадра в поверхность видеокарты.
///
/// Нужна там, где аппаратного декодера нет. Смысл в том, чтобы НЕ переводить
/// кадр в BGRA: показывать его всё равно будет композитор, и NV12 он читает
/// сам. Мы лишь перекладываем полуплоскость цветности (yuv420p → nv12, это
/// перетасовка 0.5 байта на пиксель, а не полноценный пересчёт цвета) и
/// отдаём кадр видеокарте.
///
/// Замер 15.08.2026 на AV1 1280×720, 300 кадров: декод+BGRA+выдача — 3.65 с
/// CPU, декод+загрузка NV12 — 1.79 с. При этом отпадает и перекладывание трубы
/// на стороне dwall, и заливка shm в текстуру на стороне композитора.
struct Загрузка {
    /// Пул поверхностей VAAPI, в которые кладём кадры.
    frames: *mut ff::AVBufferRef,
    /// Перекладчик yuv420p → nv12. Нужен потому, что поверхность у нас NV12, а
    /// программные декодеры отдают планарный yuv420p.
    sws: *mut ff::SwsContext,
    /// Промежуточный кадр в NV12: сюда пишет sws, отсюда читает загрузка.
    nv12: *mut ff::AVFrame,
    /// Формат и размер, под которые всё это настроено. Сменились (такого быть
    /// не должно, но ролики бывают всякие) — пересоздаём.
    настроено: (ff::AVPixelFormat, i32, i32),
}

impl Drop for Загрузка {
    fn drop(&mut self) {
        unsafe {
            if !self.nv12.is_null() {
                ff::av_frame_free(&mut self.nv12);
            }
            if !self.sws.is_null() {
                ff::sws_freeContext(self.sws);
            }
            if !self.frames.is_null() {
                ff::av_buffer_unref(&mut self.frames);
            }
        }
    }
}

impl Загрузка {
    /// Собрать пул поверхностей и перекладчик под конкретный кадр.
    unsafe fn новая(
        hw_device: *mut ff::AVBufferRef,
        формат: ff::AVPixelFormat,
        w: i32,
        h: i32,
    ) -> Option<Загрузка> {
        unsafe {
            // ── Пул поверхностей ────────────────────────────────────────────
            let frames = ff::av_hwframe_ctx_alloc(hw_device);
            if frames.is_null() {
                return None;
            }
            let ctx = (*frames).data as *mut ff::AVHWFramesContext;
            (*ctx).format = ff::AVPixelFormat_AV_PIX_FMT_VAAPI;
            (*ctx).sw_format = ff::AVPixelFormat_AV_PIX_FMT_NV12;
            (*ctx).width = w;
            (*ctx).height = h;
            // Пул должен быть заметно больше, чем кадров «в полёте»: один
            // показывается, один готовится, плюс запас на задержку release от
            // композитора. Меньше — и загрузка начнёт ждать освобождения.
            (*ctx).initial_pool_size = 8;
            let mut frames = frames;
            let код = ff::av_hwframe_ctx_init(frames);
            if код < 0 {
                eprintln!("dwall: пул поверхностей не создался: {}", ошибка(код));
                ff::av_buffer_unref(&mut frames);
                return None;
            }

            // ── Перекладчик в NV12 ──────────────────────────────────────────
            let sws = ff::sws_getContext(
                w, h, формат,
                w, h, ff::AVPixelFormat_AV_PIX_FMT_NV12,
                SWS_POINT,
                std::ptr::null_mut(), std::ptr::null_mut(), std::ptr::null_mut(),
            );
            if sws.is_null() {
                ff::av_buffer_unref(&mut frames);
                return None;
            }

            let nv12 = ff::av_frame_alloc();
            if nv12.is_null() {
                ff::sws_freeContext(sws);
                ff::av_buffer_unref(&mut frames);
                return None;
            }
            (*nv12).format = ff::AVPixelFormat_AV_PIX_FMT_NV12;
            (*nv12).width = w;
            (*nv12).height = h;
            if ff::av_frame_get_buffer(nv12, 0) < 0 {
                ff::av_frame_free(&mut { nv12 });
                ff::sws_freeContext(sws);
                ff::av_buffer_unref(&mut frames);
                return None;
            }

            Some(Загрузка { frames, sws, nv12, настроено: (формат, w, h) })
        }
    }

    /// Переложить программный кадр в поверхность видеокарты.
    ///
    /// Возвращает НОВЫЙ кадр формата VAAPI; исходный остаётся на совести
    /// вызывающего.
    unsafe fn загрузить(&mut self, кадр: *mut ff::AVFrame) -> Option<*mut ff::AVFrame> {
        unsafe {
            // yuv420p → nv12.
            let выс = ff::sws_scale(
                self.sws,
                (*кадр).data.as_ptr() as *const *const u8,
                (*кадр).linesize.as_ptr(),
                0,
                (*кадр).height,
                self.nv12.as_ref()?.data.as_ptr() as *const *mut u8,
                self.nv12.as_ref()?.linesize.as_ptr(),
            );
            if выс <= 0 {
                eprintln!("dwall: перевод в nv12 не удался (строк {выс})");
                return None;
            }

            // Берём свободную поверхность из пула и заливаем в неё кадр.
            let поверхность = ff::av_frame_alloc();
            if поверхность.is_null() {
                return None;
            }
            let код = ff::av_hwframe_get_buffer(self.frames, поверхность, 0);
            if код < 0 {
                eprintln!("dwall: поверхность не выдалась: {}", ошибка(код));
                ff::av_frame_free(&mut { поверхность });
                return None;
            }
            let код = ff::av_hwframe_transfer_data(поверхность, self.nv12, 0);
            if код < 0 {
                eprintln!("dwall: кадр не залился в поверхность: {}", ошибка(код));
                ff::av_frame_free(&mut { поверхность });
                return None;
            }
            Some(поверхность)
        }
    }
}

/// Всё, что нужно потоку декодера. Собирается в главном потоке, чтобы о
/// неудаче (нет VAAPI, битый файл) узнать сразу и успеть откатиться на ffmpeg.
struct Открытое {
    fmt: *mut ff::AVFormatContext,
    codec: *mut ff::AVCodecContext,
    hw_device: *mut ff::AVBufferRef,
    поток: i32,
    размер: (u32, u32),
    шаг: Duration,
}

// Контексты уезжают в поток декодера целиком и больше нигде не используются.
unsafe impl Send for Открытое {}

impl Drop for Открытое {
    fn drop(&mut self) {
        unsafe {
            if !self.codec.is_null() {
                ff::avcodec_free_context(&mut self.codec);
            }
            if !self.fmt.is_null() {
                ff::avformat_close_input(&mut self.fmt);
            }
            if !self.hw_device.is_null() {
                ff::av_buffer_unref(&mut self.hw_device);
            }
        }
    }
}

/// Открыть файл и поднять аппаратный декодер. `None` — эта машина или этот
/// ролик так не умеют, надо на запасной путь.
fn открыть(путь: &str, устройство: &str) -> Option<Открытое> {
    let c_путь = CString::new(путь).ok()?;
    let c_устройство = CString::new(устройство).ok()?;

    unsafe {
        // Ругань libav в stderr нам не нужна: неудача здесь — штатная ветка,
        // после которой обои спокойно поедут через ffmpeg. Но когда что-то
        // идёт не так, без его сообщений не разобраться — открываем их по
        // DWALL_FFMPEG_LOG=1.
        ff::av_log_set_level(if std::env::var_os("DWALL_FFMPEG_LOG").is_some() {
            ff::AV_LOG_VERBOSE as i32
        } else {
            ff::AV_LOG_FATAL as i32
        });

        let mut fmt: *mut ff::AVFormatContext = std::ptr::null_mut();
        if ff::avformat_open_input(
            &mut fmt, c_путь.as_ptr(), std::ptr::null_mut(), std::ptr::null_mut(),
        ) < 0
        {
            return None;
        }
        // С этого места любой ранний выход обязан закрыть fmt — поэтому дальше
        // всё живёт в `Открытое`, а его Drop прибирает за нами.
        let mut открытое = Открытое {
            fmt,
            codec: std::ptr::null_mut(),
            hw_device: std::ptr::null_mut(),
            поток: -1,
            размер: (0, 0),
            шаг: Duration::from_millis(16),
        };

        if ff::avformat_find_stream_info(открытое.fmt, std::ptr::null_mut()) < 0 {
            return None;
        }

        let mut декодер: *const ff::AVCodec = std::ptr::null_mut();
        let поток = ff::av_find_best_stream(
            открытое.fmt,
            ff::AVMediaType_AVMEDIA_TYPE_VIDEO,
            -1, -1,
            &mut декодер,
            0,
        );
        if поток < 0 || декодер.is_null() {
            return None;
        }
        открытое.поток = поток;

        // ── Устройство ──────────────────────────────────────────────────────
        if ff::av_hwdevice_ctx_create(
            &mut открытое.hw_device,
            ff::AVHWDeviceType_AV_HWDEVICE_TYPE_VAAPI,
            c_устройство.as_ptr(),
            std::ptr::null_mut(),
            0,
        ) < 0
        {
            // Нет драйвера libva (на NixOS это hardware.graphics.extraPackages)
            // или карта не умеет — штатный откат.
            return None;
        }

        // ── Декодер ─────────────────────────────────────────────────────────
        открытое.codec = ff::avcodec_alloc_context3(декодер);
        if открытое.codec.is_null() {
            return None;
        }
        let поток_ptr = *(*открытое.fmt).streams.add(поток as usize);
        if ff::avcodec_parameters_to_context(открытое.codec, (*поток_ptr).codecpar) < 0 {
            return None;
        }
        (*открытое.codec).hw_device_ctx = ff::av_buffer_ref(открытое.hw_device);
        (*открытое.codec).get_format = Some(выбрать_формат);
        // Кадры отдаёт видеокарта — потоки на процессоре не нужны и только
        // добавили бы переключений контекста.
        (*открытое.codec).thread_count = 1;

        if ff::avcodec_open2(открытое.codec, декодер, std::ptr::null_mut()) < 0 {
            // Сюда попадаем в том числе когда выбрать_формат не нашёл VAAPI:
            // кодек этой карте не по зубам (частый случай — AV1 на старом
            // железе). Обои от этого не пропадут, просто поедут дороже.
            return None;
        }

        открытое.размер = (
            (*открытое.codec).width.max(0) as u32,
            (*открытое.codec).height.max(0) as u32,
        );
        if открытое.размер.0 == 0 || открытое.размер.1 == 0 {
            return None;
        }

        // ── Темп ────────────────────────────────────────────────────────────
        // Берём avg_frame_rate, а при его отсутствии r_frame_rate. Как и
        // раньше, безумные значения из битых метаданных подрезаем: 1000 к/с —
        // это не обои, а мусор в заголовке.
        let частота = {
            let avg = (*поток_ptr).avg_frame_rate;
            let r = (*поток_ptr).r_frame_rate;
            let взять = |v: ff::AVRational| {
                (v.den > 0 && v.num > 0).then(|| v.num as f64 / v.den as f64)
            };
            взять(avg).or_else(|| взять(r)).unwrap_or(30.0).clamp(1.0, 240.0)
        };
        открытое.шаг = Duration::from_micros((1_000_000.0 / частота).round() as u64);

        Some(открытое)
    }
}

/// Выдрать из отображённого кадра описание dmabuf.
///
/// VAAPI отдаёт NV12 то одним слоем с двумя плоскостями, то двумя слоями
/// (R8 — яркость, GR88 — цветность). Для Wayland это в обоих случаях один
/// `wl_buffer` формата NV12 с двумя плоскостями, поэтому слои мы просто
/// разворачиваем в общий список.
unsafe fn описать(
    mapped: *mut ff::AVFrame,
    surface_id: usize,
    размер: (u32, u32),
) -> Option<ОписаниеПоверхности> {
    unsafe {
        let desc = (*mapped).data[0] as *const ff::AVDRMFrameDescriptor;
        if desc.is_null() {
            return None;
        }
        let desc = &*desc;
        if desc.nb_objects < 1 || desc.nb_layers < 1 {
            return None;
        }

        // Модификатор берём у первого объекта: разные модификаторы у плоскостей
        // одного кадра Wayland описать не даёт, да VAAPI так и не делает.
        let модификатор = desc.objects[0].format_modifier as u64;

        let mut плоскости = Vec::new();
        let mut форматы = Vec::new();
        for сл in 0..desc.nb_layers as usize {
            let layer = &desc.layers[сл];
            форматы.push(layer.format as u32);
            for п in 0..layer.nb_planes as usize {
                let plane = &layer.planes[п];
                let об = plane.object_index as usize;
                if об >= desc.nb_objects as usize {
                    return None;
                }
                // Дескриптор дублируем: исходный принадлежит отображению и
                // умрёт вместе с ним, а wl_buffer живёт своей жизнью и
                // переживает не один кадр (главный цикл кэширует буферы).
                let сырой = libc::dup(desc.objects[об].fd);
                if сырой < 0 {
                    return None;
                }
                плоскости.push(Плоскость {
                    fd: OwnedFd::from_raw_fd(сырой),
                    сдвиг: plane.offset as u32,
                    шаг: plane.pitch as u32,
                });
            }
        }

        if плоскости.is_empty() || плоскости.len() > 4 {
            return None;
        }

        // Что за формат получился целиком.
        let fourcc = match форматы.as_slice() {
            [ф] => *ф,
            // Разложенный по слоям NV12 — собираем обратно.
            [DRM_FORMAT_R8, DRM_FORMAT_GR88] => DRM_FORMAT_NV12,
            _ => return None,
        };

        Some(ОписаниеПоверхности {
            surface_id,
            ширина: размер.0,
            высота: размер.1,
            fourcc,
            модификатор,
            плоскости,
        })
    }
}

/// Запустить аппаратное декодирование обоев.
///
/// `устройство` — узел рендера, обычно `/dev/dri/renderD128`. `None` в ответе
/// значит «эта машина/этот ролик так не умеют», и вызывающий обязан откатиться
/// на путь через процесс ffmpeg.
pub fn запустить(путь: &str, устройство: &str) -> Option<HwВидео> {
    let открытое = открыть(путь, устройство)?;
    let размер = открытое.размер;
    let шаг = открытое.шаг;

    // Ёмкость 1: декодер бежит ровно на один кадр впереди показа. Больше
    // держать нельзя — каждый непоказанный кадр занимает поверхность в пуле
    // VAAPI, а пул конечен.
    let (tx, rx) = sync_channel::<ГотовыйКадр>(1);
    let стоп = Arc::new(AtomicBool::new(false));
    let поток_стоп = стоп.clone();

    std::thread::Builder::new()
        .name("dwall-hwdec".into())
        .spawn(move || декодировать(открытое, tx, поток_стоп, шаг))
        .ok()?;

    // ── Дожидаемся ПЕРВОГО кадра прямо здесь ────────────────────────────────
    //
    // Без этого «не смогли» выглядело бы как намертво замёрзшие обои, а не как
    // откат. Дело в том, что `avcodec_open2` успехом ещё ничего не значит:
    // libavcodec спрашивает формат (см. выбрать_формат) только когда доходит до
    // первого настоящего кадра. Для AV1 на этом железе декодер честно
    // открывается — программный-то есть, — а потом на каждом кадре упирается в
    // отсутствие VAAPI и не отдаёт НИЧЕГО. Проверено 15.08.2026: без этой
    // проверки dwall вставал на `recv` навсегда.
    //
    // Ждать здесь безопасно: поток сдаётся сам, отсчитав ЛИМИТ_БЕЗ_КАДРОВ
    // пакетов впустую, и канал закрывается за доли секунды. Таймаут — только
    // страховка от совсем экзотического зависания внутри libavcodec.
    let первый = match rx.recv_timeout(Duration::from_secs(5)) {
        Ok(кадр) => Some(кадр),
        Err(_) => return None,
    };

    Some(HwВидео { rx, размер, первый, стоп })
}

/// Узел рендера по умолчанию. Отдельная карта здесь одна, и перебирать
/// `/dev/dri/renderD*` смысла нет; если когда-нибудь понадобится — сюда.
pub const УЗЕЛ_ПО_УМОЛЧАНИЮ: &str = "/dev/dri/renderD128";

/// Служебный режим `--hwtest`: прогнать ролик через аппаратный декодер и
/// показать, что получилось. Нужен, чтобы отличать «обои не появились, потому
/// что сломан композитор» от «видеокарта не умеет этот кодек».
pub fn режим_проверки(путь: Option<String>) -> i32 {
    let Some(путь) = путь else {
        eprintln!("применение: dwall --hwtest <файл>");
        return 2;
    };

    let начало = std::time::Instant::now();
    let Some(mut видео) = запустить(&путь, УЗЕЛ_ПО_УМОЛЧАНИЮ) else {
        println!("аппаратный декодер НЕ ВЗЯЛСЯ — обои поедут через ffmpeg");
        return 1;
    };
    println!("декодер поднялся, кадр {}×{}", видео.размер.0, видео.размер.1);

    let mut кадров = 0u32;
    let mut поверхностей = 0u32;
    // Первый кадр забран ещё в `запустить` — считаем и его.
    if let Some(кадр) = видео.первый.take() {
        кадров += 1;
        if кадр.описание.is_some() {
            поверхностей += 1;
        }
    }
    // Сотни кадров хватает: пул поверхностей VAAPI прокручивается целиком за
    // первые несколько десятков, а дальше идут одни повторы.
    while кадров < 300 {
        match видео.rx.recv() {
            Ok(кадр) => {
                if let Some(опис) = &кадр.описание {
                    поверхностей += 1;
                    if поверхностей <= 3 {
                        println!(
                            "  поверхность #{}: {}×{}, формат {:?}, модификатор {:#x}, плоскостей {}",
                            опис.surface_id,
                            опис.ширина,
                            опис.высота,
                            std::str::from_utf8(&опис.fourcc.to_le_bytes())
                                .unwrap_or("?")
                                .trim_end(),
                            опис.модификатор,
                            опис.плоскости.len(),
                        );
                    }
                }
                кадров += 1;
                // Держатель роняем сразу — здесь показывать некуда, и поверхность
                // должна вернуться в пул, иначе декодер встанет на третьем кадре.
                drop(кадр);
            }
            Err(_) => break,
        }
    }

    let сек = начало.elapsed().as_secs_f64();
    println!(
        "кадров {кадров}, разных поверхностей {поверхностей}, за {:.2} с ({:.0} к/с)",
        сек,
        кадров as f64 / сек.max(0.001),
    );
    0
}

/// Тело потока-декодера.
fn декодировать(
    открытое: Открытое,
    tx: SyncSender<ГотовыйКадр>,
    стоп: Arc<AtomicBool>,
    шаг: Duration,
) {
    // Поверхности, про которые главный цикл уже знает. VAAPI гоняет по кругу
    // десяток-другой, так что после первых кадров описания перестают строиться
    // вовсе — остаётся только номер поверхности.
    let mut известные: HashSet<usize> = HashSet::new();
    // Сколько пакетов согласны скормить декодеру, не увидев ни одного кадра,
    // прежде чем признать, что он этот кодек не тянет.
    //
    // Порог щедрый нарочно: у длинного GOP до первого показуемого кадра
    // законно уходит несколько десятков пакетов, а ошибиться в эту сторону
    // дорого — обои просто не появятся. При отказе же (AV1 на Comet Lake)
    // пакеты пролетают мгновенно, и порог выбирается за доли секунды.
    const ЛИМИТ_БЕЗ_КАДРОВ: u32 = 240;
    let mut пакетов_впустую: u32 = 0;
    let mut был_кадр = false;
    // Заводится лениво и только если декодер оказался программным — по факту
    // первого же кадра. Заранее знать нельзя: libavcodec сообщает свой выбор
    // (см. выбрать_формат) только когда доходит до настоящего кадра.
    let mut загрузка: Option<Загрузка> = None;

    unsafe {
        let пакет = ff::av_packet_alloc();
        if пакет.is_null() {
            return;
        }

        'внешний: loop {
            if стоп.load(Ordering::SeqCst) {
                break;
            }

            // Декодер открылся, но кадров не даёт — уходим и закрываем канал.
            // Вызывающий увидит это как «не смогли» и откатится на ffmpeg.
            if !был_кадр && пакетов_впустую > ЛИМИТ_БЕЗ_КАДРОВ {
                eprintln!("dwall: аппаратный декодер не отдал ни одного кадра");
                break;
            }

            let код = ff::av_read_frame(открытое.fmt, пакет);
            if код < 0 {
                // Ролик кончился — крутим сначала. Это тот же `-stream_loop -1`,
                // что стоял у ffmpeg, только своими руками.
                ff::av_seek_frame(открытое.fmt, открытое.поток, 0, ff::AVSEEK_FLAG_BACKWARD as i32);
                ff::avcodec_flush_buffers(открытое.codec);
                continue;
            }

            if (*пакет).stream_index != открытое.поток {
                ff::av_packet_unref(пакет);
                continue;
            }

            пакетов_впустую += 1;
            let код = ff::avcodec_send_packet(открытое.codec, пакет);
            ff::av_packet_unref(пакет);
            if код < 0 {
                if !был_кадр && пакетов_впустую == 1 {
                    eprintln!("dwall: пакет не принят декодером: {}", ошибка(код));
                }
                continue;
            }

            loop {
                let кадр = ff::av_frame_alloc();
                if кадр.is_null() {
                    break 'внешний;
                }
                let код = ff::avcodec_receive_frame(открытое.codec, кадр);
                if код < 0 {
                    // EAGAIN (нужен ещё пакет) или EOF — оба не беда.
                    if !был_кадр && пакетов_впустую == ЛИМИТ_БЕЗ_КАДРОВ {
                        eprintln!("dwall: кадр не забрался у декодера: {}", ошибка(код));
                    }
                    ff::av_frame_free(&mut { кадр });
                    break;
                }

                // Кадр приезжает либо готовой поверхностью видеокарты (её
                // заполнил аппаратный декодер), либо в системной памяти (её
                // заполнил процессор). Во втором случае кладём кадр в
                // поверхность сами — показывать всё равно будем одним и тем же
                // dmabuf-путём, и композитор разницы не увидит.
                let поверхность = if (*кадр).format == ff::AVPixelFormat_AV_PIX_FMT_VAAPI {
                    кадр
                } else {
                    let нужно = ((*кадр).format, (*кадр).width, (*кадр).height);
                    if загрузка.as_ref().map(|з| з.настроено) != Some(нужно) {
                        загрузка = Загрузка::новая(
                            открытое.hw_device, нужно.0, нужно.1, нужно.2,
                        );
                    }
                    let готово = загрузка.as_mut().and_then(|з| з.загрузить(кадр));
                    ff::av_frame_free(&mut { кадр });
                    match готово {
                        Some(п) => п,
                        // Не смогли переложить — пропускаем кадр. Если это
                        // навсегда (пул не создался), нас снимет счётчик
                        // пакетов впустую, и вызывающий уйдёт на ffmpeg.
                        None => continue,
                    }
                };

                был_кадр = true;
                match отдать_кадр(поверхность, &mut известные, &tx, шаг) {
                    Ok(()) => {}
                    // Главный цикл закрыл канал: обои сменили или dwall
                    // заканчивается.
                    Err(()) => break 'внешний,
                }

                if стоп.load(Ordering::SeqCst) {
                    break 'внешний;
                }
            }
        }

        ff::av_packet_free(&mut { пакет });
    }
}

/// Отобразить готовый кадр в dmabuf и отдать главному циклу.
///
/// `Err(())` — канал закрыт, поток обязан закончиться.
unsafe fn отдать_кадр(
    кадр: *mut ff::AVFrame,
    известные: &mut HashSet<usize>,
    tx: &SyncSender<ГотовыйКадр>,
    шаг: Duration,
) -> Result<(), ()> {
    unsafe {
        // Номер поверхности VAAPI libavcodec кладёт в data[3].
        let surface_id = (*кадр).data[3] as usize;
        let размер = ((*кадр).width.max(0) as u32, (*кадр).height.max(0) as u32);

        // Отображаем в DRM_PRIME. Отображение держит dmabuf-дескрипторы и
        // ссылку на исходный кадр, поэтому жить оно должно ровно столько же.
        let mapped = ff::av_frame_alloc();
        if mapped.is_null() {
            ff::av_frame_free(&mut { кадр });
            return Ok(());
        }
        (*mapped).format = ff::AVPixelFormat_AV_PIX_FMT_DRM_PRIME;
        if ff::av_hwframe_map(mapped, кадр, ff::AV_HWFRAME_MAP_READ as i32) < 0 {
            ff::av_frame_free(&mut { mapped });
            ff::av_frame_free(&mut { кадр });
            return Ok(());
        }

        // Описание строим только для поверхности, которую главный цикл ещё не
        // видел, — остальные он узнает по номеру и возьмёт готовый wl_buffer.
        let описание = if известные.insert(surface_id) {
            match описать(mapped, surface_id, размер) {
                Some(готово) => Some(готово),
                None => {
                    // Формат, который мы не умеем разложить в wl_buffer.
                    // Поверхность обратно в «неизвестные»: вдруг следующая
                    // приедет нормальной.
                    известные.remove(&surface_id);
                    ff::av_frame_free(&mut { mapped });
                    ff::av_frame_free(&mut { кадр });
                    return Ok(());
                }
            }
        } else {
            None
        };

        let готовый = ГотовыйКадр {
            surface_id,
            описание,
            шаг,
            держатель: Держатель { frame: кадр, mapped },
        };

        // `send` на канале ёмкостью 1 блокирует, пока главный цикл не заберёт
        // предыдущий кадр. Это и есть весь механизм «не бежать вперёд»: обои
        // закрыли — цикл перестал забирать, и декодер встал здесь, не тратя
        // ничего. Ошибка = канал закрыт.
        tx.send(готовый).map_err(|_| ())
    }
}
