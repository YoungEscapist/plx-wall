//! Живая передняя карточка ленты: ролик, выбранный лентой, играется прямо в
//! карточке, а не стоит одним кадром.
//!
//! Просьба 27.09.2026: «сделай предпросмотр анимации обоев, которые сейчас
//! выбраны лентой». Выбранная — ПЕРЕДНЯЯ карточка (см. `сетка_дробно`): та,
//! что стоит посреди ленты в полный размер.
//!
//! **Почему поток с ffmpeg, а не заготовленные кадры.** Кадров на несколько
//! секунд в размере карточки — это сотня мегабайт; держать их ради одной
//! карточки незачем. Вместо этого ffmpeg гонит ролик по кругу
//! (`-stream_loop -1`) в размере карточки, а темп задаёт ОЧЕРЕДЬ ёмкостью 1:
//! пока меню не забрало кадр, поток стоит на `send`, труба ffmpeg переполняется,
//! и тот засыпает сам. В памяти всё время два-три кадра, а декодер работает
//! ровно в том темпе, в каком кадры показывают.
//!
//! **Почему через клип в кэше, а не сам ролик.** Первая версия гнала в
//! карточку сам файл обоев — и ffmpeg ел 160% ядра: обои у Ярика 4K@60, а у
//! системного ffmpeg нет ни одного hwaccel, то есть все шестьдесят кадров 4K
//! декодировались программно ради картинки 604×340. Теперь первые
//! [`СЕКУНД_КЛИПА`] секунд ролика один раз ужимаются в клип 640×360@24
//! (`~/.cache/plx-wall/preview/`, ключ — путь+размер+время правки, как у
//! миниатюр) — это ~4 с одного фонового ffmpeg под `nice`, — и крутится уже
//! он. Замер 27.09.2026 на kitten-minecraft (h264 3840×2160@60): 32 с клипа
//! декодируются за 1.8 с процессора, то есть ~6% ядра вместо 160%.
//!
//! **Почему с задержкой.** Листая ленту, человек проезжает карточки десятками:
//! запускать ffmpeg (а на сетевой вкладке — ещё и качать ролик) на каждую
//! пролетевшую было бы чистым расходом. Превью заводится, только когда лента
//! постояла [`ЗАДЕРЖКА`].

use std::io::Read;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::mpsc;
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant};

/// Темп превью. Карточка — не обои: плавности 24 кадров ей хватает, а
/// декодер при этом работает вдвое-втрое меньше, чем на 60.
pub const КАДРОВ_В_СЕКУНДУ: f64 = 24.0;

/// Сколько секунд ролика идёт в клип превью. Карточке хватает кусочка:
/// ролик обоев обычно и так закольцован, а клип короче — дешевле и ужать, и
/// хранить (десятки-сотни килобайт).
const СЕКУНД_КЛИПА: u32 = 8;
/// Размер клипа: тот же, что у миниатюр (`МИНИ_W`×`МИНИ_H`). До карточки его
/// доужимает уже проигрывание.
const КЛИП: (u32, u32) = (super::МИНИ_W, super::МИНИ_H);

/// Сколько ленте стоять на месте, прежде чем передняя карточка оживёт.
pub const ЗАДЕРЖКА: Duration = Duration::from_millis(280);

/// Откуда брать ролик.
pub enum Источник {
    /// Свои обои: файл на диске (видео или gif).
    Файл(String),
    /// Находка сетевой вкладки «Живые»: ролик ещё надо найти на странице и
    /// скачать (см. `online::ролик_превью`).
    Сеть(crate::online::Находка),
}

/// Идущее превью одной карточки.
///
/// Чья это карточка, знает не оно, а `Config::превью` (ключ рядом с ним).
pub struct Превью {
    /// Последний показанный кадр: RGBA, `размер`.
    pub кадр: Option<Vec<u8>>,
    pub размер: (u32, u32),
    /// Когда забирать следующий кадр.
    pub срок: Instant,
    rx: mpsc::Receiver<Vec<u8>>,
    стоп: Arc<AtomicBool>,
    ffmpeg: Arc<Mutex<Option<std::process::Child>>>,
}

impl Превью {
    /// Завести превью: ролик ищется, качается и декодируется в своём потоке —
    /// меню от этого не ждёт ни кадра.
    pub fn завести(источник: Источник, размер: (u32, u32)) -> Self {
        // Чётные стороны: декодер видеокарты (`*_cuvid -resize`) нечётные не
        // берёт. До размера карточки кадр доужмёт отрисовка — на полпикселя.
        let размер = ((размер.0 & !1).max(2), (размер.1 & !1).max(2));
        let (tx, rx) = mpsc::sync_channel::<Vec<u8>>(1);
        let стоп = Arc::new(AtomicBool::new(false));
        let ffmpeg: Arc<Mutex<Option<std::process::Child>>> = Arc::new(Mutex::new(None));
        {
            let стоп = стоп.clone();
            let ffmpeg = ffmpeg.clone();
            std::thread::spawn(move || гнать(источник, размер, tx, стоп, ffmpeg));
        }
        Self {
            кадр: None,
            размер,
            срок: Instant::now(),
            rx,
            стоп,
            ffmpeg,
        }
    }

    /// Забрать кадр, если подошёл его срок. `true` — кадр сменился, меню надо
    /// перерисовать.
    pub fn шаг(&mut self) -> bool {
        let сейчас = Instant::now();
        if сейчас < self.срок {
            return false;
        }
        match self.rx.try_recv() {
            Ok(кадр) => {
                self.кадр = Some(кадр);
                let период = Duration::from_secs_f64(1.0 / КАДРОВ_В_СЕКУНДУ);
                // Срок идёт от ПРОШЛОГО срока, а не от «сейчас»: иначе каждое
                // опоздание цикла копилось бы и ролик плыл медленнее, чем надо.
                // Отстали больше чем на кадр (меню стояло) — догонять рывком
                // незачем, начинаем отсчёт заново.
                self.срок += период;
                if self.срок + период < сейчас {
                    self.срок = сейчас + период;
                }
                true
            }
            // Декодер не успел — спросим снова на следующем проходе цикла.
            Err(_) => false,
        }
    }

    /// Сколько миллисекунд циклу можно спать до следующего кадра.
    pub fn до_кадра_мс(&self) -> i32 {
        let ост = self.срок.saturating_duration_since(Instant::now());
        // Пол в 4 мс: канал не файловый дескриптор, о готовности кадра poll
        // не узнает, и опоздавший кадр остаётся только опрашивать.
        (ост.as_micros().div_ceil(1000) as i32).clamp(4, 1000)
    }
}

impl Drop for Превью {
    fn drop(&mut self) {
        self.стоп.store(true, Ordering::Relaxed);
        // Убиваем ffmpeg СРАЗУ: поток может стоять на чтении трубы, и сам он
        // узнает о стопе, только когда труба закроется.
        if let Ok(mut ребёнок) = self.ffmpeg.lock() {
            if let Some(mut процесс) = ребёнок.take() {
                let _ = процесс.kill();
                let _ = процесс.wait();
            }
        }
    }
}

/// Тело потока: найти ролик, запустить ffmpeg и гнать кадры в очередь.
fn гнать(
    источник: Источник,
    размер: (u32, u32),
    tx: mpsc::SyncSender<Vec<u8>>,
    стоп: Arc<AtomicBool>,
    ffmpeg: Arc<Mutex<Option<std::process::Child>>>,
) {
    let ролик = match источник {
        Источник::Файл(п) => п,
        Источник::Сеть(находка) => match crate::online::ролик_превью(&находка) {
            Some(п) => п.to_string_lossy().into_owned(),
            None => return,
        },
    };
    if стоп.load(Ordering::Relaxed) {
        return;
    }
    let Some(путь) = клип(&ролик, &стоп) else { return };
    if стоп.load(Ordering::Relaxed) {
        return;
    }
    // Клип и так мелкий, частота у него уже та, что нужна: ни видеокарта, ни
    // фильтр `fps` ему не нужны.
    let Some(mut ребёнок) = super::spawn_ffmpeg(&путь, Some(размер), None, false) else {
        return;
    };
    let Some(mut труба) = ребёнок.stdout.take() else { return };
    // Отдаём ребёнка тому, кто умеет его убить (Drop у `Превью`). Если стоп уже
    // сказан, пока ffmpeg запускался, — убиваем сами: Drop прошёл раньше и
    // ребёнка не застал.
    {
        let Ok(mut место) = ffmpeg.lock() else { return };
        if стоп.load(Ordering::Relaxed) {
            let _ = ребёнок.kill();
            let _ = ребёнок.wait();
            return;
        }
        *место = Some(ребёнок);
    }
    let нужно = (размер.0 as usize) * (размер.1 as usize) * 4;
    loop {
        let mut кадр = vec![0u8; нужно];
        if труба.read_exact(&mut кадр).is_err() {
            return; // ffmpeg кончился или его убили
        }
        // ffmpeg отдаёт bgra (так удобнее обоям), а карточки ленты — RGBA.
        for точка in кадр.chunks_exact_mut(4) {
            точка.swap(0, 2);
        }
        if стоп.load(Ordering::Relaxed) || tx.send(кадр).is_err() {
            return;
        }
    }
}

/// Клип превью для ролика: готовый из кэша или ужатый сейчас.
///
/// Ужимает ffmpeg под `nice -n 19`: это разовая работа, и живым обоям с меню
/// она уступать обязана. Пишет во временный файл и переименовывает — оборванная
/// запись (меню закрыли, лента уехала) не должна потом найтись как готовый клип.
fn клип(ролик: &str, стоп: &AtomicBool) -> Option<String> {
    let мета = std::fs::metadata(ролик).ok()?;
    let ключ = {
        use std::hash::{Hash, Hasher};
        let mut h = std::collections::hash_map::DefaultHasher::new();
        ролик.hash(&mut h);
        мета.len().hash(&mut h);
        мета.modified().ok().hash(&mut h);
        format!("{:016x}", h.finish())
    };
    let каталог = format!("{}/.cache/plx-wall/preview", super::home());
    let готовый = format!("{каталог}/{ключ}.mp4");
    if std::fs::metadata(&готовый).map(|м| м.len() > 0).unwrap_or(false) {
        return Some(готовый);
    }
    std::fs::create_dir_all(&каталог).ok()?;
    let временный = format!("{каталог}/.{ключ}.part");
    let (w, h) = КЛИП;
    let mut ffmpeg = std::process::Command::new("nice")
        .args([
            "-n", "19", "ffmpeg", "-loglevel", "error", "-nostdin", "-y",
            "-t", &СЕКУНД_КЛИПА.to_string(), "-i", ролик,
            "-an", "-sn",
            "-vf", &format!(
                "fps={КАДРОВ_В_СЕКУНДУ},scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h}"
            ),
            "-c:v", "libx264", "-preset", "veryfast", "-crf", "24", "-pix_fmt", "yuv420p",
            // Имя временного файла без .mp4 — формат говорим явно.
            "-f", "mp4", &временный,
        ])
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .spawn()
        .ok()?;
    // Ждём, поглядывая на стоп: карточка перестала быть передней — ужимать
    // дальше незачем, клип понадобится (может быть) в другой раз.
    loop {
        match ffmpeg.try_wait() {
            Ok(Some(статус)) if статус.success() => break,
            Ok(Some(_)) | Err(_) => {
                let _ = std::fs::remove_file(&временный);
                return None;
            }
            Ok(None) => {}
        }
        if стоп.load(Ordering::Relaxed) {
            let _ = ffmpeg.kill();
            let _ = ffmpeg.wait();
            let _ = std::fs::remove_file(&временный);
            return None;
        }
        std::thread::sleep(Duration::from_millis(50));
    }
    std::fs::rename(&временный, &готовый).ok()?;
    Some(готовый)
}
