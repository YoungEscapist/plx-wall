    /// Меню фильтров — это готовые состояния: выбрал строку, получил новые
    /// фильтры целиком. Заодно проверяем, что действующее значение помечено, а
    /// «сбросить» появляется только когда есть что сбрасывать.
    #[test]
    fn меню_фильтров_отдаёт_готовые_состояния() {
        let текущие = Фильтры::default();
        let пункты = меню_фильтров(Источник::Картинки, &текущие, &[], false);

        let помечено: Vec<&String> = пункты.iter().map(|(п, _)| п).filter(|п| п.contains('✓')).collect();
        // Источник, размер, ориентация, род и цвет — по одной галочке на
        // настройку. Источник появился 25.08.2026 вместе с wallhaven/picsum/bing.
        assert_eq!(помечено.len(), 5, "по одной галочке на настройку: {помечено:?}");

        // Строка источника меняет ТОЛЬКО источник — как и все остальные.
        let (_, после_источника) = пункты
            .iter()
            .find(|(п, _)| п.starts_with("Источник: wallhaven"))
            .expect("wallhaven есть в меню");
        assert_eq!(после_источника.провайдер, Провайдер::Wallhaven);
        assert_eq!(после_источника.размер, текущие.размер);
        assert_eq!(после_источника.род, текущие.род);
        assert!(
            !пункты.iter().any(|(п, _)| п.starts_with("Сбросить")),
            "сбрасывать нечего — пункта быть не должно"
        );

        let (_, после) = пункты
            .iter()
            .find(|(п, _)| п.starts_with("Род: рисунки"))
            .expect("род есть в меню");
        assert_eq!(после.род, Род::Рисунки);
        // Остальное не тронуто: строка меняет ровно одну настройку.
        assert_eq!(после.размер, текущие.размер);
        assert!(после.заданы());

        // Теперь сбрасывать есть что.
        let пункты = меню_фильтров(Источник::Картинки, после, &[], false);
        let (_, сброс) = пункты
            .iter()
            .find(|(п, _)| п.starts_with("Сбросить"))
            .expect("пункт сброса появился");
        assert_eq!(*сброс, Фильтры::default());
    }

