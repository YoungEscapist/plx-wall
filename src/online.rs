//! Обои из сети.
//!
//! Два источника, по одному на каждый род обоев:
//! - **openverse.org** — статичные картинки. Открытый JSON API без ключа.
//!   Стоит здесь вместо wallhaven.cc, который недоступен из России.
//!   Openverse — фотобанк CC-картинок, а не сборник обоев, поэтому выдачу
//!   приходится сужать фильтрами (см. [`openverse`]), а миниатюры брать не у
//!   него (см. [`превью`]).
//! - **moewalls.com** — живые обои. Открытого API у сайта нет, но он на
//!   WordPress, и его `/wp-json/wp/v2/posts` отдаёт список постов вместе с
//!   адресом картинки-превью (в поле `yoast_head_json.og_image`). Сам ролик
//!   ищем по странице поста — уже когда обои ВЫБРАЛИ, одним запросом.
//!
//! Почему адрес ролика не собирается по шаблону, хотя он предсказуемый
//! (`/wp-content/uploads/preview/<год>/<slug>-preview.webm`): год в адресе —
//! это год ЗАГРУЗКИ файла, а он не всегда совпадает с датой поста, и на
//! старых обоях шаблон промахивается. Один лишний запрос при скачивании
//! дешевле, чем «выбрал — не открылось».
//!
//! Ходим наружу через `curl`, а не через HTTP-клиент на Rust: в plx-wall нет ни
//! асинхронного рантайма, ни TLS-обвязки, и тащить их ради двух запросов —
//! это плюс полторы сотни зависимостей. Тем же способом (через процесс)
//! работает и декодер обоев, так что приём для этого кода не новый.
//!
//! ВАЖНО: всё здесь БЛОКИРУЮЩЕЕ и обязано вызываться из отдельного потока —
//! главный цикл не должен ждать сеть ни секунды.

use std::path::{Path, PathBuf};
use std::process::Command;

/// Представляемся браузером: moewalls отвечает на «непонятные» подписи
/// страницей-заглушкой, а не данными.
const БРАУЗЕР: &str =
    "Mozilla/5.0 (X11; Linux x86_64; rv:128.0) Gecko/20100101 Firefox/128.0";

/// Сколько ждать сеть на КОРОТКОМ запросе — список выдачи или миниатюра.
/// Больше нет смысла: при таком ожидании человек уже закрыл меню.
const ЖДАТЬ: &str = "20";

/// Сколько ждать САМ файл обоев. Тот же срок, что и на список, здесь был
/// прямой ошибкой: полный ролик живых обоев весит десятки мегабайт (замер
/// 14.08.2026: 81 МБ), и на любом канале медленнее 30 Мбит/с загрузка
/// обрывалась ровно на двадцатой секунде — снаружи это выглядело как «обои
/// не качаются». Зависшую загрузку ловит не этот срок, а `--speed-time`.
const ЖДАТЬ_ФАЙЛ: &str = "600";

/// До какого веса файл качаем ОРИГИНАЛОМ, а не пережатым кадром под монитор
/// (см. [`викимедиа`]). 24 МБ — с запасом накрывает нормальные обои в PNG и
/// отсекает сканы карт и панорамы на полсотни мегабайт, ради которых 1920-й
/// кадр когда-то и завели.
const ПРЕДЕЛ_ОРИГИНАЛА: u64 = 24 * 1024 * 1024;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Источник {
    /// Статичные картинки, openverse.org.
    Картинки,
    /// Живые обои, moewalls.com.
    Живые,
}

/// Насколько крупные картинки просить у Openverse.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Размер {
    /// `size=large` — то, что годится на широкий экран без растягивания.
    Крупные,
    /// `size=medium,large` — когда в крупных нашлось слишком мало.
    Средние,
    /// Без ограничения. Мелочь всё равно отсеется по ширине (см. [`openverse`]).
    Любые,
}

/// Форма картинки.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Ориентация {
    /// `aspect_ratio=wide` — по умолчанию: вертикальные снимки на широкий
    /// экран не растянуть.
    Широкие,
    Любая,
}

/// Род картинки у Openverse: он всё-таки фотобанк, и рисунки с фотографиями
/// перемешаны.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Род {
    Любой,
    /// `category=illustration`.
    Рисунки,
    /// `category=photograph`.
    Фотографии,
}

/// Чем сортировать выдачу moewalls.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Порядок {
    /// `orderby=date` — свежие сверху. Так сайт показывает и сам.
    Свежие,
    /// `orderby=relevance`. WordPress принимает его ТОЛЬКО вместе с поиском:
    /// без `search` он отвечает ошибкой, поэтому без запроса не просим.
    Совпадение,
}

/// Откуда брать статичные обои.
///
/// **Замер 25.08.2026 прямо с машины Ярика** (curl, без VPN): wallhaven.cc —
/// 200, openverse — 200, commons.wikimedia — 200, picsum — 200, bing — 200;
/// waifu.im, nekos.best и reddit отвечают 403 на любые заголовки и в список не
/// попали. Прежняя заметка «wallhaven недоступен из России» (и такая же про
/// Openverse) устарела — оба открываются, судя по всему через zapret.
///
/// Порядок в `Авто` — по тому, насколько источник ЗАТОЧЕН под обои: wallhaven
/// это сайт обоев с поиском и фильтром по разрешению, Openverse и Commons —
/// фотобанки, из которых обои приходится выуживать, а picsum и bing поиска не
/// умеют вовсе и в автоцепочку не входят.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Провайдер {
    /// wallhaven → openverse → commons, первый непустой.
    Авто,
    /// wallhaven.cc — обои, поиск, `atleast`, оригиналы без ужатия.
    Wallhaven,
    /// api.openverse.org — фотобанк CC.
    Openverse,
    /// commons.wikimedia.org.
    Викимедиа,
    /// picsum.photos — случайные фотографии (Unsplash), поиска нет.
    Picsum,
    /// Обои дня Bing в UHD, поиска нет.
    Bing,
    /// images-api.nasa.gov — снимки NASA. Один из двух БЕСКОНЕЧНЫХ (см. ниже).
    Космос,
    /// api.artic.edu — собрание Чикагского института искусств, второй
    /// бесконечный.
    Искусство,
}

/// Бесконечен ли источник — то есть кончается ли у него выдача.
///
/// **Зачем это отдельно названо.** У всех прежних источников дно близко:
/// bing — восемь рынков по восемь картинок (64 штуки, и они повторяются),
/// picsum — тысяча фотографий, wallhaven и commons упираются в запрос. Лента
/// с карточкой «далее» рассчитана на бесконечное листание, и на таких
/// источниках она через минуту приносит пустую страницу.
///
/// Бесконечными считаются те, у кого выдача измеряется сотнями тысяч и
/// листается страницами без ключа: NASA (164 714 снимков по запросу «space»,
/// замер 05.09.2026) и Чикагский институт искусств (132 740 работ, листаются
/// вообще без запроса). Их и стоит выбирать, когда хочется просто смотреть
/// обои, пока не надоест.
pub fn бесконечный(п: Провайдер) -> bool {
    matches!(п, Провайдер::Космос | Провайдер::Искусство)
}

/// Откуда брать ЖИВЫЕ обои.
///
/// Замер 31.08.2026 прямо с машины Ярика (curl, без VPN): motionbgs.com — 200,
/// livewallpapers4free.com — 200 и полноценный WordPress-API с поиском и
/// страницами. Два сайта, которые в список НЕ попали и почему:
/// mylivewallpapers.com отдаёт 307 и заставку Sucuri («включите JavaScript»),
/// то есть без исполнения скриптов недостижим; moewalls.com жив, но его
/// `/wp-json/` теперь отвечает `rest_forbidden` — читать его пришлось бы
/// разбором вёрстки, а она у него своя, не такая, как у двух других.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum ЖивойИсточник {
    /// motionbgs → livewallpapers4free, первый непустой.
    Авто,
    /// motionbgs.com — разбор вёрстки, свой полный файл в высоком качестве.
    Motionbgs,
    /// livewallpapers4free.com — WordPress-API: поиск и страницы без разбора
    /// вёрстки, ролик берётся со страницы поста.
    ///
    /// **Качество ниже.** Замер: скачанный ролик — 854×480 HEVC, и другого
    /// сайт не предлагает (`<source>` на странице ровно один). У motionbgs
    /// полный файл идёт в родном разрешении. Поэтому в `Авто` он и стоит
    /// первым, а этот — запасной; выбрать его руками осмысленно, когда у
    /// motionbgs по запросу пусто: поиск у lw4free настоящий, а motionbgs
    /// умеет только метки.
    LiveWallpapers4Free,
}

/// Чем сужена выдача. Значения по умолчанию — то, с чем plx-wall жил раньше
/// (крупные широкие картинки, все разделы moewalls, свежие сверху), поэтому
/// «сбросить» возвращает ровно прежнее поведение.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Фильтры {
    pub провайдер: Провайдер,
    /// Источник живых обоев. Отдельным полем, а не общим с `провайдер`:
    /// сайты не пересекаются ни одним, и «wallhaven для живых обоев» — это
    /// состояние, которого не должно существовать вовсе.
    pub живой: ЖивойИсточник,
    pub размер: Размер,
    pub ориентация: Ориентация,
    pub род: Род,
    /// Раздел живых обоев: метка сайта (`anime`, `4k`, `gifs`…) и её имя для
    /// показа. `None` — все разделы. Раньше здесь лежал НОМЕР категории
    /// WordPress; после переезда moewalls на motionbgs разделы стали
    /// словами в адресе (`/tag:anime/`), см. [`motionbgs`].
    pub раздел: Option<(String, String)>,
    pub порядок: Порядок,
    /// Отбор по цвету. Ни один из источников этого не умеет, поэтому он
    /// работает уже по скачанным миниатюрам — см. [`crate::palette::Цвет`] и
    /// отбор в главном модуле.
    pub цвет: Option<crate::palette::Цвет>,
}

impl Default for Фильтры {
    fn default() -> Self {
        Фильтры {
            провайдер: Провайдер::Авто,
            живой: ЖивойИсточник::Авто,
            размер: Размер::Крупные,
            ориентация: Ориентация::Широкие,
            род: Род::Любой,
            раздел: None,
            порядок: Порядок::Свежие,
            цвет: None,
        }
    }
}

impl Фильтры {
    /// Хоть что-то сужено? По этому меню подсвечивает кнопку — объяснить
    /// словами, почему в сетке не «всё подряд», в plx-wall нечем.
    pub fn заданы(&self) -> bool {
        *self != Фильтры::default()
    }
}

/// Одна находка в выдаче.
#[derive(Clone, Debug)]
pub struct Находка {
    /// Адрес миниатюры — её и показываем в сетке.
    pub миниатюра: String,
    /// Что скачивать. У openverse это сразу файл, у moewalls — страница
    /// поста, на которой ещё надо найти ролик (см. [`скачать`]).
    pub цель: String,
    pub источник: Источник,
    /// Из чего строить имя файла.
    pub имя: String,
}

/// Короткий запрос: список выдачи, страница поста, миниатюра.
fn curl(url: &str) -> Option<Vec<u8>> {
    качнуть(url, ЖДАТЬ)
}

/// Запрос за САМИМ файлом обоев — с другим сроком, см. [`ЖДАТЬ_ФАЙЛ`].
fn curl_файл(url: &str) -> Option<Vec<u8>> {
    качнуть(url, ЖДАТЬ_ФАЙЛ)
}

/// Общее тело обоих: разница только в сроке ожидания.
///
/// Ключи, которых здесь когда-то не было, и что каждый чинит:
///
/// * `--fail` — БЕЗ него curl считает удачей и 403, и 404: тело страницы
///   ошибки возвращалось как «файл», и в каталог обоев ложился HTML под
///   именем картинки. Отсюда «некоторые обои просто не качаются» — они
///   качались, но это были не обои;
/// * `--retry` — одна оборванная попытка больше не приговор. Сеть у Ярика
///   ходит через zapret и туннель, и первый запрос к незнакомому хосту
///   срывается заметно чаще следующего;
/// * `--speed-limit/--speed-time` — обрыв ПО МОЛЧАНИЮ, а не по общему сроку:
///   живые обои весят под сотню мегабайт, и жёсткие 20 секунд рубили честно
///   идущую загрузку на середине.
/// Заголовки, которых требует конкретный хост.
///
/// Пока такой один: картинки Чикагского института искусств
/// (`www.artic.edu/iiif/…`) без `AIC-User-Agent` отвечают 403 и страницей с
/// объяснением — при том что сам их API отдаёт JSON кому угодно. Проверка
/// 05.09.2026: без заголовка 403 (5.6 КБ HTML), с ним 200 (643 КБ jpeg).
///
/// Правило по ХОСТУ, а не по вызывающему: тот же адрес просят и лента (за
/// миниатюрой), и загрузка обоев, и путь у них разный.
fn заголовки_хоста(url: &str) -> Vec<String> {
    if url.contains("artic.edu") {
        return vec!["AIC-User-Agent: plx-wall (github.com/yarik/plx-wall)".to_string()];
    }
    Vec::new()
}

fn качнуть(url: &str, срок: &str) -> Option<Vec<u8>> {
    let mut cmd = Command::new("curl");
    for заголовок in заголовки_хоста(url) {
        cmd.arg("-H").arg(заголовок);
    }
    let out = cmd
        .args([
            "-sL",
            "--fail",
            "--retry",
            "2",
            "--retry-connrefused",
            "--connect-timeout",
            "10",
            "--speed-limit",
            "1024",
            "--speed-time",
            "20",
            "--max-time",
            срок,
            "-A",
            БРАУЗЕР,
            url,
        ])
        .output()
        .ok()?;
    out.status.success().then_some(out.stdout)
}

fn curl_текст(url: &str) -> Option<String> {
    String::from_utf8(curl(url)?).ok()
}

/// Проценты вместо всего, что не буква и не цифра.
///
/// Свой, а не крейт: нужно ровно это, а запрос приходит от человека и может
/// содержать что угодно — пробелы, кириллицу, амперсанд. Без кодирования
/// амперсанд разрезал бы запрос на два параметра, а пробел вовсе сломал бы
/// адрес.
fn закодировать(текст: &str) -> String {
    let mut out = String::with_capacity(текст.len());
    for b in текст.as_bytes() {
        match b {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => {
                out.push(*b as char)
            }
            b' ' => out.push('+'),
            _ => out.push_str(&format!("%{b:02X}")),
        }
    }
    out
}

/// Список обоев со страницы `страница` (нумерация с единицы).
///
/// `запрос` пустой — показываем то, что источник считает лучшим.
pub fn список(
    источник: Источник,
    страница: u32,
    ширина: u32,
    высота: u32,
    запрос: &str,
    фильтры: &Фильтры,
) -> Result<Vec<Находка>, String> {
    match источник {
        Источник::Картинки => match фильтры.провайдер {
            // Первый непустой. Пустая выдача — не ошибка (у источника просто
            // нет ничего по запросу), но и показывать пустую сетку, когда
            // соседний источник что-то знает, незачем.
            Провайдер::Авто => {
                let попытки: [fn(u32, u32, u32, &str, &Фильтры) -> Result<Vec<Находка>, String>; 3] =
                    [wallhaven, openverse, |с, ш, в, з, _| викимедиа(с, ш, в, з)];
                let mut последняя = Err("источники молчат".to_string());
                for попытка in попытки {
                    match попытка(страница, ширина, высота, запрос, фильтры) {
                        Ok(находки) if !находки.is_empty() => return Ok(находки),
                        иное => последняя = иное,
                    }
                }
                последняя
            }
            Провайдер::Wallhaven => wallhaven(страница, ширина, высота, запрос, фильтры),
            Провайдер::Openverse => openverse(страница, ширина, высота, запрос, фильтры),
            Провайдер::Викимедиа => викимедиа(страница, ширина, высота, запрос),
            Провайдер::Picsum => picsum(страница, ширина, высота),
            Провайдер::Bing => bing(страница),
            Провайдер::Космос => космос(страница, запрос),
            Провайдер::Искусство => искусство(страница, ширина, запрос),
        },
        Источник::Живые => match фильтры.живой {
            // Тем же правилом, что у картинок: первый непустой. Пустая выдача
            // — не ошибка (у сайта просто нет ничего по запросу), но и
            // показывать пустую ленту, когда соседний сайт что-то знает,
            // незачем. motionbgs первым: у него есть полный файл в высоком
            // качестве, а lw4f отдаёт только то, что лежит на странице.
            ЖивойИсточник::Авто => {
                let mut последняя = Err("источники живых обоев молчат".to_string());
                match motionbgs(страница, запрос, фильтры) {
                    Ok(н) if !н.is_empty() => return Ok(н),
                    иное => последняя = иное,
                }
                match lw4f(страница, запрос) {
                    Ok(н) if !н.is_empty() => Ok(н),
                    иное => {
                        // Отдаём ту беду, что случилась позже: если молчали
                        // оба, полезнее знать про второй — первый уже описан
                        // в логе.
                        let _ = последняя;
                        иное
                    }
                }
            }
            ЖивойИсточник::Motionbgs => motionbgs(страница, запрос, фильтры),
            ЖивойИсточник::LiveWallpapers4Free => lw4f(страница, запрос),
        },
    }
}

/// wallhaven.cc — единственный из доступных источников, который сделан ИМЕННО
/// под обои: поиск, категории и, главное, `atleast` — фильтр по разрешению на
/// стороне сервера. Отдаёт ОРИГИНАЛ файла (`path`), а не ужатый кадр, поэтому
/// «без потери качества» здесь получается само собой.
///
/// Ключ не нужен: анонимный доступ даёт поиск и 24 находки на страницу; ключ
/// открывает только NSFW и личные коллекции, которые нам не нужны.
///
/// Соответствие фильтров plx-wall параметрам wallhaven:
/// * `Размер` → `atleast`. «Крупные» — не мельче монитора (то самое «без
///   потери качества»: такую картинку не придётся растягивать), «средние» —
///   половина монитора, «любые» — без ограничения.
/// * `Ориентация::Широкие` → `ratios=16x9,16x10,21x9,32x9`.
/// * `Род` → `categories`: рисунки — аниме (010), фотографии — general (100),
///   любой — всё (111). People (001) идёт в «любой» и не идёт в «фотографии»:
///   портреты на широкий экран ложатся плохо.
/// * `Порядок` → `sorting`. В отличие от WordPress у moewalls, `relevance`
///   здесь допустим и без запроса.
///
/// `purity=100` (только SFW) стоит жёстко и в меню не выведено.
fn wallhaven(
    страница: u32,
    ширина: u32,
    высота: u32,
    запрос: &str,
    фильтры: &Фильтры,
) -> Result<Vec<Находка>, String> {
    let категории = match фильтры.род {
        Род::Рисунки => "010",
        Род::Фотографии => "100",
        Род::Любой => "111",
    };
    let atleast = match фильтры.размер {
        Размер::Крупные => format!("&atleast={ширина}x{высота}"),
        Размер::Средние => format!("&atleast={}x{}", (ширина / 2).max(1), (высота / 2).max(1)),
        Размер::Любые => String::new(),
    };
    let ratios = match фильтры.ориентация {
        Ориентация::Широкие => "&ratios=16x9,16x10,21x9,32x9",
        Ориентация::Любая => "",
    };
    let sorting = match фильтры.порядок {
        Порядок::Свежие => "date_added",
        Порядок::Совпадение => "relevance",
    };
    let url = format!(
        "https://wallhaven.cc/api/v1/search?purity=100&categories={категории}\
         &sorting={sorting}&page={страница}{atleast}{ratios}&q={}",
        закодировать(запрос)
    );
    let тело = curl_текст(&url).ok_or("wallhaven не ответил")?;
    let json: serde_json::Value =
        serde_json::from_str(&тело).map_err(|e| format!("wallhaven: непонятный ответ ({e})"))?;
    let список = json
        .get("data")
        .and_then(|v| v.as_array())
        .ok_or("wallhaven: в ответе нет списка")?;

    Ok(список
        .iter()
        .filter_map(|item| {
            let цель = item.get("path")?.as_str()?.to_string();
            // Миниатюру сайт отдаёт сам — не надо ни угадывать её адрес, ни
            // качать ради сетки многомегабайтный оригинал.
            // `large`, а не `small`. Замер 04.09.2026: small — это 300×200,
            // то есть КАДРИРОВАННЫЕ 3:2, и лента растягивала их до 16:9 —
            // картинка выходила и мутной, и вытянутой. large отдаёт 432×243,
            // ровно 16:9. Крупнее у wallhaven ничего нет: `original` на том же
            // снимке ответил 146 байтами ошибки, а `path` — это оригинал в
            // мегабайты, ради сетки его не качают.
            let миниатюра = item
                .get("thumbs")
                .and_then(|t| t.get("large").or_else(|| t.get("small")))
                .and_then(|v| v.as_str())
                .unwrap_or(&цель)
                .to_string();
            let имя = item.get("id")?.as_str()?.to_string();
            Some(Находка { миниатюра, цель, источник: Источник::Картинки, имя })
        })
        .collect())
}

/// picsum.photos — витрина Unsplash. Поиска нет вовсе, зато выдача бездонная и
/// каждая картинка отдаётся в ОРИГИНАЛЕ (у большинства 5000×3333).
///
/// Запрос игнорируется намеренно: параметра поиска у API не существует, и
/// молча отдавать «не то, что просили» честнее одним способом — сказать об
/// этом в меню (см. [`меню_фильтров`]).
fn picsum(страница: u32, ширина: u32, высота: u32) -> Result<Vec<Находка>, String> {
    let url = format!("https://picsum.photos/v2/list?page={страница}&limit=20");
    let тело = curl_текст(&url).ok_or("picsum не ответил")?;
    let json: serde_json::Value =
        serde_json::from_str(&тело).map_err(|e| format!("picsum: непонятный ответ ({e})"))?;
    let список = json.as_array().ok_or("picsum: в ответе нет списка")?;
    Ok(список
        .iter()
        .filter_map(|item| {
            let id = item.get("id")?.as_str()?.to_string();
            let w = item.get("width").and_then(|v| v.as_u64()).unwrap_or(0);
            let h = item.get("height").and_then(|v| v.as_u64()).unwrap_or(0);
            if w * 2 < ширина as u64 || h * 2 < высота as u64 {
                return None;
            }
            // download_url ведёт на оригинал; миниатюру просим у самого picsum
            // ужатой — он умеет отдавать любой размер прямо в адресе.
            let цель = item.get("download_url")?.as_str()?.to_string();
            Some(Находка {
                // Ровно тот размер, в котором миниатюру и будут хранить
                // (crate::МИНИ_W×МИНИ_H): просить меньше — значит показывать
                // растянутое, просить больше — платить трафиком за пиксели,
                // которые тут же выбросит `разобрать_миниатюру`.
                миниатюра: format!(
                    "https://picsum.photos/id/{id}/{}/{}",
                    crate::МИНИ_W,
                    crate::МИНИ_H
                ),
                цель,
                источник: Источник::Картинки,
                имя: format!("picsum-{id}"),
            })
        })
        .collect())
}

/// Обои дня Bing в UHD (3840×2160). Поиска у архива нет, зато картинки
/// отобраны редакторами и всегда ровно под широкий экран.
///
/// Архив отдаёт максимум 8 дней на один рынок (`mkt`), поэтому «страницы» —
/// это рынки: на каждой свои 8 картинок, у разных стран подборки разные.
/// Дубли между рынками отсеиваем по `urlbase`.
///
/// **`_UHD.jpg`, а не `_1920x1080.jpg`.** Тот же адрес отдаёт и то, и другое;
/// UHD весит ~3.7 МБ и это настоящий оригинал (замер 25.08.2026).
fn bing(страница: u32) -> Result<Vec<Находка>, String> {
    const РЫНКИ: [&str; 8] = [
        "en-US", "ja-JP", "de-DE", "en-GB", "fr-FR", "en-AU", "en-CA", "zh-CN",
    ];
    let рынок = РЫНКИ[(страница.saturating_sub(1) as usize) % РЫНКИ.len()];
    let url = format!(
        "https://www.bing.com/HPImageArchive.aspx?format=js&idx=0&n=8&mkt={рынок}"
    );
    let тело = curl_текст(&url).ok_or("bing не ответил")?;
    let json: serde_json::Value =
        serde_json::from_str(&тело).map_err(|e| format!("bing: непонятный ответ ({e})"))?;
    let список = json
        .get("images")
        .and_then(|v| v.as_array())
        .ok_or("bing: в ответе нет списка")?;
    let mut видели = std::collections::HashSet::new();
    Ok(список
        .iter()
        .filter_map(|item| {
            let база = item.get("urlbase")?.as_str()?;
            if !видели.insert(база.to_string()) {
                return None;
            }
            let имя = база.rsplit("OHR.").next().unwrap_or(база).to_string();
            Some(Находка {
                // _1280x720, а не _400x240: 400-й кадр в карточке ленты (та
                // шире 600 px) размазывался, да и пропорции у него 5:3 — лента
                // растягивала его до 16:9. Замер 04.09.2026: _400x240 — 16 КБ,
                // _1280x720 — 145 КБ, _UHD — 3.7 МБ; 145 КБ на карточку это
                // та цена, за которую картинка перестаёт быть мылом.
                миниатюра: format!("https://www.bing.com{база}_1280x720.jpg"),
                цель: format!("https://www.bing.com{база}_UHD.jpg"),
                источник: Источник::Картинки,
                имя,
            })
        })
        .collect())
}

/// Запрос по умолчанию для NASA: без него API отвечает пустотой, а «space»
/// накрывает всю библиотеку разом (164 714 снимков, замер 05.09.2026).
const КОСМОС_ПО_УМОЛЧАНИЮ: &str = "space";

/// images-api.nasa.gov — снимки NASA, один из двух бесконечных источников
/// (см. [`бесконечный`]).
///
/// Ключа не требует, страницы честные (сто находок на страницу), и запас
/// такой, что листать можно неделю. Для обоев это едва ли не лучший источник
/// из доступных: снимки телескопов и планет заведомо крупные (оригиналы по
/// 5–8 МБ, замер), тёмные и без мелких деталей, которые на весь экран
/// рассыпаются.
///
/// **Про размеры.** У каждой находки есть готовая лесенка `~thumb` (640),
/// `~small`, `~medium` (1280), `~large` (1920) и `~orig` (родное разрешение).
/// Миниатюре берём `~thumb`, обоям — `~orig`: он и есть «без потери качества».
/// Адрес строится подменой суффикса, потому что в списке `links` лежит только
/// превью — остальные варианты API не перечисляет, но они есть всегда (проверка
/// 05.09.2026: `~orig` у PIA13845 — 7.5 МБ).
fn космос(страница: u32, запрос: &str) -> Result<Vec<Находка>, String> {
    let запрос = if запрос.trim().is_empty() { КОСМОС_ПО_УМОЛЧАНИЮ } else { запрос };
    let url = format!(
        "https://images-api.nasa.gov/search?q={}&media_type=image&page={}",
        закодировать(запрос),
        страница.max(1),
    );
    let тело = curl_текст(&url).ok_or("NASA не ответил")?;
    let json: serde_json::Value =
        serde_json::from_str(&тело).map_err(|e| format!("NASA: непонятный ответ ({e})"))?;
    let список = json
        .get("collection")
        .and_then(|c| c.get("items"))
        .and_then(|v| v.as_array())
        .ok_or("NASA: в ответе нет списка")?;
    Ok(список
        .iter()
        .filter_map(|item| {
            let превью = item
                .get("links")?
                .as_array()?
                .iter()
                .find_map(|l| l.get("href")?.as_str())?
                .to_string();
            // Строго http**s**: адреса в links бывают и без буквы s, а curl за
            // редиректом сходит, но лишний круг тут ни к чему.
            let превью = превью.replacen("http://", "https://", 1);
            let данные = item.get("data")?.as_array()?.first()?;
            let id = данные.get("nasa_id")?.as_str()?.to_string();
            let оригинал = подменить_хвост(&превью, "~orig");
            // В `links` лежит то `~thumb`, то `~medium` (1.4 МБ!) — какой
            // вариант попал в превью, зависит от снимка. Ленте нужен
            // мелкий: просим его явно, а не берём что дали.
            let мелкий = подменить_хвост(&превью, "~thumb");
            Some(Находка {
                миниатюра: мелкий,
                цель: оригинал,
                источник: Источник::Картинки,
                имя: format!("nasa-{id}"),
            })
        })
        .collect())
}

/// Подменить размерный суффикс в адресе снимка NASA: `…~thumb.jpg` → `…~orig.jpg`.
///
/// Отдельной функцией ради проверки: ошибиться здесь значит скачать
/// шестисотпиксельную миниатюру вместо обоев, а на экране это видно не сразу —
/// сперва покажется, что «источник отдаёт мыло».
fn подменить_хвост(адрес: &str, новый: &str) -> String {
    let Some(точка) = адрес.rfind('.') else { return адрес.to_string() };
    let (без_расширения, расширение) = адрес.split_at(точка);
    match без_расширения.rfind('~') {
        Some(тильда) => format!("{}{новый}{расширение}", &без_расширения[..тильда]),
        None => format!("{без_расширения}{новый}{расширение}"),
    }
}

/// api.artic.edu — собрание Чикагского института искусств, второй бесконечный
/// источник: 132 740 работ, которые листаются вообще БЕЗ запроса.
///
/// Пустой запрос уводит на `/artworks` (просто всё подряд, страница за
/// страницей), непустой — на `/artworks/search`. Это не мелочь: у остальных
/// источников без запроса выдача либо пустая, либо одна и та же.
///
/// Картинки идут через IIIF, то есть размер просится прямо в адресе:
/// миниатюре — ровно `МИНИ_W`, обоям — родная ширина работы (с потолком, см.
/// ниже). Ужимать на своей стороне ничего не нужно.
///
/// **Грабля: 403 без `AIC-User-Agent`.** Сам API отвечает кому угодно, а вот
/// картинки с `www.artic.edu/iiif/2/…` без этого заголовка возвращают 403 и
/// страницу с объяснением (замер 05.09.2026). Заголовок подставляет
/// [`заголовки_хоста`] — иначе в каталог обоев ложился бы HTML под именем
/// картинки.
fn искусство(страница: u32, ширина: u32, запрос: &str) -> Result<Vec<Находка>, String> {
    const ПОЛЯ: &str = "id,title,image_id,artist_title,thumbnail";
    let запрос = запрос.trim();
    let url = if запрос.is_empty() {
        format!(
            "https://api.artic.edu/api/v1/artworks?page={}&limit=20&fields={ПОЛЯ}",
            страница.max(1)
        )
    } else {
        format!(
            "https://api.artic.edu/api/v1/artworks/search?q={}&page={}&limit=20&fields={ПОЛЯ}",
            закодировать(запрос),
            страница.max(1),
        )
    };
    let тело = curl_текст(&url).ok_or("artic не ответил")?;
    let json: serde_json::Value =
        serde_json::from_str(&тело).map_err(|e| format!("artic: непонятный ответ ({e})"))?;
    let список = json.get("data").and_then(|v| v.as_array()).ok_or("artic: в ответе нет списка")?;
    Ok(список
        .iter()
        .filter_map(|item| {
            // Работы без снимка в собрании есть, и их немало: у них нет
            // image_id, и просить IIIF нечего.
            let ключ = item.get("image_id")?.as_str()?.to_string();
            let эскиз = item.get("thumbnail");
            let w = эскиз.and_then(|t| t.get("width")).and_then(|v| v.as_u64()).unwrap_or(0);
            // Мельче экрана по ширине не берём: такую работу пришлось бы
            // растягивать, а это ровно то, от чего «крупные» и спасают.
            if w > 0 && w < ширина as u64 {
                return None;
            }
            // Потолок ширины: у части работ снимок 10 969 px (замер), и
            // просить его целиком значит качать десятки мегабайт ради экрана
            // вчетверо уже.
            let полная = w.clamp(1, 4096);
            let имя = item
                .get("title")
                .and_then(|v| v.as_str())
                .map(безопасное)
                .filter(|s| !s.is_empty())
                .unwrap_or_else(|| format!("artic-{ключ}"));
            Some(Находка {
                миниатюра: format!(
                    "https://www.artic.edu/iiif/2/{ключ}/full/{},/0/default.jpg",
                    crate::МИНИ_W
                ),
                цель: format!(
                    "https://www.artic.edu/iiif/2/{ключ}/full/{полная},/0/default.jpg"
                ),
                источник: Источник::Картинки,
                имя,
            })
        })
        .collect())
}

/// Адрес уменьшенной картинки для сетки.
///
/// Собственные миниатюры Openverse (`/v1/images/<id>/thumb/`) НЕ используем по
/// двум причинам сразу. Первая: они попросту не работают — на проверке
/// 09.08.2026 все до одной ответили 424 «Thumbnail unavailable from provider».
/// Вторая, более принципиальная: анонимный доступ к API ограничен 20 запросами
/// в минуту и 200 в сутки, а одна страница сетки — это 20 миниатюр, то есть
/// минутный лимит выбирался бы целиком на первой же странице.
///
/// Поэтому уменьшенный вариант просим прямо у хранилища провайдера, и к самому
/// Openverse остаётся ОДИН запрос на страницу — за списком.
fn превью(файл: &str) -> String {
    // Wikimedia (весь верх выдачи с нашими фильтрами — из неё). Произвольную
    // ширину через /thumb/ она больше не отдаёт: 400 и «Use thumbnail sizes
    // listed on ...». Документированный Special:FilePath с width работает и
    // отдаёт ~100 КБ вместо нескольких мегабайт оригинала.
    if файл.starts_with("https://upload.wikimedia.org/") {
        if let Some(имя) = файл.rsplit('/').next().filter(|s| !s.is_empty()) {
            return format!(
                "https://commons.wikimedia.org/wiki/Special:FilePath/{имя}?width={}",
                crate::МИНИ_W
            );
        }
    }
    // Flickr держит размер прямо в имени файла: _b — 1024 px, _z — 640 px,
    // _n — 320 px. Было _n, и карточка в 604 px растягивала его вдвое; _z
    // ровно МИНИ_W.
    if файл.contains("staticflickr.com") {
        if let Some(без) = файл.strip_suffix("_b.jpg") {
            return format!("{без}_z.jpg");
        }
    }
    // Прочие провайдеры: сойдёт и оригинал — ужимать его всё равно нам.
    файл.to_string()
}

/// Параметры сужения выдачи Openverse, собранные из фильтров.
fn сужение_openverse(ф: &Фильтры) -> String {
    let mut out = String::new();
    match ф.размер {
        Размер::Крупные => out.push_str("&size=large"),
        Размер::Средние => out.push_str("&size=medium,large"),
        Размер::Любые => {}
    }
    match ф.ориентация {
        Ориентация::Широкие => out.push_str("&aspect_ratio=wide"),
        Ориентация::Любая => {}
    }
    match ф.род {
        Род::Рисунки => out.push_str("&category=illustration"),
        Род::Фотографии => out.push_str("&category=photograph"),
        Род::Любой => {}
    }
    out
}

fn openverse(
    страница: u32,
    ширина: u32,
    высота: u32,
    запрос: &str,
    фильтры: &Фильтры,
) -> Result<Vec<Находка>, String> {
    // page_size=20 — потолок для анонима: с 21 API отвечает 401, а не режет
    // выдачу. Пустой запрос допустим, отдельная «сортировка по умолчанию»,
    // как у wallhaven, здесь не нужна.
    //
    // size=large и aspect_ratio=wide стоят по умолчанию не для красоты:
    // Openverse — фотобанк, и без них в выдачу лезут вертикальные снимки и
    // мелочь, которую на широкий экран не растянуть. С ними ширина находок
    // начинается от ~1400 px. Снять их можно фильтрами — когда по узкому
    // запросу в крупных нашлась пара картинок.
    let url = format!(
        "https://api.openverse.org/v1/images/?page_size=20{}&page={страница}&q={}",
        сужение_openverse(фильтры),
        закодировать(запрос)
    );
    let тело = curl_текст(&url).ok_or("openverse не ответил")?;
    let json: serde_json::Value =
        serde_json::from_str(&тело).map_err(|e| format!("openverse: непонятный ответ ({e})"))?;

    let список = json
        .get("results")
        .and_then(|v| v.as_array())
        .ok_or("openverse: в ответе нет списка")?;

    Ok(список
        .iter()
        .filter_map(|item| {
            let цель = item.get("url")?.as_str()?.to_string();

            // Аналог wallhaven-овского atleast, но мягче: там фильтровал сам
            // сервер и запас картинок был бездонный, здесь же строгое «не
            // мельче монитора» на 4K оставило бы от страницы пару находок.
            // Отсекаем только явную мелочь — вдвое меньше экрана; остальное
            // plx-wall кадрирует сам.
            let w = item.get("width").and_then(|v| v.as_u64()).unwrap_or(0);
            let h = item.get("height").and_then(|v| v.as_u64()).unwrap_or(0);
            if w * 2 < ширина as u64 || h * 2 < высота as u64 {
                return None;
            }

            let имя = item.get("id")?.as_str()?.to_string();
            Some(Находка { миниатюра: превью(&цель), цель, источник: Источник::Картинки, имя })
        })
        .collect())
}

/// Картинки прямо из Wikimedia Commons — запасной путь, когда Openverse
/// недоступен.
///
/// Зачем: Openverse не отвечает с российских адресов (проверено 19.08.2026 с
/// чистого IP — соединение не устанавливается вовсе, тогда как через VPN тот
/// же запрос проходит). Commons при этом открыт, а половина верха выдачи
/// Openverse и так вела на upload.wikimedia.org — то есть спрашиваем ровно у
/// того хранилища, откуда картинки всё равно приходили, только напрямую.
///
/// Фильтры сужения Openverse (size/aspect_ratio/category) здесь не
/// применяются: у Commons такого языка запросов нет. Мелочь и вертикальные
/// снимки отсекаются тем же порогом по ширине и высоте, что и в [`openverse`].
fn викимедиа(
    страница: u32,
    ширина: u32,
    высота: u32,
    запрос: &str,
) -> Result<Vec<Находка>, String> {
    // gsrnamespace=6 — только файлы, иначе в выдачу лезут статьи.
    // gsroffset листает страницы: на странице те же 20 находок, что у
    // Openverse, чтобы сетка выглядела одинаково.
    //
    // **iiurlwidth — ШИРИНА МОНИТОРА, а не 1920** (правка 25.08.2026, жалоба
    // «сделай без потери качества»). Раньше здесь стояло жёсткое 1920 с
    // обоснованием «оригиналы на Commons бывают по 50 МБ». На мониторе 2560 это
    // означало обои, растянутые с 1920 до 2560 — то есть ровно ту потерю
    // качества, которой не должно быть. Полсотни мегабайт мы всё равно не
    // качаем: оригинал берётся только когда он не больше [`ПРЕДЕЛ_ОРИГИНАЛА`],
    // иначе остаётся кадр под монитор (см. ниже).
    let сдвиг = (страница.saturating_sub(1)) * 20;
    let поиск = if запрос.trim().is_empty() { "wallpaper" } else { запрос };
    let кадр = ширина.clamp(1280, 7680);
    let url = format!(
        "https://commons.wikimedia.org/w/api.php?action=query&format=json\
         &generator=search&gsrnamespace=6&gsrlimit=20&gsroffset={сдвиг}&gsrsearch={}\
         &prop=imageinfo&iiprop=url%7Csize&iiurlwidth={кадр}",
        закодировать(поиск)
    );
    let тело = curl_текст(&url).ok_or("викимедиа не ответила")?;
    let json: serde_json::Value =
        serde_json::from_str(&тело).map_err(|e| format!("викимедиа: непонятный ответ ({e})"))?;

    // Пустая выдача — это не ошибка: у Commons просто нет ничего по запросу.
    let Some(страницы) = json.get("query").and_then(|q| q.get("pages")).and_then(|p| p.as_object())
    else {
        return Ok(Vec::new());
    };

    Ok(страницы
        .values()
        .filter_map(|item| {
            let инфо = item.get("imageinfo")?.as_array()?.first()?;

            let w = инфо.get("width").and_then(|v| v.as_u64()).unwrap_or(0);
            let h = инфо.get("height").and_then(|v| v.as_u64()).unwrap_or(0);
            if w * 2 < ширина as u64 || h * 2 < высота as u64 {
                return None;
            }

            // ОРИГИНАЛ, если он разумного веса, — иначе кадр под монитор.
            // Порядок именно такой: `thumburl` это пересжатая копия, и когда
            // оригинал всего пара мегабайт, брать вместо него JPEG-пережим
            // незачем. Вес отдаёт сам API (`iiprop=size`), лишнего запроса не
            // нужно; когда его нет — считаем файл тяжёлым и остаёмся на кадре.
            let вес = инфо.get("size").and_then(|v| v.as_u64()).unwrap_or(u64::MAX);
            let оригинал = инфо.get("url").and_then(|v| v.as_str());
            let кадр = инфо.get("thumburl").and_then(|v| v.as_str());
            let цель = match (оригинал, кадр) {
                (Some(o), _) if вес <= ПРЕДЕЛ_ОРИГИНАЛА => o,
                (_, Some(t)) => t,
                (Some(o), None) => o,
                (None, None) => return None,
            }
            .to_string();

            let имя = item.get("title")?.as_str()?.trim_start_matches("File:").to_string();
            Some(Находка { миниатюра: превью(&цель), цель, источник: Источник::Картинки, имя })
        })
        .collect())
}

/// Хост живых обоев.
///
/// **moewalls.com в августе 2026 переехал на motionbgs.com.** Старый домен
/// отвечает `303` с `location: motionbgs.com`, а прежнего пути WordPress-API
/// на новом домене нет вовсе — `/wp-json/…` отдаёт 404. Отсюда «сеть —
/// moewalls не ответил» и пустая вкладка живых обоев.
///
/// Нового API у сайта нет, поэтому список читается прямо из вёрстки. Она
/// простая и серверная: карточка — это `<a href=/имя>` с картинкой
/// `/i/c/364x205/media/<номер>/<имя>.jpg` и подписью в `<span class=ttl>`.
const ЖИВЫЕ: &str = "https://motionbgs.com";

/// Список живых обоев с motionbgs.
///
/// Адреса: главная `/`, дальше `/2/`, `/3/`…; раздел — `/tag:<метка>/` и
/// `/tag:<метка>/2/`. Своего поиска у сайта нет: `/search?q=nature` он сам
/// переводит в `/tag:nature/`, поэтому запрос мы превращаем в метку так же.
/// Несуществующая метка — честный 404, и тогда выдача пуста.
///
/// **Атрибуты в вёрстке БЕЗ КАВЫЧЕК** (`href=/имя`), поэтому разбор ищет
/// значение до пробела или `>`, а не до закрывающей кавычки.
fn motionbgs(страница: u32, запрос: &str, фильтры: &Фильтры) -> Result<Vec<Находка>, String> {
    let метка = if !запрос.is_empty() {
        Some(в_метку(запрос))
    } else {
        фильтры.раздел.as_ref().map(|(м, _)| м.clone())
    };

    let основа = match &метка {
        Some(м) => format!("{ЖИВЫЕ}/tag:{м}/"),
        None => format!("{ЖИВЫЕ}/"),
    };
    let url = if страница <= 1 { основа } else { format!("{основа}{страница}/") };

    let html = curl_текст(&url).ok_or("motionbgs не ответил")?;
    Ok(карточки(&html))
}

const ЖИВЫЕ_LW4F: &str = "https://livewallpapers4free.com";

/// Список живых обоев с livewallpapers4free.com.
///
/// Единственный из найденных сайтов живых обоев, у которого открыт
/// WordPress-API: `/wp-json/wp/v2/posts` отдаёт и заголовок, и адрес поста, и
/// картинку-превью (`yoast_head_json.og_image[0].url`) — то есть всё нужное
/// одним запросом и без разбора вёрстки, которая на таких сайтах меняется без
/// предупреждения. Поиск и страницы — штатные параметры того же API.
///
/// Чего API НЕ отдаёт — адрес самого ролика: он лежит на странице поста в
/// `<source src=…>`, и берётся уже при скачивании (см. [`скачать`]), одним
/// лишним запросом на выбранные обои.
fn lw4f(страница: u32, запрос: &str) -> Result<Vec<Находка>, String> {
    let mut url = format!(
        "{ЖИВЫЕ_LW4F}/wp-json/wp/v2/posts?per_page=24&page={}&_fields=title,link,yoast_head_json",
        страница.max(1),
    );
    if !запрос.is_empty() {
        url.push_str(&format!("&search={}", закодировать(запрос)));
    }
    let текст = curl_текст(&url).ok_or("livewallpapers4free не ответил")?;
    let разбор: serde_json::Value =
        serde_json::from_str(&текст).map_err(|e| format!("не разобрать ответ: {e}"))?;
    let Some(посты) = разбор.as_array() else {
        // За краем выдачи WordPress отвечает объектом с кодом ошибки, а не
        // массивом. Это не беда, это «страниц больше нет».
        return Ok(Vec::new());
    };

    let mut из = Vec::new();
    for пост in посты {
        let Some(ссылка) = пост["link"].as_str() else { continue };
        let превью = пост["yoast_head_json"]["og_image"]
            .get(0)
            .and_then(|к| к["url"].as_str());
        // Без превью карточку показать нечем — такой пост пропускаем целиком,
        // а не рисуем пустой прямоугольник.
        let Some(превью) = превью else { continue };
        let имя = пост["title"]["rendered"]
            .as_str()
            .map(снять_сущности)
            .unwrap_or_else(|| "wallpaper".to_string());
        из.push(Находка {
            миниатюра: превью.to_string(),
            цель: ссылка.to_string(),
            источник: Источник::Живые,
            имя,
        });
    }
    Ok(из)
}

/// Заголовки WordPress приходят с HTML-сущностями (`&#8211;`, `&amp;`), а из
/// заголовка строится ИМЯ ФАЙЛА. Без этого в каталоге обоев заводились файлы
/// вида `The_Silent_Ronin__8211__Where_Winds_Meet`.
fn снять_сущности(текст: &str) -> String {
    let mut из = String::with_capacity(текст.len());
    let mut хвост = текст;
    while let Some(i) = хвост.find('&') {
        из.push_str(&хвост[..i]);
        хвост = &хвост[i..];
        let Some(конец) = хвост.find(';').filter(|к| *к <= 8) else {
            из.push('&');
            хвост = &хвост[1..];
            continue;
        };
        let сущность = &хвост[1..конец];
        из.push(match сущность {
            "amp" => '&',
            "lt" => '<',
            "gt" => '>',
            "quot" | "#8220" | "#8221" => '"',
            "#039" | "#8217" | "#8216" => '\'',
            "nbsp" => ' ',
            // Числовые — по коду; всё прочее заменяем дефисом, потому что
            // дальше из строки всё равно делается имя файла.
            иное => иное
                .strip_prefix('#')
                .and_then(|ц| ц.parse::<u32>().ok())
                .and_then(char::from_u32)
                .unwrap_or('-'),
        });
        хвост = &хвост[конец + 1..];
    }
    из.push_str(хвост);
    из
}

/// Запрос человека -> метка сайта: строчными, пробелы дефисами, лишнее прочь.
fn в_метку(запрос: &str) -> String {
    let mut метка = String::new();
    for c in запрос.trim().to_lowercase().chars() {
        if c.is_alphanumeric() {
            метка.push(c);
        } else if !метка.ends_with('-') {
            метка.push('-');
        }
    }
    метка.trim_matches('-').to_string()
}

/// Миниатюра motionbgs в размер нашей карточки.
///
/// В вёрстке стоит `/i/c/364x205/…`, а карточка ленты — ~604×340: картинку
/// тянуло в 1.7 раза, и вся вкладка «Живые» выглядела мылом. Размер в адресе
/// сайт режет на лету под любой запрос (замер 27.09.2026: 364x205 — 9 КБ,
/// 640x360 — 22 КБ, оба честные WebP ровно своего размера), поэтому просим
/// ровно `МИНИ_W×МИНИ_H` — то, во что миниатюра всё равно ляжет.
fn превью_motionbgs(адрес: &str) -> String {
    let Some((до, после)) = адрес.split_once("/i/c/") else { return адрес.to_string() };
    let Some((размер, хвост)) = после.split_once('/') else { return адрес.to_string() };
    if !размер.contains('x') || !размер.bytes().all(|б| б.is_ascii_digit() || б == b'x') {
        return адрес.to_string();
    }
    format!("{до}/i/c/{}x{}/{хвост}", crate::МИНИ_W, crate::МИНИ_H)
}

/// Разбор списка обоев из вёрстки motionbgs.
///
/// Идём по ссылкам `<a … href=/имя …>`: внутри карточки лежит миниатюра
/// (`/i/c/364x205/media/<номер>/…`) и подпись. Ссылки без миниатюры — это
/// меню и метки, они отсеиваются сами.
fn карточки(html: &str) -> Vec<Находка> {
    let mut найдено = Vec::new();
    for кусок in html.split("<a ").skip(1) {
        // Кончается карточка на закрывающем теге; дальше уже соседняя.
        let кусок = кусок.split("</a>").next().unwrap_or(кусок);
        let Some(адрес) = значение(кусок, "href=") else { continue };
        if !адрес.starts_with('/') || адрес.starts_with("/tag:") || адрес.len() < 2 {
            continue;
        }
        let Some(картинка) = кусок
            .split("src=")
            .skip(1)
            .filter_map(значение_с_начала)
            .find(|адрес| адрес.contains("/i/c/") && адрес.contains("/media/"))
        else {
            continue;
        };

        let имя = адрес.trim_matches('/').to_string();
        найдено.push(Находка {
            миниатюра: format!("{ЖИВЫЕ}{}", превью_motionbgs(&картинка)),
            цель: format!("{ЖИВЫЕ}{адрес}"),
            источник: Источник::Живые,
            имя,
        });
    }
    найдено
}

/// Значение атрибута `ключ` в куске тега. Кавычки необязательны.
fn значение(кусок: &str, ключ: &str) -> Option<String> {
    let i = кусок.find(ключ)?;
    значение_с_начала(&кусок[i + ключ.len()..])
}

/// То же, но кусок уже начинается сразу после знака равенства.
fn значение_с_начала(хвост: &str) -> Option<String> {
    let хвост = хвост.trim_start();
    let (граница, хвост) = match хвост.chars().next()? {
        c @ ('"' | '\'') => (c, &хвост[1..]),
        _ => (' ', хвост),
    };
    let конец = хвост
        .find(|c: char| c == граница || (граница == ' ' && (c == '>' || c.is_whitespace())))
        .unwrap_or(хвост.len());
    let значение = &хвост[..конец];
    (!значение.is_empty()).then(|| значение.to_string())
}

/// Разделы moewalls (категории WordPress): номер и имя.
///
/// Спрашиваем сайт, а не держим список в коде: разделы там иногда добавляют.
/// Если сеть не ответила — берём замер от 14.08.2026, иначе меню фильтров
/// оказалось бы пустым ровно тогда, когда сеть и так барахлит.
pub fn разделы_живых() -> Vec<(String, String)> {
    // `4k` и `gifs` — не метки, а отдельные разделы сайта, но в адресе
    // ведут себя так же, поэтому в меню стоят рядом с метками.
    const ЗАПАС: [(&str, &str); 12] = [
        ("anime", "Аниме"), ("games", "Игры"), ("fantasy", "Фэнтези"),
        ("nature", "Природа"), ("space", "Космос"), ("cars", "Машины"),
        ("movies", "Кино"), ("abstract", "Абстракция"),
        ("pixel-art", "Пиксель-арт"), ("animal", "Животные"),
        ("4k", "4K"), ("gifs", "Гифки"),
    ];
    let запас = || {
        ЗАПАС.iter().map(|(м, имя)| (м.to_string(), имя.to_string())).collect::<Vec<_>>()
    };

    // Метки живут прямо на главной, отдельного списка у сайта нет.
    let Some(html) = curl_текст(&format!("{ЖИВЫЕ}/")) else { return запас() };

    let mut разделы: Vec<(String, String)> = Vec::new();
    for кусок in html.split("/tag:").skip(1) {
        let Some(метка) = кусок.split(['/', '"', '\'', ' ', '>']).next() else { continue };
        if метка.is_empty() || разделы.iter().any(|(м, _)| м == метка) {
            continue;
        }
        разделы.push((метка.to_string(), по_русски(&метка.replace('-', " "))));
    }

    if разделы.is_empty() {
        return запас();
    }
    // Разделов на главной под две сотни — в меню столько не нужно, оно
    // показывается одним списком rofi.
    разделы.truncate(40);
    разделы
}

