/// Куда moewalls отдаёт ПОЛНЫЙ файл обоев.
///
/// На странице поста лежит только превью (`*-preview.webm`, 1280×720@30 VP9) —
/// именно его мы и качали, отсюда «обои хуже, чем на сайте». Настоящий файл
/// раздаётся отдельной точкой, и её адрес в вёрстке не написан: кнопка
/// «Download Wallpaper» собирает его в `custom-wall.js` из перевёрнутых кусков
/// строк («moc.sllaweom.og» → `go.moewalls.com`), а сам файл называет не имя, а
/// непрозрачный токен в `data-url` у ссылки `id="moe-download"`.
///
/// Замер 14.08.2026 на furina-midnight-meadow: превью 1.4 МБ 1280×720@30 VP9,
/// полный файл 81 МБ **3840×2160@60 h264, 40 Мбит/с**.
const ПОЛНЫЙ_ФАЙЛ_MOEWALLS: &str = "https://go.moewalls.com/download.php?video=";

/// Адрес ПОЛНОГО файла на странице motionbgs.
///
/// В вёрстке есть две ссылки: `/dl/4k/<номер>` и `/dl/hd/<номер>`. Берём 4K,
/// его же сайт и показывает главной кнопкой. Проверено на `blue-eyes-
/// swordswoman`: `/dl/4k/9933/` отдаёт `video/mp4`, 9.4 МБ,
/// `content-disposition: …3840x2160.mp4`, тогда как на самой странице лежит
/// только превью `960x540`.
fn полный_файл_motionbgs(html: &str) -> Option<String> {
    for ключ in ["/dl/4k/", "/dl/hd/"] {
        if let Some(i) = html.find(ключ) {
            let хвост = &html[i + ключ.len()..];
            let номер: String = хвост.chars().take_while(|c| c.is_ascii_digit()).collect();
            if !номер.is_empty() {
                // Со слешем на конце: без него сайт отвечает 301 на него же.
                return Some(format!("{ЖИВЫЕ}{ключ}{номер}/"));
            }
        }
    }
    None
}

/// Токен полного файла со страницы поста: `<a id="moe-download" data-url="…">`.
///
/// Значение в атрибуте уже закодировано процентами (base64 с `+` и `/`), и
/// приделывать его к адресу надо КАК ЕСТЬ — второе кодирование сломает токен.
fn токен_полного_файла(html: &str) -> Option<String> {
    let ссылка = html.find("id=\"moe-download\"")?;
    // Атрибуты у этой ссылки идут и до, и после id, поэтому ищем data-url в
    // пределах самого тега, а не «дальше по странице».
    let тег = &html[ссылка..];
    let конец = тег.find('>')?;
    let тег = &тег[..конец];
    let i = тег.find("data-url")?;
    let хвост = &тег[i + "data-url".len()..];
    let хвост = хвост.trim_start().strip_prefix('=')?.trim_start();
    let кавычка = хвост.chars().next().filter(|c| *c == '"' || *c == '\'')?;
    let хвост = &хвост[1..];
    let конец = хвост.find(кавычка)?;
    let токен = &хвост[..конец];
    (!токен.is_empty()).then(|| токен.to_string())
}

/// Расширение по первым байтам файла.
///
/// Полный файл раздаётся как `application/octet-stream` и без имени в адресе,
/// поэтому «взять расширение из ссылки» тут не работает вовсе: у токена его
/// нет. А расширение нам нужно — по нему plx-wall решает, живые это обои или
/// картинка (см. `is_video`).
fn расширение_по_байтам(данные: &[u8]) -> Option<&'static str> {
    // ISO BMFF (mp4/mov): 4 байта длины, дальше «ftyp».
    if данные.len() > 12 && &данные[4..8] == b"ftyp" {
        return Some(if &данные[8..11] == b"qt " { "mov" } else { "mp4" });
    }
    // Matroska и webm — один контейнер, различаются в DocType.
    if данные.starts_with(&[0x1A, 0x45, 0xDF, 0xA3]) {
        let голова = &данные[..данные.len().min(4096)];
        return Some(if голова.windows(4).any(|w| w == b"webm") { "webm" } else { "mkv" });
    }
    if данные.starts_with(b"\x89PNG") { return Some("png") }
    if данные.starts_with(&[0xFF, 0xD8, 0xFF]) { return Some("jpg") }
    if данные.starts_with(b"GIF8") { return Some("gif") }
    if данные.len() > 12 && данные.starts_with(b"RIFF") && &данные[8..12] == b"WEBP" {
        return Some("webp");
    }
    None
}

/// Найти на странице обоев адрес ролика.
///
/// Это ЗАПАСНОЙ путь: превью мельче настоящего файла в разы, и берётся оно,
/// только если полного не нашлось (см. [`полный_файл_motionbgs`]). На
/// motionbgs превью размечено как `src=/media/<номер>/<имя>.960x540.mp4`
/// — **без кавычек**, поэтому значение берём до пробела или `>`; на старом
/// moewalls было `src="…-preview.webm"` в кавычках, и этот вид тоже
/// поддерживаем, чтобы разбор не зависел от того, чья страница пришла.
fn ролик_со_страницы(html: &str) -> Option<String> {
    let ключ = "src=";
    let mut хвост = html;
    while let Some(i) = хвост.find(ключ) {
        хвост = &хвост[i + ключ.len()..];
        let Some(адрес) = значение_с_начала(хвост) else { continue };
        let адрес = адрес.as_str();
        if (адрес.contains("preview") || адрес.contains("/media/"))
            && (адрес.ends_with(".webm") || адрес.ends_with(".mp4"))
        {
            return Some(if адрес.starts_with("http") {
                адрес.to_string()
            } else if адрес.starts_with('/') {
                format!("{ЖИВЫЕ}{адрес}")
            } else {
                format!("{ЖИВЫЕ}/{адрес}")
            });
        }
    }
    None
}

/// Ролик из тега `<source src="…">` — так размечены страницы
/// livewallpapers4free.
///
/// Отдельно от [`ролик_со_страницы`]: тот берёт только адреса, в которых есть
/// `preview` или `/media/` (приметы motionbgs и старого moewalls), а здесь
/// адрес обычный — `/wp-content/uploads/2026/08/…-VIDEO-zxcv.mp4`, и под то
/// правило он не подходит. Зато сам тег `<source>` — примета достаточная:
/// внутри `<video>` ничего кроме ролика не лежит.
///
/// Пробуется ПОСЛЕ полного файла motionbgs: у того качество выше, а на
/// страницах motionbgs `<source>` тоже встречается — но с превью.
///
/// Берётся ПЕРВЫЙ подходящий тег. Замер на lw4free: на странице обоев тег
/// `<source>` ровно один, а второй mp4 на той же странице (заставка сайта)
/// лежит вне тега и под правило не попадает. Если сайт когда-нибудь поставит
/// свою заставку в `<source>` выше ролика, здесь начнёт возвращаться она —
/// признака надёжнее, чем «первый source», у страницы нет.
fn ролик_из_source(html: &str) -> Option<String> {
    let mut хвост = html;
    while let Some(i) = хвост.find("<source") {
        хвост = &хвост[i + "<source".len()..];
        // Ищем src ВНУТРИ этого тега, а не где придётся дальше по странице.
        let конец = хвост.find('>').unwrap_or(хвост.len());
        let тег = &хвост[..конец];
        let Some(j) = тег.find("src=") else { continue };
        let Some(адрес) = значение_с_начала(&тег[j + "src=".len()..]) else { continue };
        if адрес.ends_with(".mp4") || адрес.ends_with(".webm") {
            return Some(адрес);
        }
    }
    None
}

/// Безопасное имя файла: у обоев в названии бывает что угодно.
fn безопасное(имя: &str) -> String {
    имя.chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '-' { c } else { '_' })
        .take(60)
        .collect()
}

/// Расширение из адреса — запасной путь, когда содержимое не опознано.
fn расширение_из_адреса(адрес: &str) -> Option<String> {
    адрес
        .rsplit('/')
        .next()?
        .rsplit_once('.')
        .map(|(_, e)| e)
        .filter(|e| e.len() <= 5 && e.chars().all(|c| c.is_ascii_alphanumeric()))
        .map(|e| e.to_lowercase())
}

/// Эти обои уже лежат в каталоге? Ищем по имени БЕЗ расширения: у полного
/// файла moewalls расширение заранее неизвестно (адрес — токен без имени), и
/// узнаётся оно только по скачанным байтам. Сравнивать с одним ожидаемым
/// именем, как раньше, значит качать 80 МБ повторно.
fn уже_скачано(каталог: &Path, имя: &str) -> Option<PathBuf> {
    let список = std::fs::read_dir(каталог).ok()?;
    for запись in список.flatten() {
        let путь = запись.path();
        if путь.file_stem().and_then(|s| s.to_str()) != Some(имя) {
            continue;
        }
        if запись.metadata().map(|m| m.len() > 0).unwrap_or(false) {
            return Some(путь);
        }
    }
    None
}

/// Ролик для живой карточки ленты (см. preview.rs) — скачанный в кэш.
///
/// Здесь нужен ровно обратный [`скачать`] выбор: не полный файл (4K, десятки
/// мегабайт), а то самое мелкое превью со страницы — 960×540, пара мегабайт.
/// Полный берём, только если превью на странице нет вовсе.
///
/// Качаем в файл, а не отдаём ffmpeg адрес: сеть у Ярика ходит через обход
/// (см. заголовки в [`качнуть`]), а ffmpeg пошёл бы мимо них. Заодно превью
/// переживает сеанс — на ту же карточку второй раз сеть не нужна.
pub fn ролик_превью(находка: &Находка) -> Option<PathBuf> {
    if находка.источник != Источник::Живые {
        return None;
    }
    let каталог = PathBuf::from(format!(
        "{}/.cache/plx-wall/preview",
        std::env::var("HOME").unwrap_or_else(|_| "/tmp".into()),
    ));
    let ключ = {
        use std::hash::{Hash, Hasher};
        let mut h = std::collections::hash_map::DefaultHasher::new();
        находка.цель.hash(&mut h);
        format!("{:016x}", h.finish())
    };
    if let Some(готовый) = уже_скачано(&каталог, &ключ) {
        return Some(готовый);
    }
    let html = curl_текст(&находка.цель)?;
    let адрес = ролик_со_страницы(&html).or_else(|| ролик_из_source(&html))?;
    let данные = curl_файл(&адрес).filter(|д| !д.is_empty())?;
    let расширение = расширение_по_байтам(&данные)
        .map(|e| e.to_string())
        .or_else(|| расширение_из_адреса(&адрес))
        .unwrap_or_else(|| "mp4".to_string());
    std::fs::create_dir_all(&каталог).ok()?;
    let путь = каталог.join(format!("{ключ}.{расширение}"));
    // Через временный файл: оборванная на полпути запись не должна потом
    // находиться `уже_скачано` как готовый ролик.
    let временный = каталог.join(format!(".{ключ}.part"));
    std::fs::write(&временный, &данные).ok()?;
    std::fs::rename(&временный, &путь).ok()?;
    Some(путь)
}

/// Скачивает выбранные обои в `каталог` и отдаёт путь к файлу.
///
/// У живых обоев берём ПОЛНЫЙ файл (см. [`ПОЛНЫЙ_ФАЙЛ`]), а не превью с
/// страницы: превью — это 720p@30, и на широком экране оно и выглядело
/// соответственно.
pub fn скачать(находка: &Находка, каталог: &Path) -> Result<PathBuf, String> {
    std::fs::create_dir_all(каталог).map_err(|e| format!("не создать каталог: {e}"))?;

    let имя = безопасное(&находка.имя);
    if let Some(готовый) = уже_скачано(каталог, &имя) {
        return Ok(готовый);
    }

    let файл = match находка.источник {
        Источник::Картинки => находка.цель.clone(),
        Источник::Живые => {
            let html = curl_текст(&находка.цель).ok_or("страница обоев не открылась")?;
            // Порядок проб: полный файл motionbgs, потом старая кнопка
            // moewalls (вдруг в списке обоев остались ссылки на неё), и
            // только затем превью со страницы — оно мельче в разы, но
            // лучше показать обои хуже, чем не показать вовсе.
            полный_файл_motionbgs(&html)
                .or_else(|| {
                    токен_полного_файла(&html).map(|т| format!("{ПОЛНЫЙ_ФАЙЛ_MOEWALLS}{т}"))
                })
                .or_else(|| ролик_из_source(&html))
                .or_else(|| ролик_со_страницы(&html))
                .ok_or("на странице не нашлось ролика")?
        }
    };

    let данные = curl_файл(&файл).ok_or("файл не скачался")?;
    if данные.is_empty() {
        return Err("сервер отдал пустой файл".into());
    }

    // Расширение — по содержимому: полный файл раздаётся как
    // application/octet-stream, и в адресе у него имени нет вовсе. А знать его
    // надо: по расширению plx-wall отличает живые обои от картинки.
    let расширение = расширение_по_байтам(&данные)
        .map(|e| e.to_string())
        .or_else(|| расширение_из_адреса(&файл))
        .unwrap_or_else(|| "bin".to_string());

    let путь = каталог.join(format!("{имя}.{расширение}"));
    std::fs::write(&путь, &данные).map_err(|e| format!("не записать файл: {e}"))?;

    Ok(путь)
}

