//! Обои из сети.
//!
//! Два источника, по одному на каждый род обоев:
//! - **openverse.org** — статичные картинки. Открытый JSON API без ключа.
//!   Стоит здесь вместо wallhaven.cc, который недоступен из России.
//!   Openverse — фотобанк CC-картинок, а не сборник обоев, поэтому выдачу
//!   приходится сужать фильтрами (см. [`openverse`]), а миниатюры брать не у
//!   него (см. [`превью`]).
//! - **moewalls.com** — живые обои. Открытого API у сайта нет, но он на
//!   WordPress, и его `/wp-json/wp/v2/posts` отдаёт список постов вместе с
//!   адресом картинки-превью (в поле `yoast_head_json.og_image`). Сам ролик
//!   ищем по странице поста — уже когда обои ВЫБРАЛИ, одним запросом.
//!
//! Почему адрес ролика не собирается по шаблону, хотя он предсказуемый
//! (`/wp-content/uploads/preview/<год>/<slug>-preview.webm`): год в адресе —
//! это год ЗАГРУЗКИ файла, а он не всегда совпадает с датой поста, и на
//! старых обоях шаблон промахивается. Один лишний запрос при скачивании
//! дешевле, чем «выбрал — не открылось».
//!
//! Ходим наружу через `curl`, а не через HTTP-клиент на Rust: в dwall нет ни
//! асинхронного рантайма, ни TLS-обвязки, и тащить их ради двух запросов —
//! это плюс полторы сотни зависимостей. Тем же способом (через процесс)
//! работает и декодер обоев, так что приём для этого кода не новый.
//!
//! ВАЖНО: всё здесь БЛОКИРУЮЩЕЕ и обязано вызываться из отдельного потока —
//! главный цикл не должен ждать сеть ни секунды.

use std::path::{Path, PathBuf};
use std::process::Command;

/// Представляемся браузером: moewalls отвечает на «непонятные» подписи
/// страницей-заглушкой, а не данными.
const БРАУЗЕР: &str =
    "Mozilla/5.0 (X11; Linux x86_64; rv:128.0) Gecko/20100101 Firefox/128.0";

/// Сколько ждать сеть. Больше нет смысла: при таком ожидании человек уже
/// закрыл меню.
const ЖДАТЬ: &str = "20";

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Источник {
    /// Статичные картинки, openverse.org.
    Картинки,
    /// Живые обои, moewalls.com.
    Живые,
}

/// Насколько крупные картинки просить у Openverse.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Размер {
    /// `size=large` — то, что годится на широкий экран без растягивания.
    Крупные,
    /// `size=medium,large` — когда в крупных нашлось слишком мало.
    Средние,
    /// Без ограничения. Мелочь всё равно отсеется по ширине (см. [`openverse`]).
    Любые,
}

/// Форма картинки.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Ориентация {
    /// `aspect_ratio=wide` — по умолчанию: вертикальные снимки на широкий
    /// экран не растянуть.
    Широкие,
    Любая,
}

/// Род картинки у Openverse: он всё-таки фотобанк, и рисунки с фотографиями
/// перемешаны.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Род {
    Любой,
    /// `category=illustration`.
    Рисунки,
    /// `category=photograph`.
    Фотографии,
}

/// Чем сортировать выдачу moewalls.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Порядок {
    /// `orderby=date` — свежие сверху. Так сайт показывает и сам.
    Свежие,
    /// `orderby=relevance`. WordPress принимает его ТОЛЬКО вместе с поиском:
    /// без `search` он отвечает ошибкой, поэтому без запроса не просим.
    Совпадение,
}

/// Чем сужена выдача. Значения по умолчанию — то, с чем dwall жил раньше
/// (крупные широкие картинки, все разделы moewalls, свежие сверху), поэтому
/// «сбросить» возвращает ровно прежнее поведение.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Фильтры {
    pub размер: Размер,
    pub ориентация: Ориентация,
    pub род: Род,
    /// Раздел moewalls: номер категории WordPress и её имя для показа.
    /// `None` — все разделы.
    pub раздел: Option<(u32, String)>,
    pub порядок: Порядок,
}

impl Default for Фильтры {
    fn default() -> Self {
        Фильтры {
            размер: Размер::Крупные,
            ориентация: Ориентация::Широкие,
            род: Род::Любой,
            раздел: None,
            порядок: Порядок::Свежие,
        }
    }
}

impl Фильтры {
    /// Хоть что-то сужено? По этому меню подсвечивает кнопку — объяснить
    /// словами, почему в сетке не «всё подряд», в dwall нечем.
    pub fn заданы(&self) -> bool {
        *self != Фильтры::default()
    }
}

/// Одна находка в выдаче.
#[derive(Clone, Debug)]
pub struct Находка {
    /// Адрес миниатюры — её и показываем в сетке.
    pub миниатюра: String,
    /// Что скачивать. У openverse это сразу файл, у moewalls — страница
    /// поста, на которой ещё надо найти ролик (см. [`скачать`]).
    pub цель: String,
    pub источник: Источник,
    /// Из чего строить имя файла.
    pub имя: String,
}

fn curl(url: &str) -> Option<Vec<u8>> {
    let out = Command::new("curl")
        .args(["-sL", "--max-time", ЖДАТЬ, "-A", БРАУЗЕР, url])
        .output()
        .ok()?;
    out.status.success().then_some(out.stdout)
}

fn curl_текст(url: &str) -> Option<String> {
    String::from_utf8(curl(url)?).ok()
}

/// Проценты вместо всего, что не буква и не цифра.
///
/// Свой, а не крейт: нужно ровно это, а запрос приходит от человека и может
/// содержать что угодно — пробелы, кириллицу, амперсанд. Без кодирования
/// амперсанд разрезал бы запрос на два параметра, а пробел вовсе сломал бы
/// адрес.
fn закодировать(текст: &str) -> String {
    let mut out = String::with_capacity(текст.len());
    for b in текст.as_bytes() {
        match b {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => {
                out.push(*b as char)
            }
            b' ' => out.push('+'),
            _ => out.push_str(&format!("%{b:02X}")),
        }
    }
    out
}

/// Список обоев со страницы `страница` (нумерация с единицы).
///
/// `запрос` пустой — показываем то, что источник считает лучшим.
pub fn список(
    источник: Источник,
    страница: u32,
    ширина: u32,
    высота: u32,
    запрос: &str,
    фильтры: &Фильтры,
) -> Result<Vec<Находка>, String> {
    match источник {
        Источник::Картинки => openverse(страница, ширина, высота, запрос, фильтры),
        Источник::Живые => moewalls(страница, запрос, фильтры),
    }
}

/// Адрес уменьшенной картинки для сетки.
///
/// Собственные миниатюры Openverse (`/v1/images/<id>/thumb/`) НЕ используем по
/// двум причинам сразу. Первая: они попросту не работают — на проверке
/// 09.08.2026 все до одной ответили 424 «Thumbnail unavailable from provider».
/// Вторая, более принципиальная: анонимный доступ к API ограничен 20 запросами
/// в минуту и 200 в сутки, а одна страница сетки — это 20 миниатюр, то есть
/// минутный лимит выбирался бы целиком на первой же странице.
///
/// Поэтому уменьшенный вариант просим прямо у хранилища провайдера, и к самому
/// Openverse остаётся ОДИН запрос на страницу — за списком.
fn превью(файл: &str) -> String {
    // Wikimedia (весь верх выдачи с нашими фильтрами — из неё). Произвольную
    // ширину через /thumb/ она больше не отдаёт: 400 и «Use thumbnail sizes
    // listed on ...». Документированный Special:FilePath с width работает и
    // отдаёт ~100 КБ вместо нескольких мегабайт оригинала.
    if файл.starts_with("https://upload.wikimedia.org/") {
        if let Some(имя) = файл.rsplit('/').next().filter(|s| !s.is_empty()) {
            return format!("https://commons.wikimedia.org/wiki/Special:FilePath/{имя}?width=640");
        }
    }
    // Flickr держит размер прямо в имени файла: _b — 1024 px, _n — 320 px.
    if файл.contains("staticflickr.com") {
        if let Some(без) = файл.strip_suffix("_b.jpg") {
            return format!("{без}_n.jpg");
        }
    }
    // Прочие провайдеры: сойдёт и оригинал — ужимать его всё равно нам.
    файл.to_string()
}

/// Параметры сужения выдачи Openverse, собранные из фильтров.
fn сужение_openverse(ф: &Фильтры) -> String {
    let mut out = String::new();
    match ф.размер {
        Размер::Крупные => out.push_str("&size=large"),
        Размер::Средние => out.push_str("&size=medium,large"),
        Размер::Любые => {}
    }
    match ф.ориентация {
        Ориентация::Широкие => out.push_str("&aspect_ratio=wide"),
        Ориентация::Любая => {}
    }
    match ф.род {
        Род::Рисунки => out.push_str("&category=illustration"),
        Род::Фотографии => out.push_str("&category=photograph"),
        Род::Любой => {}
    }
    out
}

fn openverse(
    страница: u32,
    ширина: u32,
    высота: u32,
    запрос: &str,
    фильтры: &Фильтры,
) -> Result<Vec<Находка>, String> {
    // page_size=20 — потолок для анонима: с 21 API отвечает 401, а не режет
    // выдачу. Пустой запрос допустим, отдельная «сортировка по умолчанию»,
    // как у wallhaven, здесь не нужна.
    //
    // size=large и aspect_ratio=wide стоят по умолчанию не для красоты:
    // Openverse — фотобанк, и без них в выдачу лезут вертикальные снимки и
    // мелочь, которую на широкий экран не растянуть. С ними ширина находок
    // начинается от ~1400 px. Снять их можно фильтрами — когда по узкому
    // запросу в крупных нашлась пара картинок.
    let url = format!(
        "https://api.openverse.org/v1/images/?page_size=20{}&page={страница}&q={}",
        сужение_openverse(фильтры),
        закодировать(запрос)
    );
    let тело = curl_текст(&url).ok_or("openverse не ответил")?;
    let json: serde_json::Value =
        serde_json::from_str(&тело).map_err(|e| format!("openverse: непонятный ответ ({e})"))?;

    let список = json
        .get("results")
        .and_then(|v| v.as_array())
        .ok_or("openverse: в ответе нет списка")?;

    Ok(список
        .iter()
        .filter_map(|item| {
            let цель = item.get("url")?.as_str()?.to_string();

            // Аналог wallhaven-овского atleast, но мягче: там фильтровал сам
            // сервер и запас картинок был бездонный, здесь же строгое «не
            // мельче монитора» на 4K оставило бы от страницы пару находок.
            // Отсекаем только явную мелочь — вдвое меньше экрана; остальное
            // dwall кадрирует сам.
            let w = item.get("width").and_then(|v| v.as_u64()).unwrap_or(0);
            let h = item.get("height").and_then(|v| v.as_u64()).unwrap_or(0);
            if w * 2 < ширина as u64 || h * 2 < высота as u64 {
                return None;
            }

            let имя = item.get("id")?.as_str()?.to_string();
            Some(Находка { миниатюра: превью(&цель), цель, источник: Источник::Картинки, имя })
        })
        .collect())
}

fn moewalls(страница: u32, запрос: &str, фильтры: &Фильтры) -> Result<Vec<Находка>, String> {
    let раздел = match &фильтры.раздел {
        Some((id, _)) => format!("&categories={id}"),
        None => String::new(),
    };
    // orderby=relevance WordPress принимает только вместе с search: без
    // запроса он отвечает ошибкой и выдача пропадает совсем. Поэтому без
    // запроса порядок всегда «свежие».
    let порядок = match фильтры.порядок {
        Порядок::Совпадение if !запрос.is_empty() => "&orderby=relevance",
        _ => "&orderby=date",
    };
    let url = format!(
        "https://moewalls.com/wp-json/wp/v2/posts?per_page=24&page={страница}\
         {раздел}{порядок}&search={}",
        закодировать(запрос)
    );
    let тело = curl_текст(&url).ok_or("moewalls не ответил")?;
    let json: serde_json::Value =
        serde_json::from_str(&тело).map_err(|e| format!("moewalls: непонятный ответ ({e})"))?;

    let список = json.as_array().ok_or("moewalls: в ответе нет списка")?;

    Ok(список
        .iter()
        .filter_map(|item| {
            let миниатюра = item
                .pointer("/yoast_head_json/og_image/0/url")?
                .as_str()?
                .to_string();
            let цель = item.get("link")?.as_str()?.to_string();
            let имя = item.get("slug").and_then(|v| v.as_str()).unwrap_or("moewalls").to_string();
            Some(Находка { миниатюра, цель, источник: Источник::Живые, имя })
        })
        .collect())
}

/// Разделы moewalls (категории WordPress): номер и имя.
///
/// Спрашиваем сайт, а не держим список в коде: разделы там иногда добавляют.
/// Если сеть не ответила — берём замер от 14.08.2026, иначе меню фильтров
/// оказалось бы пустым ровно тогда, когда сеть и так барахлит.
pub fn разделы_живых() -> Vec<(u32, String)> {
    const ЗАПАС: [(u32, &str); 12] = [
        (18, "Аниме"), (20, "Игры"), (19, "Фэнтези"), (21, "Пейзаж"),
        (26, "Фантастика"), (22, "Быт"), (23, "Кино"), (1, "Абстракция"),
        (27, "Транспорт"), (25, "Пиксель-арт"), (24, "Прочее"), (17, "Животные"),
    ];
    let запас = || ЗАПАС.iter().map(|(id, имя)| (*id, имя.to_string())).collect::<Vec<_>>();

    // orderby=count — самые населённые разделы сверху: список выбирают
    // глазами, и «Аниме» с 4838 обоями должно быть первым, а не «Животные».
    let Some(тело) = curl_текст(
        "https://moewalls.com/wp-json/wp/v2/categories?per_page=100&orderby=count&order=desc",
    ) else {
        return запас();
    };
    let Ok(json) = serde_json::from_str::<serde_json::Value>(&тело) else {
        return запас();
    };
    let Some(список) = json.as_array() else { return запас() };

    let разделы: Vec<(u32, String)> = список
        .iter()
        .filter_map(|c| {
            let id = c.get("id")?.as_u64()? as u32;
            let имя = c.get("name")?.as_str()?;
            // Пустые разделы в списке не нужны — выбрать их можно, а обоев
            // там нет.
            (c.get("count").and_then(|v| v.as_u64()).unwrap_or(0) > 0)
                .then(|| (id, по_русски(имя)))
        })
        .collect();

    if разделы.is_empty() { запас() } else { разделы }
}

/// Имена разделов на сайте английские, а меню у dwall русское. Незнакомое
/// оставляем как есть: новый раздел лучше показать по-английски, чем не
/// показать вовсе.
fn по_русски(имя: &str) -> String {
    match имя {
        "Anime" => "Аниме",
        "Games" => "Игры",
        "Fantasy" => "Фэнтези",
        "Landscape" => "Пейзаж",
        "Sci-fi" => "Фантастика",
        "Lifestyle" => "Быт",
        "Movies" => "Кино",
        "Abstract" => "Абстракция",
        "Vehicle" => "Транспорт",
        "Pixel Art" => "Пиксель-арт",
        "Others" => "Прочее",
        "Animal" => "Животные",
        прочее => прочее,
    }
    .to_string()
}

/// Пункты меню фильтров: подпись и то состояние, которое получится при выборе.
///
/// Меню показывает fuzzel (в самом dwall шрифта нет), поэтому здесь только
/// строки. Каждая строка — ОДНА готовая настройка, а не «подменю»: выбрал —
/// применилось, открыл снова — поменял следующее. Так весь разговор с
/// человеком укладывается в один вызов fuzzel.
///
/// Действующее значение помечено галочкой: список видно целиком, и по нему
/// сразу понятно, чем сужена выдача.
pub fn меню_фильтров(
    источник: Источник,
    текущие: &Фильтры,
    разделы: &[(u32, String)],
    есть_запрос: bool,
) -> Vec<(String, Фильтры)> {
    let mut пункты: Vec<(String, Фильтры)> = Vec::new();
    let mut добавить = |подпись: String, выбран: bool, состояние: Фильтры| {
        пункты.push((
            if выбран { format!("{подпись}  ✓") } else { подпись },
            состояние,
        ));
    };

    match источник {
        Источник::Картинки => {
            for (имя, значение) in [
                ("крупные", Размер::Крупные),
                ("средние и крупные", Размер::Средние),
                ("любые", Размер::Любые),
            ] {
                добавить(
                    format!("Размер: {имя}"),
                    текущие.размер == значение,
                    Фильтры { размер: значение, ..текущие.clone() },
                );
            }
            for (имя, значение) in [
                ("широкие", Ориентация::Широкие),
                ("любая", Ориентация::Любая),
            ] {
                добавить(
                    format!("Ориентация: {имя}"),
                    текущие.ориентация == значение,
                    Фильтры { ориентация: значение, ..текущие.clone() },
                );
            }
            for (имя, значение) in [
                ("любой", Род::Любой),
                ("рисунки", Род::Рисунки),
                ("фотографии", Род::Фотографии),
            ] {
                добавить(
                    format!("Род: {имя}"),
                    текущие.род == значение,
                    Фильтры { род: значение, ..текущие.clone() },
                );
            }
        }
        Источник::Живые => {
            добавить(
                "Раздел: все".to_string(),
                текущие.раздел.is_none(),
                Фильтры { раздел: None, ..текущие.clone() },
            );
            for (id, имя) in разделы {
                добавить(
                    format!("Раздел: {имя}"),
                    текущие.раздел.as_ref().map(|(t, _)| *t) == Some(*id),
                    Фильтры { раздел: Some((*id, имя.clone())), ..текущие.clone() },
                );
            }
            добавить(
                "Порядок: свежие".to_string(),
                текущие.порядок == Порядок::Свежие,
                Фильтры { порядок: Порядок::Свежие, ..текущие.clone() },
            );
            // Без запроса сортировать по совпадению не с чем, и WordPress на
            // такое отвечает ошибкой. Пункта, который ничего не делает, в
            // меню быть не должно.
            if есть_запрос {
                добавить(
                    "Порядок: по совпадению".to_string(),
                    текущие.порядок == Порядок::Совпадение,
                    Фильтры { порядок: Порядок::Совпадение, ..текущие.clone() },
                );
            }
        }
    }

    if текущие.заданы() {
        добавить("Сбросить фильтры".to_string(), false, Фильтры::default());
    }
    пункты
}

