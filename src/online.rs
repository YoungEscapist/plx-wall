/// Пункты меню фильтров: подпись и то состояние, которое получится при выборе.
///
/// Меню показывает rofi (в самом plx-wall шрифта нет), поэтому здесь только
/// строки. Каждая строка — ОДНА готовая настройка, а не «подменю»: выбрал —
/// применилось, открыл снова — поменял следующее. Так весь разговор с
/// человеком укладывается в один вызов rofi.
///
/// Действующее значение помечено галочкой: список видно целиком, и по нему
/// сразу понятно, чем сужена выдача.
pub fn меню_фильтров(
    источник: Источник,
    текущие: &Фильтры,
    разделы: &[(String, String)],
    есть_запрос: bool,
) -> Vec<(String, Фильтры)> {
    let mut пункты: Vec<(String, Фильтры)> = Vec::new();
    let mut добавить = |подпись: String, выбран: bool, состояние: Фильтры| {
        пункты.push((
            if выбран { format!("{подпись}  ✓") } else { подпись },
            состояние,
        ));
    };

    match источник {
        Источник::Картинки => {
            // Источник — первым: он решает, что вообще значат остальные пункты
            // (picsum и bing не знают ни поиска, ни рода, ни размера).
            for (имя, значение) in [
                ("авто", Провайдер::Авто),
                ("wallhaven", Провайдер::Wallhaven),
                ("openverse", Провайдер::Openverse),
                ("викимедиа", Провайдер::Викимедиа),
                ("picsum (без поиска)", Провайдер::Picsum),
                ("bing UHD (без поиска)", Провайдер::Bing),
                ("NASA ∞", Провайдер::Космос),
                ("искусство ∞", Провайдер::Искусство),
            ] {
                добавить(
                    format!("Источник: {имя}"),
                    текущие.провайдер == значение,
                    Фильтры { провайдер: значение, ..текущие.clone() },
                );
            }
            for (имя, значение) in [
                ("крупные", Размер::Крупные),
                ("средние и крупные", Размер::Средние),
                ("любые", Размер::Любые),
            ] {
                добавить(
                    format!("Размер: {имя}"),
                    текущие.размер == значение,
                    Фильтры { размер: значение, ..текущие.clone() },
                );
            }
            for (имя, значение) in [
                ("широкие", Ориентация::Широкие),
                ("любая", Ориентация::Любая),
            ] {
                добавить(
                    format!("Ориентация: {имя}"),
                    текущие.ориентация == значение,
                    Фильтры { ориентация: значение, ..текущие.clone() },
                );
            }
            for (имя, значение) in [
                ("любой", Род::Любой),
                ("рисунки", Род::Рисунки),
                ("фотографии", Род::Фотографии),
            ] {
                добавить(
                    format!("Род: {имя}"),
                    текущие.род == значение,
                    Фильтры { род: значение, ..текущие.clone() },
                );
            }
        }
        Источник::Живые => {
            добавить(
                "Раздел: все".to_string(),
                текущие.раздел.is_none(),
                Фильтры { раздел: None, ..текущие.clone() },
            );
            for (метка, имя) in разделы {
                добавить(
                    format!("Раздел: {имя}"),
                    текущие.раздел.as_ref().map(|(m, _)| m.as_str()) == Some(метка.as_str()),
                    Фильтры {
                        раздел: Some((метка.clone(), имя.clone())),
                        ..текущие.clone()
                    },
                );
            }
            // Порядка у motionbgs нет вовсе: сайт отдаёт только «свежие
            // сверху», отдельного параметра сортировки в адресах не
            // существует. Пункт, который ничего не делает, из меню убран —
            // раньше он был про `orderby` в WordPress-API moewalls.
            let _ = есть_запрос;
        }
    }

    // Цвет — общий для обоих источников: отбирают его не сайты, а мы сами по
    // миниатюрам, значит и работает он везде одинаково.
    добавить(
        "Цвет: любой".to_string(),
        текущие.цвет.is_none(),
        Фильтры { цвет: None, ..текущие.clone() },
    );
    for цвет in crate::palette::Цвет::ВСЕ {
        добавить(
            format!("Цвет: {}", цвет.имя()),
            текущие.цвет == Some(цвет),
            Фильтры { цвет: Some(цвет), ..текущие.clone() },
        );
    }

    if текущие.заданы() {
        добавить("Сбросить фильтры".to_string(), false, Фильтры::default());
    }
    пункты
}

