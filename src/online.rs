/// Куда moewalls отдаёт ПОЛНЫЙ файл обоев.
///
/// На странице поста лежит только превью (`*-preview.webm`, 1280×720@30 VP9) —
/// именно его мы и качали, отсюда «обои хуже, чем на сайте». Настоящий файл
/// раздаётся отдельной точкой, и её адрес в вёрстке не написан: кнопка
/// «Download Wallpaper» собирает его в `custom-wall.js` из перевёрнутых кусков
/// строк («moc.sllaweom.og» → `go.moewalls.com`), а сам файл называет не имя, а
/// непрозрачный токен в `data-url` у ссылки `id="moe-download"`.
///
/// Замер 14.08.2026 на furina-midnight-meadow: превью 1.4 МБ 1280×720@30 VP9,
/// полный файл 81 МБ **3840×2160@60 h264, 40 Мбит/с**.
const ПОЛНЫЙ_ФАЙЛ: &str = "https://go.moewalls.com/download.php?video=";

/// Токен полного файла со страницы поста: `<a id="moe-download" data-url="…">`.
///
/// Значение в атрибуте уже закодировано процентами (base64 с `+` и `/`), и
/// приделывать его к адресу надо КАК ЕСТЬ — второе кодирование сломает токен.
fn токен_полного_файла(html: &str) -> Option<String> {
    let ссылка = html.find("id=\"moe-download\"")?;
    // Атрибуты у этой ссылки идут и до, и после id, поэтому ищем data-url в
    // пределах самого тега, а не «дальше по странице».
    let тег = &html[ссылка..];
    let конец = тег.find('>')?;
    let тег = &тег[..конец];
    let i = тег.find("data-url")?;
    let хвост = &тег[i + "data-url".len()..];
    let хвост = хвост.trim_start().strip_prefix('=')?.trim_start();
    let кавычка = хвост.chars().next().filter(|c| *c == '"' || *c == '\'')?;
    let хвост = &хвост[1..];
    let конец = хвост.find(кавычка)?;
    let токен = &хвост[..конец];
    (!токен.is_empty()).then(|| токен.to_string())
}

/// Расширение по первым байтам файла.
///
/// Полный файл раздаётся как `application/octet-stream` и без имени в адресе,
/// поэтому «взять расширение из ссылки» тут не работает вовсе: у токена его
/// нет. А расширение нам нужно — по нему dwall решает, живые это обои или
/// картинка (см. `is_video`).
fn расширение_по_байтам(данные: &[u8]) -> Option<&'static str> {
    // ISO BMFF (mp4/mov): 4 байта длины, дальше «ftyp».
    if данные.len() > 12 && &данные[4..8] == b"ftyp" {
        return Some(if &данные[8..11] == b"qt " { "mov" } else { "mp4" });
    }
    // Matroska и webm — один контейнер, различаются в DocType.
    if данные.starts_with(&[0x1A, 0x45, 0xDF, 0xA3]) {
        let голова = &данные[..данные.len().min(4096)];
        return Some(if голова.windows(4).any(|w| w == b"webm") { "webm" } else { "mkv" });
    }
    if данные.starts_with(b"\x89PNG") { return Some("png") }
    if данные.starts_with(&[0xFF, 0xD8, 0xFF]) { return Some("jpg") }
    if данные.starts_with(b"GIF8") { return Some("gif") }
    if данные.len() > 12 && данные.starts_with(b"RIFF") && &данные[8..12] == b"WEBP" {
        return Some("webp");
    }
    None
}

/// Найти на странице поста moewalls адрес ролика.
///
/// Ищем `src="...preview....webm"` — так размечен проигрыватель на странице.
/// Адрес там относительный, поэтому приделываем схему и хост.
///
/// Это ЗАПАСНОЙ путь: превью мельче настоящего файла в разы, и берётся оно
/// только если полного не нашлось (см. [`токен_полного_файла`]).
fn ролик_со_страницы(html: &str) -> Option<String> {
    let ключ = "src=\"";
    let mut хвост = html;
    while let Some(i) = хвост.find(ключ) {
        хвост = &хвост[i + ключ.len()..];
        let Some(конец) = хвост.find('"') else { break };
        let адрес = &хвост[..конец];
        if адрес.contains("preview") && (адрес.ends_with(".webm") || адрес.ends_with(".mp4")) {
            return Some(if адрес.starts_with("http") {
                адрес.to_string()
            } else if let Some(хвост) = адрес.strip_prefix('/') {
                format!("https://moewalls.com/{хвост}")
            } else {
                format!("https://moewalls.com/{адрес}")
            });
        }
    }
    None
}

/// Безопасное имя файла: у обоев в названии бывает что угодно.
fn безопасное(имя: &str) -> String {
    имя.chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '-' { c } else { '_' })
        .take(60)
        .collect()
}

/// Расширение из адреса — запасной путь, когда содержимое не опознано.
fn расширение_из_адреса(адрес: &str) -> Option<String> {
    адрес
        .rsplit('/')
        .next()?
        .rsplit_once('.')
        .map(|(_, e)| e)
        .filter(|e| e.len() <= 5 && e.chars().all(|c| c.is_ascii_alphanumeric()))
        .map(|e| e.to_lowercase())
}

/// Эти обои уже лежат в каталоге? Ищем по имени БЕЗ расширения: у полного
/// файла moewalls расширение заранее неизвестно (адрес — токен без имени), и
/// узнаётся оно только по скачанным байтам. Сравнивать с одним ожидаемым
/// именем, как раньше, значит качать 80 МБ повторно.
fn уже_скачано(каталог: &Path, имя: &str) -> Option<PathBuf> {
    let список = std::fs::read_dir(каталог).ok()?;
    for запись in список.flatten() {
        let путь = запись.path();
        if путь.file_stem().and_then(|s| s.to_str()) != Some(имя) {
            continue;
        }
        if запись.metadata().map(|m| m.len() > 0).unwrap_or(false) {
            return Some(путь);
        }
    }
    None
}

/// Скачивает выбранные обои в `каталог` и отдаёт путь к файлу.
///
/// У живых обоев берём ПОЛНЫЙ файл (см. [`ПОЛНЫЙ_ФАЙЛ`]), а не превью с
/// страницы: превью — это 720p@30, и на широком экране оно и выглядело
/// соответственно.
pub fn скачать(находка: &Находка, каталог: &Path) -> Result<PathBuf, String> {
    std::fs::create_dir_all(каталог).map_err(|e| format!("не создать каталог: {e}"))?;

    let имя = безопасное(&находка.имя);
    if let Some(готовый) = уже_скачано(каталог, &имя) {
        return Ok(готовый);
    }

    let файл = match находка.источник {
        Источник::Картинки => находка.цель.clone(),
        Источник::Живые => {
            let html = curl_текст(&находка.цель).ok_or("страница обоев не открылась")?;
            match токен_полного_файла(&html) {
                Some(токен) => format!("{ПОЛНЫЙ_ФАЙЛ}{токен}"),
                // Разметку кнопки поменяли — обои всё равно отдадим, пусть и
                // превью. Лучше хуже, чем никак.
                None => ролик_со_страницы(&html).ok_or("на странице не нашлось ролика")?,
            }
        }
    };

    let данные = curl(&файл).ok_or("файл не скачался")?;
    if данные.is_empty() {
        return Err("сервер отдал пустой файл".into());
    }

    // Расширение — по содержимому: полный файл раздаётся как
    // application/octet-stream, и в адресе у него имени нет вовсе. А знать его
    // надо: по расширению dwall отличает живые обои от картинки.
    let расширение = расширение_по_байтам(&данные)
        .map(|e| e.to_string())
        .or_else(|| расширение_из_адреса(&файл))
        .unwrap_or_else(|| "bin".to_string());

    let путь = каталог.join(format!("{имя}.{расширение}"));
    std::fs::write(&путь, &данные).map_err(|e| format!("не записать файл: {e}"))?;

    Ok(путь)
}

