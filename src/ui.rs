    /// прошли. Ради этого сглаживание и считается от dt.
    #[test]
    fn путь_не_зависит_от_частоты_кадров() {
        let прогон = |шагов: u32, dt: f32| {
            let mut п = Плавно::новое(0.0, 0.2);
            п.к(1.0);
            for _ in 0..шагов {
                п.шаг(dt);
            }
            п.значение()
        };
        let редко = прогон(10, 0.02);
        let часто = прогон(40, 0.005);
        assert!((редко - часто).abs() < 0.01, "{редко} против {часто}");
    }
