/// Величина, которая догоняет цель, а не прыгает к ней.
///
/// Сглаживание экспоненциальное и посчитано ОТ ВРЕМЕНИ, а не от числа кадров:
/// `k = 1 − exp(−dt/τ)`. Наивное «текущее += (цель − текущее) * 0.2» на каждый
/// кадр выглядит одинаково только при постоянной частоте, а меню dwall
/// перерисовывается то по таймеру, то по событию мыши — и та же анимация шла
/// бы то быстрее, то медленнее.
#[derive(Clone, Copy, Debug)]
pub struct Плавно {
    текущее: f32,
    цель: f32,
    /// Постоянная времени в секундах: за неё расстояние до цели падает втрое.
    тау: f32,
}

impl Плавно {
    pub fn новое(значение: f32, тау: f32) -> Плавно {
        Плавно { текущее: значение, цель: значение, тау: тау.max(0.001) }
    }

    pub fn к(&mut self, цель: f32) {
        self.цель = цель;
    }

    /// Поставить значение немедленно, без анимации, — например когда меню
    /// открывается заново и «доезжать» неоткуда.
    pub fn сразу(&mut self, значение: f32) {
        self.текущее = значение;
        self.цель = значение;
    }

    pub fn значение(&self) -> f32 {
        self.текущее
    }

    pub fn цель(&self) -> f32 {
        self.цель
    }

    /// Идёт ли ещё движение. Порог не нулевой намеренно: экспонента к цели
    /// приближается вечно, и без порога меню перерисовывалось бы всегда.
    pub fn идёт(&self) -> bool {
        (self.цель - self.текущее).abs() > 0.002
    }

    /// Шаг на `dt` секунд. Возвращает `true`, если значение изменилось, —
    /// по этому ответу главный цикл решает, нужен ли ещё кадр.
    pub fn шаг(&mut self, dt: f32) -> bool {
        if !self.идёт() {
            // Дотягиваем вплотную: иначе у величины навсегда остаётся хвост в
            // тысячные, и «выключено» никогда не равно нулю ровно.
            if self.текущее != self.цель {
                self.текущее = self.цель;
                return true;
            }
            return false;
        }
        let k = 1.0 - (-dt / self.тау).exp();
        self.текущее += (self.цель - self.текущее) * k;
        true
    }
}

/// Что именно подсвечено. Ключ для [`Наведения`].
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum Что {
    Карта(usize),
    Вкладка(usize),
    Поиск,
    Фильтр,
    /// Кнопка-источник в ряду выбора API.
    Источник(usize),
    /// Стрелка листания: `false` — левая, `true` — правая.
    Стрелка(bool),
    /// Крестик удаления на карточке.
    Крестик(usize),
}

/// Подсветки под курсором — по одной величине на элемент.
///
/// Хранилищем, а не полем на элемент: элементы меню (карточки, кнопки,
/// источники) заводятся и исчезают при смене вкладки и прокрутке, и держать
/// их анимации рядом с ними значило бы терять состояние на каждом чихе.
#[derive(Default)]
pub struct Наведения {
    величины: HashMap<Что, Плавно>,
}

impl Наведения {
    /// Задать цель для элемента. Ко всем непомянутым в этом кадре элементам
    /// применяется 0 — см. [`Наведения::погасить_кроме`].
    pub fn к(&mut self, что: Что, цель: f32) {
        self.величины
            .entry(что)
            .or_insert_with(|| Плавно::новое(0.0, 0.09))
            .к(цель);
    }

    pub fn значение(&self, что: Что) -> f32 {
        self.величины.get(&что).map(|п| п.значение()).unwrap_or(0.0)
    }

    /// Погасить всё, кроме одного элемента (обычно — того, что под курсором).
    /// Так подсветка уходит с прежней карточки плавно, а не мгновенно.
    pub fn погасить_кроме(&mut self, кроме: Option<Что>) {
        for (ключ, п) in self.величины.iter_mut() {
            if Some(*ключ) != кроме {
                п.к(0.0);
            }
        }
    }

    /// Движется ли хоть одна подсветка.
    pub fn шевелится(&self) -> bool {
        self.величины.values().any(|п| п.идёт())
    }

    /// Шаг всех подсветок. `true` — что-то ещё движется.
    pub fn шаг(&mut self, dt: f32) -> bool {
        let mut движется = false;
        for п in self.величины.values_mut() {
            движется |= п.шаг(dt);
        }
        // Погасшие выбрасываем: иначе за сеанс здесь накопятся все карточки
        // всех выдач, по которым мышь когда-либо проезжала.
        self.величины
            .retain(|_, п| п.значение() > 0.001 || п.цель() > 0.001);
        движется
    }
}

/// Плавный вход-выход для долей 0..1: у краёв движение замедляется.
/// Экспонента сама по себе трогается резко, и без этого меню «выстреливало».
pub fn мягко(t: f32) -> f32 {
    let t = t.clamp(0.0, 1.0);
    t * t * (3.0 - 2.0 * t)
}

