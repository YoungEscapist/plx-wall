//! Рисовалка меню: смешение по альфе, сглаженные формы, текст и анимации.
//!
//! **Зачем понадобился отдельный модуль.** Меню plx-wall рисовалось одним
//! приёмом — `copy_from_slice` цвета в пиксель. Это не рисование, а
//! ПЕРЕЗАПИСЬ: полупрозрачный элемент поверх фона стирал фон вместо того,
//! чтобы просвечивать сквозь себя, скругления выходили ступеньками, а тени и
//! градиенты были невозможны в принципе. Всё, что здесь есть, — следствие
//! одного решения: рисовать со смешением.
//!
//! **ПИКСЕЛИ ПРЕМУЛЬТИПЛИЦИРОВАНЫ.** Wayland ждёт от `ARGB8888` именно этого:
//! цвет уже умножен на свою альфу. Класть в буфер «честный» цвет с отдельной
//! альфой — та самая грабля, от которой в parallax белели плашки; здесь она
//! проявилась бы как засветка полупрозрачного фона. Поэтому цвета в коде
//! задаются ОБЫЧНЫМИ (`0xCC101014` — это «цвет 0x101014 с альфой 0xCC»), а
//! умножение делает [`Цвет::из_argb`] ровно один раз, на входе.
//!
//! Порядок каналов в буфере — RGBA; в BGRA его переворачивает вызывающий
//! перед отправкой композитору (так было и раньше).

use std::collections::HashMap;
use std::sync::OnceLock;

// ── Цвет ────────────────────────────────────────────────────────────────────

/// Премультиплицированный цвет. Каналы 0..=255, `r,g,b` уже умножены на `a`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Цвет {
    pub r: u8,
    pub g: u8,
    pub b: u8,
    pub a: u8,
}

impl Цвет {
    pub const ПУСТО: Цвет = Цвет { r: 0, g: 0, b: 0, a: 0 };

    /// Из привычного `0xAARRGGBB` с НЕпремультиплицированным цветом.
    pub const fn из_argb(argb: u32) -> Цвет {
        let a = ((argb >> 24) & 0xFF) as u32;
        let r = ((argb >> 16) & 0xFF) as u32;
        let g = ((argb >> 8) & 0xFF) as u32;
        let b = (argb & 0xFF) as u32;
        // Округление к ближайшему, а не вниз: без него тёмные каналы
        // систематически теряют единицу и фон уходит в синеву.
        // (`на255` здесь не позвать — функция `const`, а та нет.)
        Цвет {
            r: ((r * a + 127) / 255) as u8,
            g: ((g * a + 127) / 255) as u8,
            b: ((b * a + 127) / 255) as u8,
            a: a as u8,
        }
    }

    /// Тот же цвет, но с прозрачностью, умноженной на `k` (0..=1).
    ///
    /// Работает прямо по премультиплицированным каналам — для них ослабление
    /// альфы это просто умножение всех четырёх, никакого деления обратно.
    pub fn с_прозрачностью(self, k: f32) -> Цвет {
        let k = k.clamp(0.0, 1.0);
        let м = |c: u8| (c as f32 * k + 0.5) as u8;
        Цвет { r: м(self.r), g: м(self.g), b: м(self.b), a: м(self.a) }
    }

    /// Смешать два цвета в пропорции `k`: 0 — первый, 1 — второй.
    pub fn между(self, друг: Цвет, k: f32) -> Цвет {
        let k = k.clamp(0.0, 1.0);
        let м = |a: u8, b: u8| (a as f32 + (b as f32 - a as f32) * k + 0.5) as u8;
        Цвет {
            r: м(self.r, друг.r),
            g: м(self.g, друг.g),
            b: м(self.b, друг.b),
            a: м(self.a, друг.a),
        }
    }
}

/// Деление на 255 с округлением — без самого деления.
///
/// Смешение вызывается по разу на канал на пиксель, то есть миллионы раз за
/// кадр, и деление здесь стоило заметной доли времени отрисовки. Тождество
/// точное для всех `x` до 65535, а больше в смешении и не бывает
/// (255×255 = 65025).
#[inline(always)]
fn на255(x: u32) -> u32 {
    let t = x + 128;
    (t + (t >> 8)) >> 8
}

/// Положить цвет на пиксель по правилу «источник поверх» (source-over).
///
/// Формула для премультиплицированных: `итог = верх + низ * (1 − a_верх)`.
#[inline]
pub fn смешать(буфер: &mut [u8], idx: usize, цвет: Цвет) {
    if цвет.a == 0 || idx + 3 >= буфер.len() {
        return;
    }
    if цвет.a == 255 {
        буфер[idx] = цвет.r;
        буфер[idx + 1] = цвет.g;
        буфер[idx + 2] = цвет.b;
        буфер[idx + 3] = 255;
        return;
    }
    let обратно = 255 - цвет.a as u32;
    let см = |верх: u8, низ: u8| -> u8 {
        (верх as u32 + на255(низ as u32 * обратно)).min(255) as u8
    };
    буфер[idx] = см(цвет.r, буфер[idx]);
    буфер[idx + 1] = см(цвет.g, буфер[idx + 1]);
    буфер[idx + 2] = см(цвет.b, буфер[idx + 2]);
    буфер[idx + 3] = см(цвет.a, буфер[idx + 3]);
}

// ── Формы ───────────────────────────────────────────────────────────────────

/// Полотно: буфер вместе со своим размером. Без него каждая рисующая функция
/// тащила бы `sw`/`sh` отдельными параметрами — так их было легко перепутать
/// местами, и один такой промах стоил бы косой картинки во всём меню.
pub struct Холст<'a> {
    pub пиксели: &'a mut [u8],
    pub ш: u32,
    pub в: u32,
    /// Сдвиг всего нарисованного. Им меню выезжает при открытии: вместо того
    /// чтобы прибавлять смещение к каждой из полусотни координат (и однажды
    /// забыть), оно прибавляется в одной точке — здесь.
    pub сдвиг_y: i32,
    /// Множитель прозрачности всего нарисованного, 0..=1. Им же меню и
    /// проявляется.
    pub общая_альфа: f32,
    /// Класть цвет ЗАМЕНОЙ, не смешивая.
    ///
    /// Годится ровно для первой заливки по чистому буферу — там смешивать не
    /// с чем, результат тождественно равен самому цвету, а арифметика
    /// смешения (миллион пикселей на кадр) уходит целиком. Включать где-либо
    /// ещё НЕЛЬЗЯ: полупрозрачное просто сотрёт то, что под ним.
    pub замена: bool,
    /// Прямоугольник `(x, y, ширина, высота)`, за который рисовать нельзя.
    ///
    /// Нужен ленте: при листании карточки едут вбок и наполовину выходят за
    /// её край — без обрезки они лезли бы на стрелки листания и за кромку
    /// меню. Задаётся в тех же координатах, что и рисование, ДО сдвига.
    pub обрезка: Option<(i32, i32, u32, u32)>,
}

impl<'a> Холст<'a> {
    pub fn новый(пиксели: &'a mut [u8], ш: u32, в: u32) -> Холст<'a> {
        Холст {
            пиксели,
            ш,
            в,
            сдвиг_y: 0,
            общая_альфа: 1.0,
            замена: false,
            обрезка: None,
        }
    }

    /// Границы по горизонтали, за которые рисовать нельзя: (от, до).
    #[inline]
    fn предел_x(&self) -> (i64, i64) {
        match self.обрезка {
            None => (0, self.ш as i64),
            Some((x, _, ш, _)) => (x as i64, x as i64 + ш as i64),
        }
    }

    /// Попадает ли строка в обрезку. Проверяется по координате ДО сдвига —
    /// обрезка задана в тех же координатах, что и рисование.
    #[inline]
    fn строка_видна(&self, y: i64) -> bool {
        match self.обрезка {
            None => true,
            Some((_, oy, _, oв)) => y >= oy as i64 && y < oy as i64 + oв as i64,
        }
    }

    /// Залить сплошной кусок строки одним цветом.
    ///
    /// Ради скорости: у сплошной заливки на каждую точку приходились расчёт
    /// смещения, две проверки границ и вызов функции — на полосе меню это
    /// миллион вызовов на кадр. Здесь границы считаются ОДИН раз на отрезок,
    /// а дальше идёт плотный проход по срезу.
    #[inline]
    fn строка(&mut self, x0: i64, x1: i64, y: i64, цвет: Цвет) {
        if !self.строка_видна(y) {
            return;
        }
        let (от, до) = self.предел_x();
        let (x0, x1) = (x0.max(от), x1.min(до));
        let y = y + self.сдвиг_y as i64;
        if y < 0 || y >= self.в as i64 || цвет.a == 0 {
            return;
        }
        let цвет = if self.общая_альфа >= 1.0 {
            цвет
        } else {
            цвет.с_прозрачностью(self.общая_альфа)
        };
        if цвет.a == 0 {
            return;
        }
        let x0 = x0.max(0) as usize;
        let x1 = (x1.min(self.ш as i64)).max(0) as usize;
        if x1 <= x0 {
            return;
        }
        let начало = (y as usize * self.ш as usize + x0) * 4;
        let конец = начало + (x1 - x0) * 4;
        let Some(кусок) = self.пиксели.get_mut(начало..конец) else { return };
        if self.замена || цвет.a == 255 {
            // Альфу берём у цвета, а не 255: в режиме замены она может быть
            // любой, и записать вместо неё непрозрачность значило бы сделать
            // стекло глухим.
            let образец = [цвет.r, цвет.g, цвет.b, цвет.a];
            for п in кусок.chunks_exact_mut(4) {
                п.copy_from_slice(&образец);
            }
            return;
        }
        let обратно = 255 - цвет.a as u32;
        let верх = [цвет.r, цвет.g, цвет.b, цвет.a];
        for п in кусок.chunks_exact_mut(4) {
            for i in 0..4 {
                п[i] = (верх[i] as u32 + на255(п[i] as u32 * обратно)).min(255) as u8;
            }
        }
    }

    #[inline]
    fn точка(&mut self, x: i64, y: i64, цвет: Цвет) {
        let (от, до) = self.предел_x();
        if x < от || x >= до || !self.строка_видна(y) {
            return;
        }
        let y = y + self.сдвиг_y as i64;
        if x < 0 || y < 0 || x >= self.ш as i64 || y >= self.в as i64 {
            return;
        }
        let цвет = if self.общая_альфа >= 1.0 {
            цвет
        } else {
            цвет.с_прозрачностью(self.общая_альфа)
        };
        let idx = ((y as u32 * self.ш + x as u32) * 4) as usize;
        смешать(self.пиксели, idx, цвет);
    }

    /// Скруглённый прямоугольник со сглаженными краями.
    ///
    /// Покрытие пикселя считается по расстоянию до формы, а не «попал/не
    /// попал»: в углу берётся расстояние до центра скругления и переводится в
    /// долю закраски на полосе шириной в пиксель. Отсюда ровные дуги вместо
    /// лесенки, которая была у прежней целочисленной заливки.
    pub fn скругл(&mut self, x: i32, y: i32, ш: u32, в: u32, r: u32, цвет: Цвет) {
        self.скругл_с(x, y, ш, в, r, |_| цвет);
    }

    /// То же, но цвет зависит от строки — этим рисуются вертикальные градиенты.
    pub fn скругл_с(
        &mut self,
        x: i32,
        y: i32,
        ш: u32,
        в: u32,
        r: u32,
        цвет: impl Fn(f32) -> Цвет,
    ) {
        if ш == 0 || в == 0 {
            return;
        }
        let rц = r.min(ш / 2).min(в / 2);
        let r = rц as f32;
        let (fx, fy) = (x as f32, y as f32);
        let (fш, fв) = (ш as f32, в as f32);
        for стр in 0..в {
            let цв = цвет(if в > 1 { стр as f32 / (в - 1) as f32 } else { 0.0 });
            if цв.a == 0 {
                continue;
            }
            let py = fy + стр as f32 + 0.5;
            // БЫСТРАЯ ДОРОГА, без неё меню не по карману. Дуги есть только в
            // четырёх углах, а корень до правки считался для КАЖДОГО пикселя
            // — на полосе 2432×444 это 15 мс на кадр, то есть почти целое
            // ядро на одну анимацию. Строки между углами заливаются целиком,
            // в угловых строках считается только по `rц` столбцов с краёв.
            let угловая = стр < rц || стр >= в - rц;
            let py_экр = (y + стр as i32) as i64;
            if !угловая {
                self.строка(x as i64, x as i64 + ш as i64, py_экр, цв);
                continue;
            }
            // Угловая строка: середина сплошная, дуги только по краям.
            self.строка(x as i64 + rц as i64, x as i64 + (ш - rц) as i64, py_экр, цв);
            for кол in (0..rц).chain((ш - rц)..ш) {
                let доля = покрытие(fx + кол as f32 + 0.5, py, fx, fy, fш, fв, r);
                if доля > 0.0 {
                    self.точка((x + кол as i32) as i64, py_экр, цв.с_прозрачностью(доля));
                }
            }
        }
    }

    /// Картинка, обрезанная по скруглению, — цвет каждой точки даёт `взять`.
    ///
    /// Миниатюра раньше клалась прямоугольником поверх скруглённой карточки,
    /// и её углы торчали за дугу четырьмя острыми уголками. Обрезка здесь
    /// того же рода, что и заливка: доля покрытия умножается на альфу.
    pub fn картинка(
        &mut self,
        x: i32,
        y: i32,
        ш: u32,
        в: u32,
        r: u32,
        взять: impl Fn(u32, u32) -> Цвет,
    ) {
        if ш == 0 || в == 0 {
            return;
        }
        let rц = r.min(ш / 2).min(в / 2);
        let r = rц as f32;
        let (fx, fy) = (x as f32, y as f32);
        let (fш, fв) = (ш as f32, в as f32);
        for стр in 0..в {
            let py = fy + стр as f32 + 0.5;
            // Та же быстрая дорога, что у заливки: дуги только в углах, и
            // считать покрытие для всей площади миниатюры незачем.
            let угловая = стр < rц || стр >= в - rц;
            let py_экр = (y + стр as i32) as i64;
            // Сплошная середина строки идёт плотным проходом по срезу: на неё
            // приходится почти вся площадь миниатюры, и вызов `точка` на
            // каждую точку (смещение, две проверки границ, ветвление) стоил
            // дороже, чем сама выборка цвета.
            let (к0, к1) = if угловая { (rц, ш - rц) } else { (0, ш) };
            self.строка_из(x, py_экр, к0, к1, стр, &взять);
            if угловая {
                for кол in (0..rц).chain((ш - rц)..ш) {
                    let доля = покрытие(fx + кол as f32 + 0.5, py, fx, fy, fш, fв, r);
                    if доля > 0.0 {
                        self.точка(
                            (x + кол as i32) as i64,
                            py_экр,
                            взять(кол, стр).с_прозрачностью(доля),
                        );
                    }
                }
            }
        }
    }

    /// Картинка, УЖЕ приведённая к нужному размеру: `src` — ровно `ш`×`в`
    /// точек RGBA, по четыре байта на точку.
    ///
    /// Отличается от [`картинка`] тем, что в середине строки нет ни
    /// замыкания, ни пересборки [`Цвет`]: непрозрачная точка при полной
    /// видимости копируется четырьмя байтами. Замер 04.09.2026 (одно ядро,
    /// три карточки 604×340): общий путь — 6.7 мс на кадр, этот — 1.6 мс.
    ///
    /// Дуги в углах считаются по-старому: там нужна доля покрытия, и
    /// экономить на сотне точек в четырёх углах незачем.
    pub fn картинка_готовая(
        &mut self,
        x: i32,
        y: i32,
        ш: u32,
        в: u32,
        r: u32,
        src: &[u8],
        непрозрачная: bool,
    ) {
        if ш == 0 || в == 0 || src.len() < (ш as usize * в as usize * 4) {
            return;
        }
        let rц = r.min(ш / 2).min(в / 2);
        let r = rц as f32;
        let (fx, fy) = (x as f32, y as f32);
        let (fш, fв) = (ш as f32, в as f32);
        let альфа = self.общая_альфа;
        for стр in 0..в {
            let py_экр = (y + стр as i32) as i64;
            if !self.строка_видна(py_экр) {
                continue;
            }
            let y_буф = py_экр + self.сдвиг_y as i64;
            if y_буф < 0 || y_буф >= self.в as i64 {
                continue;
            }
            let угловая = стр < rц || стр >= в - rц;
            let (к0, к1) = if угловая { (rц, ш - rц) } else { (0, ш) };
            // Границы отрезка считаем один раз на строку — внутри прохода не
            // остаётся ни одной проверки, кроме прозрачности точки.
            let (от, до) = self.предел_x();
            let первый = к0.max((от - x as i64).max(0) as u32);
            let последний = к1.min((до - x as i64).max(0) as u32);
            let строка_нач = y_буф as usize * self.ш as usize;
            let строка_src = стр as usize * ш as usize;
            // Непрозрачная картинка при полной видимости — это ровно memcpy
            // строки: ни смешивать, ни смотреть на приёмник не нужно. Замер:
            // так три карточки 604×340 укладываются вчетверо быстрее, чем
            // проходом по точкам (даже без единого умножения в нём).
            if непрозрачная && альфа >= 1.0 && последний > первый {
                let si = (строка_src + первый as usize) * 4;
                let di = (строка_нач + (x + первый as i32) as usize) * 4;
                let длина = ((последний - первый) as usize) * 4;
                if si + длина <= src.len() && di + длина <= self.пиксели.len() {
                    self.пиксели[di..di + длина].copy_from_slice(&src[si..si + длина]);
                    if !угловая {
                        continue;
                    }
                }
            }
            for кол in первый..последний {
                let si = (строка_src + кол as usize) * 4;
                let s = &src[si..si + 4];
                let di = (строка_нач + (x + кол as i32) as usize) * 4;
                if s[3] == 255 && альфа >= 1.0 {
                    // Самый частый случай: непрозрачные обои в полностью
                    // открытом меню. Ни умножений, ни чтения приёмника.
                    if di + 3 < self.пиксели.len() {
                        self.пиксели[di..di + 4].copy_from_slice(s);
                    }
                    continue;
                }
                let цв = Цвет { r: s[0], g: s[1], b: s[2], a: s[3] };
                let цв = if альфа >= 1.0 { цв } else { цв.с_прозрачностью(альфа) };
                смешать(self.пиксели, di, цв);
            }
            if угловая {
                let py = fy + стр as f32 + 0.5;
                for кол in (0..rц).chain((ш - rц)..ш) {
                    let доля = покрытие(fx + кол as f32 + 0.5, py, fx, fy, fш, fв, r);
                    if доля <= 0.0 {
                        continue;
                    }
                    let si = (строка_src + кол as usize) * 4;
                    let s = &src[si..si + 4];
                    let цв = Цвет { r: s[0], g: s[1], b: s[2], a: s[3] };
                    self.точка(
                        (x + кол as i32) as i64,
                        py_экр,
                        цв.с_прозрачностью(доля * альфа.min(1.0)),
                    );
                }
            }
        }
    }

    /// Готовая картинка `иш`×`ив`, положенная в прямоугольник `ш`×`в` ДРУГОГО
    /// размера — БИЛИНЕЙНО, по заранее посчитанным таблицам.
    ///
    /// Нужна ленте с глубиной: карточка позади уменьшена, и её размер меняется
    /// на каждом кадре листания.
    ///
    /// **05.09.2026: была ближайшая точка, стала билинейная.** Прежний комментарий
    /// здесь утверждал, что на масштабе 0.6…1.0 ближайшая точка от усреднения
    /// «отличается неразличимо». Это неверно, и заметно это именно на таком
    /// масштабе: при коэффициенте около 0.8 ближайшая точка выбрасывает каждую
    /// пятую строку и каждый пятый столбец ИСХОДНИКА — на фотографии это рвёт
    /// провода, ветки и любую тонкую линию в пунктир, а на кадрах листания
    /// узор ещё и ползёт (Ярик 05.09.2026: «превью обоев грузятся в плохом
    /// качестве»). Никакого «мыла» при этом нет — есть зубцы, и потому
    /// поднимать разрешение миниатюр было бы лечением не той болезни.
    ///
    /// Цена — четыре выборки вместо одной. Это НЕ те миллисекунды, из-за
    /// которых лента когда-то лагала: усреднение по площади (`под_карточку`)
    /// на масштабе 0.8 берёт переменное число точек с делением на каждой,
    /// а здесь их ровно четыре и целочисленные сдвиги. Полный размер по-прежнему
    /// уходит в `картинка_готовая` одним memcpy на строку, и передняя карточка
    /// ленты — а она всегда в масштабе 1.0 — не платит вовсе.
    ///
    /// Таблицы строк и столбцов считаются ОДИН раз на карточку, а не на строку:
    /// это деление на точку, и на трёх карточках оно уже заметно (та же причина,
    /// по которой они посчитаны в `draw_thumbnail`).
    #[allow(clippy::too_many_arguments)]
    pub fn картинка_готовая_масштаб(
        &mut self,
        x: i32,
        y: i32,
        ш: u32,
        в: u32,
        r: u32,
        src: &[u8],
        иш: u32,
        ив: u32,
        непрозрачная: bool,
        затемнение: f32,
    ) {
        use rayon::prelude::*;
        if ш == 0 || в == 0 || иш == 0 || ив == 0 || src.len() < (иш as usize * ив as usize * 4) {
            return;
        }
        // Размер совпал — общий путь дешевле: там строка идёт одним memcpy.
        if ш == иш && в == ив && затемнение <= 0.0 {
            self.картинка_готовая(x, y, ш, в, r, src, непрозрачная);
            return;
        }
        // Таблица выборки по оси: пара соседних точек исходника и вес второй
        // из них в 1/256 долях. Центр точки назначения переводится в центр
        // исходника (отсюда ±0.5) — без этой поправки картинка уезжает на
        // полпикселя, и при листании края карточки заметно дрожат.
        let таблица = |длина: u32, исход: u32| -> Vec<(u32, u32, u32)> {
            let к = исход as f64 / длина as f64;
            (0..длина)
                .map(|i| {
                    let s = ((i as f64 + 0.5) * к - 0.5).max(0.0);
                    let p0 = (s.floor() as u32).min(исход - 1);
                    let p1 = (p0 + 1).min(исход - 1);
                    let вес = ((s - p0 as f64) * 256.0).round().clamp(0.0, 256.0) as u32;
                    (p0, p1, вес)
                })
                .collect()
        };
        let столбцы = таблица(ш, иш);
        let ряды = таблица(в, ив);
        // Пелена глубины кладётся ЗДЕСЬ ЖЕ, множителем на цвет, а не вторым
        // проходом `скругл` поверх готовой картинки: тот проход смешивал
        // каждую точку дальней карточки ещё раз и стоил почти столько же,
        // сколько сама выборка. Цвета у нас предумноженные, и чёрная пелена с
        // долей s над картинкой — это ровно умножение всех каналов на (1 − s);
        // альфа непрозрачной карточки остаётся 255, как и было после смешения.
        let свет = ((1.0 - затемнение.clamp(0.0, 1.0)) * 256.0).round() as u32;
        let затемнять = свет < 256;
        // Одна билинейная выборка. Отдельной замыканием, потому что нужна двум
        // путям — сплошной середине строки и её скруглённым углам; раньше углы
        // брали точку по своей формуле, и на дуге карточки был виден шов.
        //
        // Каналы смешиваются ПАРАМИ в одном u32 (R и B в масках 0x00FF00FF,
        // G и A — сдвинутые на байт): вес не больше 256, и произведение канала
        // на него помещается в свои 16 бит, не залезая в соседний. Это четыре
        // умножения на точку вместо двенадцати и никаких побайтовых индексов —
        // замер 27.09.2026: пять ужатых карточек в один поток 14.5 мс по
        // каналам против нескольких миллисекунд так.
        // Исходник читаем словами, а не по байту: четыре байта с проверкой
        // границ на каждом — это шестнадцать проверок на точку назначения.
        // Буфер из Vec<u8> на деле выровнен; если вдруг нет — медленный путь.
        // SAFETY: любой набор байт — допустимый u32.
        let (голова, слова, _) = unsafe { src.align_to::<u32>() };
        let словами = голова.is_empty();
        let точка_ист = |i: usize| -> u32 {
            if словами {
                u32::from_le(слова[i >> 2])
            } else {
                u32::from_le_bytes([src[i], src[i + 1], src[i + 2], src[i + 3]])
            }
        };
        let выборка = |кол: usize, стр0: u32, стр1: u32, вес_y: u32| -> [u8; 4] {
            let (к0, к1, вес_x) = столбцы[кол];
            let верх = стр0 as usize * иш as usize;
            let низ = стр1 as usize * иш as usize;
            let вв = точка_ист((верх + к0 as usize) * 4);
            let вп = точка_ист((верх + к1 as usize) * 4);
            let нв = точка_ист((низ + к0 as usize) * 4);
            let нп = точка_ист((низ + к1 as usize) * 4);
            let в_ = смесь_пар(вв, вп, вес_x);
            let н_ = смесь_пар(нв, нп, вес_x);
            let mut т = смесь_пар(в_, н_, вес_y);
            if затемнять {
                let rb = ((т & 0x00FF_00FF) * свет >> 8) & 0x00FF_00FF;
                let g = (((т >> 8) & 0xFF) * свет >> 8) & 0xFF;
                т = rb | (g << 8) | (т & 0xFF00_0000);
            }
            т.to_le_bytes()
        };
        let rц = r.min(ш / 2).min(в / 2);
        let rf = rц as f32;
        let (fx, fy) = (x as f32, y as f32);
        let (fш, fв) = (ш as f32, в as f32);
        let альфа = self.общая_альфа;
        let (от, до) = self.предел_x();
        let обрезка = self.обрезка;
        let сдвиг = self.сдвиг_y as i64;
        let ширина_буф = self.ш as usize;

        // Строки буфера, в которые карточка вообще попадает. Дальше они
        // считаются ПАРАЛЛЕЛЬНО: каждая строка назначения зависит только от
        // исходника и таблиц, пишет только в себя — делить нечего. Именно эта
        // функция и была фазой «карточки» в замере (7.6 мс из 11 на кадр, замер
        // 27.09.2026 на харнессе), а на мониторе 200 Гц кадру отведено 5 мс.
        let y0 = (y as i64 + сдвиг).max(0);
        let y1 = (y as i64 + в as i64 + сдвиг).min(self.в as i64);
        if y1 <= y0 {
            return;
        }
        let строка_байт = ширина_буф * 4;
        let кусок = &mut self.пиксели[y0 as usize * строка_байт..y1 as usize * строка_байт];
        кусок.par_chunks_mut(строка_байт).enumerate().for_each(|(н, строка)| {
            let y_буф = y0 + н as i64;
            let py_экр = y_буф - сдвиг;
            if let Some((_, oy, _, oв)) = обрезка {
                if py_экр < oy as i64 || py_экр >= oy as i64 + oв as i64 {
                    return;
                }
            }
            let стр = (py_экр - y as i64) as u32;
            let (стр0, стр1, вес_y) = ряды[стр as usize];
            let угловая = стр < rц || стр >= в - rц;
            let (к0, к1) = if угловая { (rц, ш - rц) } else { (0, ш) };
            let первый = к0.max((от - x as i64).max(0) as u32);
            let последний = к1.min((до - x as i64).max(0) as u32);
            for кол in первый..последний {
                let канал = выборка(кол as usize, стр0, стр1, вес_y);
                let di = (x + кол as i32) as usize * 4;
                if непрозрачная && канал[3] == 255 && альфа >= 1.0 {
                    if di + 3 < строка.len() {
                        строка[di..di + 4].copy_from_slice(&канал);
                    }
                    continue;
                }
                let цв = Цвет { r: канал[0], g: канал[1], b: канал[2], a: канал[3] };
                let цв = if альфа >= 1.0 { цв } else { цв.с_прозрачностью(альфа) };
                смешать(строка, di, цв);
            }
            if угловая {
                let py = fy + стр as f32 + 0.5;
                for кол in (0..rц).chain((ш - rц)..ш) {
                    let px = x as i64 + кол as i64;
                    if px < от || px >= до || px < 0 || px >= ширина_буф as i64 {
                        continue;
                    }
                    let доля = покрытие(fx + кол as f32 + 0.5, py, fx, fy, fш, fв, rf);
                    if доля <= 0.0 {
                        continue;
                    }
                    let s = выборка(кол as usize, стр0, стр1, вес_y);
                    let цв = Цвет { r: s[0], g: s[1], b: s[2], a: s[3] };
                    let цв = цв.с_прозрачностью(доля * альфа.min(1.0));
                    смешать(строка, px as usize * 4, цв);
                }
            }
        });
    }

    /// Кусок строки картинки: цвет у каждой точки свой, но границы и смещение
    /// считаются один раз на отрезок.
    fn строка_из(
        &mut self,
        x: i32,
        y_экр: i64,
        к0: u32,
        к1: u32,
        стр: u32,
        взять: &impl Fn(u32, u32) -> Цвет,
    ) {
        if !self.строка_видна(y_экр) {
            return;
        }
        let y = y_экр + self.сдвиг_y as i64;
        if y < 0 || y >= self.в as i64 || к1 <= к0 {
            return;
        }
        // Обрезаем отрезок по холсту и по обрезке ДО прохода, чтобы внутри не
        // проверять ни то ни другое.
        let (от, до) = self.предел_x();
        let первый = к0.max((от - x as i64).max(0) as u32);
        let последний = к1.min((до - x as i64).max(0) as u32);
        if последний <= первый {
            return;
        }
        let альфа = self.общая_альфа;
        let строка_нач = y as usize * self.ш as usize;
        for кол in первый..последний {
            let цв = взять(кол, стр);
            let цв = if альфа >= 1.0 { цв } else { цв.с_прозрачностью(альфа) };
            if цв.a == 0 {
                continue;
            }
            let idx = (строка_нач + (x + кол as i32) as usize) * 4;
            смешать(self.пиксели, idx, цв);
        }
    }

    /// Обводка скруглённого прямоугольника изнутри, толщиной `толщина`.
    pub fn кант(&mut self, x: i32, y: i32, ш: u32, в: u32, r: u32, толщина: f32, цвет: Цвет) {
        if ш == 0 || в == 0 {
            return;
        }
        let rц = r.min(ш / 2).min(в / 2);
        let r = rц as f32;
        let (fx, fy) = (x as f32, y as f32);
        let (fш, fв) = (ш as f32, в as f32);
        // Кант — это полоска в `толщина` точек по краю, но считался он ПО ВСЕЙ
        // площади: два корня на каждую точку карточки 604×340, и всё ради
        // ободка. Замер 04.09.2026: на нём одном уходило больше пяти
        // миллисекунд на кадр — вдвое больше, чем на все обои в ленте.
        // Середину пропускаем: там разность двух покрытий тождественно ноль.
        let полоса = (толщина.ceil() as u32 + 1).max(1);
        let край = rц.max(полоса);
        for стр in 0..в {
            let py = fy + стр as f32 + 0.5;
            let по_краю = стр < край || стр + край >= в;
            for кол in 0..ш {
                if !по_краю && кол >= полоса && кол + полоса < ш {
                    continue;
                }
                let px = fx + кол as f32 + 0.5;
                let снаружи = покрытие(px, py, fx, fy, fш, fв, r);
                if снаружи <= 0.0 {
                    continue;
                }
                // Кант — это разность двух форм: внешней и той же, вжатой
                // внутрь на толщину. Так он одинаково ровно ложится и на
                // прямых сторонах, и на дугах.
                let внутри = покрытие(
                    px,
                    py,
                    fx + толщина,
                    fy + толщина,
                    (fш - толщина * 2.0).max(0.0),
                    (fв - толщина * 2.0).max(0.0),
                    (r - толщина).max(0.0),
                );
                let доля = (снаружи - внутри).clamp(0.0, 1.0);
                if доля > 0.0 {
                    self.точка(
                        (x + кол as i32) as i64,
                        (y + стр as i32) as i64,
                        цвет.с_прозрачностью(доля),
                    );
                }
            }
        }
    }

    /// Мягкая тень под формой: та же скруглённая форма, размытая наружу.
    ///
    /// Считается не свёрткой (она стоила бы полного прохода по площади на
    /// каждый пиксель ядра), а по расстоянию до формы: тень — это функция
    /// «насколько далеко снаружи», и падать ей достаточно по гладкой кривой.
    /// Для мягкого ореола под меню этого хватает, а стоит он одного прохода.
    pub fn тень(&mut self, x: i32, y: i32, ш: u32, в: u32, r: u32, разлёт: u32, цвет: Цвет) {
        if ш == 0 || в == 0 || разлёт == 0 {
            return;
        }
        let rц = r.min(ш / 2).min(в / 2) as i32;
        let r = rц as f32;
        let разлёт_f = разлёт as f32;
        let (fx, fy) = (x as f32, y as f32);
        let (fш, fв) = (ш as f32, в as f32);
        let от = разлёт as i32;
        for стр in -от..(в as i32 + от) {
            let py = fy + стр as f32 + 0.5;
            // Внутренность формы тень не рисует (там расстояние ноль), но до
            // правки корень для неё всё равно считался — а это почти вся
            // площадь. Пропускаем её сразу.
            let внутри_по_вертикали = стр >= rц && стр < в as i32 - rц;
            for кол in -от..(ш as i32 + от) {
                if внутри_по_вертикали && кол >= rц && кол < ш as i32 - rц {
                    continue;
                }
                let px = fx + кол as f32 + 0.5;
                let d = расстояние(px, py, fx, fy, fш, fв, r);
                if d <= 0.0 || d >= разлёт_f {
                    continue;
                }
                // Квадратичное затухание: у самой формы тень плотная, к краю
                // разлёта сходит на нет без заметной ступеньки.
                let k = 1.0 - d / разлёт_f;
                self.точка(
                    (x + кол) as i64,
                    (y + стр) as i64,
                    цвет.с_прозрачностью(k * k),
                );
            }
        }
    }
}

/// Знаковое расстояние от точки до скруглённого прямоугольника: 0 внутри,
/// больше нуля снаружи.
#[inline]
fn расстояние(px: f32, py: f32, x: f32, y: f32, ш: f32, в: f32, r: f32) -> f32 {
    // Приводим к задаче «расстояние до прямоугольника, вжатого на r»: у
    // скруглённого прямоугольника это ровно оно минус r.
    let cx = (x + r).max(px.min(x + ш - r));
    let cy = (y + r).max(py.min(y + в - r));
    let (dx, dy) = (px - cx, py - cy);
    ((dx * dx + dy * dy).sqrt() - r).max(0.0)
}

/// Смешать две точки RGBA (байты в порядке памяти, прочитанные как
/// little-endian u32) с весом второй `w` из 256 — по два канала за умножение.
#[inline(always)]
fn смесь_пар(a: u32, b: u32, w: u32) -> u32 {
    let обр = 256 - w;
    let rb = (((a & 0x00FF_00FF) * обр + (b & 0x00FF_00FF) * w + 0x0080_0080) >> 8) & 0x00FF_00FF;
    let ga = ((((a >> 8) & 0x00FF_00FF) * обр + ((b >> 8) & 0x00FF_00FF) * w + 0x0080_0080) >> 8)
        & 0x00FF_00FF;
    rb | (ga << 8)
}

/// Доля пикселя, накрытая формой: 1 внутри, 0 снаружи, дробь на границе.
#[inline]
fn покрытие(px: f32, py: f32, x: f32, y: f32, ш: f32, в: f32, r: f32) -> f32 {
    if ш <= 0.0 || в <= 0.0 {
        return 0.0;
    }
    if px < x - 1.0 || py < y - 1.0 || px > x + ш + 1.0 || py > y + в + 1.0 {
        return 0.0;
    }
    // По прямым сторонам сглаживать нечего — там граница ложится по целому
    // пикселю; вся дробь набегает от дуг в углах.
    let d = расстояние(px, py, x, y, ш, в, r);
    let края = (px - x).min(x + ш - px).min(py - y).min(в + y - py);
    if края < 0.0 {
        return 0.0;
    }
    (1.0 - d).clamp(0.0, 1.0)
}

