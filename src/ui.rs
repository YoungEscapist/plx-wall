const ОБЫЧНЫЙ: &[u8] = include_bytes!("../assets/Nunito-Regular.ttf");
const ПОЛУЖИРНЫЙ: &[u8] = include_bytes!("../assets/Nunito-SemiBold.ttf");

#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum Начертание {
    Обычное,
    Полужирное,
}

struct Шрифты {
    обычный: fontdue::Font,
    полужирный: fontdue::Font,
}

fn шрифты() -> &'static Шрифты {
    static ШРИФТЫ: OnceLock<Шрифты> = OnceLock::new();
    ШРИФТЫ.get_or_init(|| {
        let собрать = |данные: &[u8]| {
            fontdue::Font::from_bytes(данные, fontdue::FontSettings::default())
                .expect("шрифт вшит в бинарь и обязан разбираться")
        };
        Шрифты { обычный: собрать(ОБЫЧНЫЙ), полужирный: собрать(ПОЛУЖИРНЫЙ) }
    })
}

/// Растеризованный глиф: покрытие 0..=255 и куда его класть.
struct Глиф {
    ш: usize,
    в: usize,
    сдвиг_x: i32,
    сдвиг_y: i32,
    аванс: f32,
    краска: Vec<u8>,
}

/// Кеш глифов. Меню перерисовывается целиком на каждый кадр анимации, а
/// растеризация одного размера одного символа — работа, которую незачем
/// делать шестьдесят раз в секунду.
fn кеш() -> &'static std::sync::Mutex<HashMap<(char, u32, Начертание), std::sync::Arc<Глиф>>> {
    static КЕШ: OnceLock<
        std::sync::Mutex<HashMap<(char, u32, Начертание), std::sync::Arc<Глиф>>>,
    > = OnceLock::new();
    КЕШ.get_or_init(|| std::sync::Mutex::new(HashMap::new()))
}

fn глиф(с: char, кегль: u32, н: Начертание) -> std::sync::Arc<Глиф> {
    if let Some(г) = кеш().lock().unwrap().get(&(с, кегль, н)) {
        return г.clone();
    }
    let шрифт = match н {
        Начертание::Обычное => &шрифты().обычный,
        Начертание::Полужирное => &шрифты().полужирный,
    };
    let (м, краска) = шрифт.rasterize(с, кегль as f32);
    let г = std::sync::Arc::new(Глиф {
        ш: м.width,
        в: м.height,
        сдвиг_x: м.xmin,
        сдвиг_y: м.ymin,
        аванс: м.advance_width,
        краска,
    });
    кеш().lock().unwrap().insert((с, кегль, н), г.clone());
    г
}

/// Ширина строки в пикселях. Шрифт пропорциональный — считать её умножением
/// числа символов на что-либо НЕЛЬЗЯ, только складывая адвансы.
pub fn ширина_текста(текст: &str, кегль: u32, н: Начертание) -> u32 {
    let мера: f32 = текст.chars().map(|с| глиф(с, кегль, н).аванс).sum();
    мера.ceil().max(0.0) as u32
}

/// Высота строки: от базовой линии вверх на кегль. По ней выравнивают по
/// вертикали — считать по фактической краске нельзя, иначе строки «Ага» и
/// «повод» встали бы на разной высоте.
pub fn высота_текста(кегль: u32) -> u32 {
    кегль
}

impl<'a> Холст<'a> {
    /// Написать строку. `x`, `y` — левый верхний угол строки высотой
    /// `высота_текста(кегль)`.
    pub fn текст(&mut self, x: i32, y: i32, текст: &str, кегль: u32, н: Начертание, цвет: Цвет) {
        // Базовая линия: опускаем на кегль и приподнимаем на глубину
        // подстрочных элементов, чтобы «р» и «у» не выпадали за низ строки.
        let база = y + кегль as i32;
        let mut перо = x as f32;
        for с in текст.chars() {
            let г = глиф(с, кегль, н);
            let гx = перо as i32 + г.сдвиг_x;
            let гy = база - г.в as i32 - г.сдвиг_y;
            for стр in 0..г.в {
                for кол in 0..г.ш {
                    let доля = г.краска[стр * г.ш + кол];
                    if доля == 0 {
                        continue;
                    }
                    self.точка(
                        (гx + кол as i32) as i64,
                        (гy + стр as i32) as i64,
                        цвет.с_прозрачностью(доля as f32 / 255.0),
                    );
                }
            }
            перо += г.аванс;
        }
    }

    /// Написать строку по центру прямоугольника.
    pub fn текст_по_центру(
        &mut self,
        x: i32,
        y: i32,
        ш: u32,
        в: u32,
        текст: &str,
        кегль: u32,
        н: Начертание,
        цвет: Цвет,
    ) {
        let тш = ширина_текста(текст, кегль, н);
        let тв = высота_текста(кегль);
        self.текст(
            x + (ш as i32 - тш as i32) / 2,
            y + (в as i32 - тв as i32) / 2,
            текст,
            кегль,
            н,
            цвет,
        );
    }
}

