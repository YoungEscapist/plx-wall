//! Палитра из обоев.
//!
//! Идея всей затеи: цвет живёт в ОДНОМ месте — в 16 цветах ANSI-палитры
//! терминала. Обои меняются → dwall пересчитывает палитру и рассылает её
//! escape-последовательностями во все живые pty. Всё, что рисует себя
//! обычными ANSI-цветами (cmatrix, fastfetch, starship, tuimus), меняет вид
//! само, без перезапуска и без единой строчки в их конфигах.
//!
//! Что получается на выходе:
//! - `~/.cache/dwall/palette.json` — для тех, кто хочет цвета явно (tuimus);
//! - `~/.cache/dwall/palette.sh`   — то же для шелла;
//! - `~/.config/ghostty/colors`    — новые окна ghostty стартуют уже в теме;
//! - OSC 4/10/11/12 во все `/dev/pts/*` — УЖЕ ОТКРЫТЫЕ окна перекрашиваются.
//!
//! Почему цвета не берутся из картинки «как есть»: тогда красный в терминале
//! перестал бы быть красным, и вывод `git diff` или `ls` читался бы наугад.
//! Поэтому оттенки ANSI сдвигаются к тону обоев лишь частично (см. СДВИГ), а
//! насыщенность и светлота выравниваются — цвета остаются узнаваемыми, но
//! вся палитра явно принадлежит одной картинке.

use std::io::Write;

/// Насколько круг ANSI повёрнут к тону обоев. 1.0 — полностью: опорный
/// «красный» садится ровно на тон обоев, и ни один цвет не остаётся возле
/// своего исходного места.
///
/// Раньше здесь было 0.28 с потолком в 22°, то есть каждый цвет лишь
/// подкрашивался, оставаясь узнаваемо красным или синим. По просьбе — палитра
/// теперь принадлежит обоям целиком.
const СДВИГ: f32 = 1.0;

/// Во сколько раз сжат разброс тонов вокруг тона обоев.
///
/// Это то, что удерживает затею от вырождения. Простое «тянуть каждый цвет к
/// тону обоев на 100%» сводит все шесть опор В ОДНУ ТОЧКУ круга, а светлота и
/// насыщенность у них общие (0.52 и база) — то есть красный, зелёный и синий
/// стали бы ПОПИКСЕЛЬНО одинаковыми, и `ls`, `git diff`, подсветка синтаксиса
/// перестали бы различаться вовсе.
///
/// Поэтому круг не схлопывается, а поворачивается целиком и сжимается: при
/// 0.55 шесть цветов занимают дугу около 165° вокруг тона обоев. Каждый ушёл
/// от исходного далеко, но между собой они по-прежнему различимы.
///
/// 1.0 — обычный круг, просто повёрнутый; 0.0 — полное схлопывание (см. выше,
/// так делать нельзя).
///
/// 0.28: при 0.55 шесть цветов расходились на ±100° от тона обоев, и дальние
/// от якоря — синий с голубым — оказывались в чужой семье. Это заметно на
/// логотипе NixOS в fastfetch: он нарисован ровно ANSI 4 и 6, и при широком
/// разбросе не выглядел цветом обоев вовсе. Сейчас вся шестёрка укладывается
/// в дугу около 85°, то есть в один тон с обоями, но ещё различима между
/// собой.
const РАЗБРОС: f32 = 0.28;

pub struct Palette {
    pub bg: [u8; 3],
    pub fg: [u8; 3],
    pub cursor: [u8; 3],
    pub accent: [u8; 3],
    pub sel_bg: [u8; 3],
    pub ansi: [[u8; 3]; 16],
}

// ── Цветовые преобразования ─────────────────────────────────────────────────

fn rgb2hsl(c: [u8; 3]) -> (f32, f32, f32) {
    let (r, g, b) = (c[0] as f32 / 255.0, c[1] as f32 / 255.0, c[2] as f32 / 255.0);
    let max = r.max(g).max(b);
    let min = r.min(g).min(b);
    let l = (max + min) / 2.0;
    if (max - min).abs() < 1e-6 {
        return (0.0, 0.0, l);
    }
    let d = max - min;
    let s = if l > 0.5 { d / (2.0 - max - min) } else { d / (max + min) };
    let h = if max == r {
        60.0 * (((g - b) / d) % 6.0)
    } else if max == g {
        60.0 * ((b - r) / d + 2.0)
    } else {
        60.0 * ((r - g) / d + 4.0)
    };
    ((h + 360.0) % 360.0, s, l)
}

fn hsl2rgb(h: f32, s: f32, l: f32) -> [u8; 3] {
    let h = ((h % 360.0) + 360.0) % 360.0;
    let c = (1.0 - (2.0 * l - 1.0).abs()) * s;
    let x = c * (1.0 - ((h / 60.0) % 2.0 - 1.0).abs());
    let m = l - c / 2.0;
    let (r, g, b) = match (h / 60.0) as u32 {
        0 => (c, x, 0.0),
        1 => (x, c, 0.0),
        2 => (0.0, c, x),
        3 => (0.0, x, c),
        4 => (x, 0.0, c),
        _ => (c, 0.0, x),
    };
    [
        (((r + m) * 255.0).clamp(0.0, 255.0)) as u8,
        (((g + m) * 255.0).clamp(0.0, 255.0)) as u8,
        (((b + m) * 255.0).clamp(0.0, 255.0)) as u8,
    ]
}

/// Куда переезжает опорный тон ANSI при обоях тона `тон`.
///
/// `опора` — исходный тон (красный 0°, зелёный 120° и так далее), `якорь` —
/// та опора, которая должна сесть ровно на тон обоев. Остальные раскладываются
/// вокруг неё, сохранив взаимный порядок, но со сжатым в [`РАЗБРОС`] раз
/// расстоянием.
///
/// Считаем от ЯКОРЯ, а не тянем каждый цвет к обоям по отдельности: только так
/// сохраняется взаимное расположение цветов. Поцветовое притягивание при
/// сильном коэффициенте сваливает их в кучу (см. РАЗБРОС).
fn сдвинуть_тон(опора: f32, тон: f32, якорь: f32) -> f32 {
    // Смещение опоры относительно якоря, приведённое к (-180, 180].
    let mut d = опора - якорь;
    if d > 180.0 { d -= 360.0; }
    if d < -180.0 { d += 360.0; }
    // Якорь уезжает на тон обоев целиком (СДВИГ), остальные держатся за него.
    let центр = якорь + (тон - якорь) * СДВИГ;
    (центр + d * РАЗБРОС + 360.0) % 360.0
}

fn hex(c: [u8; 3]) -> String {
    format!("#{:02x}{:02x}{:02x}", c[0], c[1], c[2])
}

/// `#rrggbb` → компоненты. Всё, что не подходит под форму, — не цвет.
fn разбор_hex(s: &str) -> Option<[u8; 3]> {
    let s = s.strip_prefix('#')?;
    if s.len() != 6 { return None; }
    Some([
        u8::from_str_radix(&s[0..2], 16).ok()?,
        u8::from_str_radix(&s[2..4], 16).ok()?,
        u8::from_str_radix(&s[4..6], 16).ok()?,
    ])
}

/// Насыщенность по HSV: 0 — серый, 1 — чистый цвет.
fn насыщенность(c: [u8; 3]) -> f32 {
    let max = c.iter().copied().max().unwrap_or(0) as f32;
    let min = c.iter().copied().min().unwrap_or(0) as f32;
    if max <= 0.0 { 0.0 } else { (max - min) / max }
}

/// Воспринимаемая светлота. Веса те же, что у Rec. 601: зелёный глазу заметно
/// ярче синего, и по среднему арифметическому шкала «фон → текст» вышла бы
/// переставленной.
fn светлота(c: [u8; 3]) -> f32 {
    0.299 * c[0] as f32 + 0.587 * c[1] as f32 + 0.114 * c[2] as f32
}

// ── Разбор картинки ─────────────────────────────────────────────────────────

/// Главный тон картинки и её средняя насыщенность.
///
/// Считается по гистограмме из 36 корзин по тону, вес пикселя — его
/// насыщенность: серый фон (небо, асфальт) почти ничего не вносит, а мелкое
/// яркое пятно заметно. Совсем тёмное и совсем белое выбрасываем — у них тон
/// шумный и определяется случайными единицами младших битов.
fn главный_тон(px: &[u8]) -> (f32, f32, f32) {
    const КОРЗИН: usize = 36;
    let mut вес = [0f32; КОРЗИН];
    let mut сумма_s = 0f32;
    let mut сумма_l = 0f32;
    let mut учтено = 0f32;

    for c in px.chunks_exact(4) {
        let (h, s, l) = rgb2hsl([c[0], c[1], c[2]]);
        if l < 0.06 || l > 0.95 { continue; }
        учтено += 1.0;
        сумма_s += s;
        сумма_l += l;
        if s < 0.12 { continue; }
        let i = ((h / 360.0 * КОРЗИН as f32) as usize).min(КОРЗИН - 1);
        вес[i] += s * s;
    }

    if учтено < 1.0 {
        return (150.0, 0.35, 0.45);
    }
    let средняя_s = (сумма_s / учтено).clamp(0.15, 0.75);
    let средняя_l = (сумма_l / учтено).clamp(0.1, 0.9);

    // Берём корзину вместе с соседями: тон редко попадает ровно в центр, а
    // без сглаживания две почти равные соседние корзины дают дёрганый выбор —
    // близкие обои давали бы заметно разный тон.
    let mut лучшая = 0usize;
    let mut лучший_вес = -1f32;
    for i in 0..КОРЗИН {
        let сумма = вес[(i + КОРЗИН - 1) % КОРЗИН] + вес[i] + вес[(i + 1) % КОРЗИН];
        if сумма > лучший_вес {
            лучший_вес = сумма;
            лучшая = i;
        }
    }
    // Пустая гистограмма — картинка серая. Тон брать неоткуда, оставляем
    // зелёный Void: лучше знакомый цвет, чем случайный.
    if лучший_вес <= 0.0 {
        return (150.0, 0.25, средняя_l);
    }
    let тон = (лучшая as f32 + 0.5) / КОРЗИН as f32 * 360.0;
    (тон, средняя_s, средняя_l)
}

impl Palette {
    pub fn from_pixels(px: &[u8]) -> Palette {
        let (тон, s, _l) = главный_тон(px);

        // Фон — тёмный, но не чёрный: в нём должен читаться тон обоев,
        // иначе смысл всей затеи теряется. Насыщенность держим низкой, чтобы
        // текст поверх не резал глаз.
        let bg = hsl2rgb(тон, (s * 0.55).clamp(0.10, 0.30), 0.075);
        let fg = hsl2rgb(тон, (s * 0.25).clamp(0.05, 0.18), 0.86);
        let accent = hsl2rgb(тон, s.max(0.45), 0.58);
        let cursor = hsl2rgb(тон, s.max(0.40), 0.66);
        let sel_bg = hsl2rgb(тон, s.max(0.35), 0.32);

        // Опорные тона ANSI. Каждый тянется к тону обоев на СДВИГ, светлота и
        // насыщенность общие — отсюда ощущение одного набора.
        const ОПОРЫ: [f32; 6] = [
            0.0,   // красный
            120.0, // зелёный
            48.0,  // жёлтый
            220.0, // синий
            300.0, // пурпурный
            180.0, // голубой
        ];
        let база_s = s.clamp(0.35, 0.70);
        let mut ansi = [[0u8; 3]; 16];

        // 0 — «чёрный». Не чистый ноль: cmatrix и компания красят им фон, и на
        // угольном тоне обоев это выглядит куском темноты, а не дырой.
        ansi[0] = hsl2rgb(тон, (s * 0.5).clamp(0.08, 0.25), 0.13);
        ansi[7] = hsl2rgb(тон, (s * 0.2).clamp(0.04, 0.15), 0.78);
        ansi[8] = hsl2rgb(тон, (s * 0.4).clamp(0.06, 0.22), 0.32);
        ansi[15] = hsl2rgb(тон, (s * 0.12).clamp(0.02, 0.10), 0.95);

        // Якорь — «красный». Он и садится на тон обоев, остальные раскладываются
        // вокруг него. Выбран не по смыслу, а по положению: это 0° круга, от
        // которого отсчитаны все остальные опоры.
        const ЯКОРЬ: f32 = 0.0;
        for (i, опора) in ОПОРЫ.iter().enumerate() {
            let h = сдвинуть_тон(*опора, тон, ЯКОРЬ);
            // 1..6 — обычные, 9..14 — яркие.
            let место = match i {
                0 => 1, 1 => 2, 2 => 3, 3 => 4, 4 => 5, _ => 6,
            };
            ansi[место] = hsl2rgb(h, база_s, 0.52);
            ansi[место + 8] = hsl2rgb(h, (база_s * 1.1).min(0.85), 0.68);
        }

        Palette { bg, fg, cursor, accent, sel_bg, ansi }
    }
}

// ── Запись и рассылка ───────────────────────────────────────────────────────

fn кэш() -> String {
    format!("{}/.cache/dwall", crate::home())
}

impl Palette {
    fn json(&self) -> String {
        let список = self
            .ansi
            .iter()
            .map(|c| format!("\"{}\"", hex(*c)))
            .collect::<Vec<_>>()
            .join(", ");
        format!(
            "{{\n  \"bg\": \"{}\",\n  \"fg\": \"{}\",\n  \"cursor\": \"{}\",\n  \
             \"accent\": \"{}\",\n  \"sel_bg\": \"{}\",\n  \"ansi\": [{}]\n}}\n",
            hex(self.bg), hex(self.fg), hex(self.cursor),
            hex(self.accent), hex(self.sel_bg), список
        )
    }

    fn shell(&self) -> String {
        let mut s = String::new();
        s.push_str(&format!("DWALL_BG={}\n", hex(self.bg)));
        s.push_str(&format!("DWALL_FG={}\n", hex(self.fg)));
        s.push_str(&format!("DWALL_ACCENT={}\n", hex(self.accent)));
        for (i, c) in self.ansi.iter().enumerate() {
            s.push_str(&format!("DWALL_ANSI{i}={}\n", hex(*c)));
        }
        s
    }

    /// Фрагмент конфига ghostty. Подключается из основного через
    /// `config-file = ?colors` — новые окна открываются уже в теме обоев.
    fn ghostty(&self) -> String {
        let mut s = String::from("# Создаётся dwall при смене обоев. Править нет смысла.\n");
        s.push_str(&format!("background = {}\n", hex(self.bg)));
        s.push_str(&format!("foreground = {}\n", hex(self.fg)));
        s.push_str(&format!("cursor-color = {}\n", hex(self.cursor)));
        s.push_str(&format!("selection-background = {}\n", hex(self.sel_bg)));
        s.push_str(&format!("selection-foreground = {}\n", hex(self.ansi[15])));
        for (i, c) in self.ansi.iter().enumerate() {
            s.push_str(&format!("palette = {i}={}\n", hex(*c)));
        }
        s
    }

    /// Тема лаунчера приложений (fuzzel).
    ///
    /// fuzzel читает конфиг при КАЖДОМ запуске и живёт ровно одно нажатие,
    /// поэтому перекрашивать уже открытое окно, как с терминалами через OSC,
    /// не нужно: следующий вызов и так стартует в новых цветах.
    ///
    /// Цвета здесь в формате RRGGBBAA — fuzzel требует альфу обязательно, без
    /// неё он ругается на конфиг и откатывается к встроенной теме.
    fn fuzzel(&self) -> String {
        let mut s = String::from(
            "# Создаётся dwall при смене обоев. Править нет смысла — перезапишется.\n\
             # Раздел [colors] правится целиком; остальное fuzzel берёт из своих\n\
             # значений по умолчанию, поэтому здесь его нет.\n[colors]\n",
        );
        // Фон чуть плотнее терминального: лаунчер висит поверх обоев, и на
        // пёстрой картинке полупрозрачный фон делал список нечитаемым.
        s.push_str(&format!("background={}f2\n", hex(self.bg).trim_start_matches('#')));
        s.push_str(&format!("text={}ff\n", hex(self.fg).trim_start_matches('#')));
        s.push_str(&format!("match={}ff\n", hex(self.accent).trim_start_matches('#')));
        s.push_str(&format!("selection={}ff\n", hex(self.sel_bg).trim_start_matches('#')));
        s.push_str(&format!("selection-text={}ff\n", hex(self.ansi[15]).trim_start_matches('#')));
        s.push_str(&format!("selection-match={}ff\n", hex(self.accent).trim_start_matches('#')));
        s.push_str(&format!("border={}ff\n", hex(self.accent).trim_start_matches('#')));
        s
    }

    /// Тема приглашения oh-my-posh, перекрашенная под обои.
    ///
    /// Берём ТЕМУ ПОЛЬЗОВАТЕЛЯ как основу и подменяем в ней только цвета:
    /// раскладка, значки и сегменты — его, и трогать их мы не вправе. Работаем
    /// по тексту, а не через разбор JSON: цвета в теме встречаются и в местах,
    /// которые схемой не описаны (шаблоны сегментов), а подстановка литерала
    /// `"#rrggbb"` одинаково верна везде.
    ///
    /// Правило подмены. Насыщенные цвета в такой теме ровно одну роль и играют
    /// — акцент (ветка git, путь), поэтому все они уходят в accent обоев.
    /// Остальные — это шкала «фон → текст», и её раскладываем по светлоте:
    /// самый тёмный цвет темы становится самым тёмным цветом палитры и так
    /// далее. Так тема сохраняет собственный контраст, даже если обои сменились
    /// со светлых на тёмные.
    fn oh_my_posh(&self, база: &str) -> String {
        // Шкала от тёмного к светлому — на неё ложатся ненасыщенные цвета темы.
        let шкала = [self.bg, self.ansi[0], self.ansi[8], self.fg, self.ansi[15]];

        let mut цвета: Vec<String> = Vec::new();
        let байты = база.as_bytes();
        let mut i = 0;
        while i + 7 <= байты.len() {
            if байты[i] == b'#'
                && байты[i + 1..i + 7].iter().all(|c| c.is_ascii_hexdigit())
            {
                let цвет = база[i..i + 7].to_string();
                if !цвета.contains(&цвет) {
                    цвета.push(цвет);
                }
                i += 7;
            } else {
                i += 1;
            }
        }

        // Ненасыщенные — по возрастанию светлоты; их порядковый номер и решает,
        // какую ступень шкалы они получат.
        let mut серые: Vec<(&String, f32)> = цвета
            .iter()
            .filter(|c| разбор_hex(c).map(|v| насыщенность(v) <= 0.18).unwrap_or(false))
            .map(|c| (c, разбор_hex(c).map(светлота).unwrap_or(0.0)))
            .collect();
        серые.sort_by(|a, b| a.1.partial_cmp(&b.1).unwrap_or(std::cmp::Ordering::Equal));

        let mut out = база.to_string();
        for (номер, (цвет, _)) in серые.iter().enumerate() {
            let ступень = if серые.len() > 1 {
                номер * (шкала.len() - 1) / (серые.len() - 1)
            } else {
                0
            };
            out = out.replace(цвет.as_str(), &hex(шкала[ступень]));
        }
        for цвет in &цвета {
            if разбор_hex(цвет).map(|v| насыщенность(v) > 0.18).unwrap_or(false) {
                out = out.replace(цвет.as_str(), &hex(self.accent));
            }
        }
        out
    }

    /// Те же цвета, но escape-последовательностями — для уже открытых окон.
    fn osc(&self) -> String {
        let mut s = String::new();
        for (i, c) in self.ansi.iter().enumerate() {
            s.push_str(&format!("\x1b]4;{i};{}\x1b\\", hex(*c)));
        }
        s.push_str(&format!("\x1b]10;{}\x1b\\", hex(self.fg)));
        s.push_str(&format!("\x1b]11;{}\x1b\\", hex(self.bg)));
        s.push_str(&format!("\x1b]12;{}\x1b\\", hex(self.cursor)));
        s
    }
}

/// Разослать палитру во все псевдотерминалы пользователя.
///
/// Запись в `/dev/pts/N` уходит в мастер-конец, то есть в сам эмулятор, и он
/// разбирает её как обычный вывод — поэтому перекрашивается и терминал, и всё,
/// что в нём сейчас нарисовано (ncurses перерисует экран следующим кадром).
///
/// Открываем ТОЛЬКО с O_NONBLOCK: если у pty никто не читает мастер (зависший
/// эмулятор, отцепленный сеанс), обычный open+write повис бы намертво и утащил
/// за собой поток обоев.
fn разослать(osc: &str) {
    let Ok(dir) = std::fs::read_dir("/dev/pts") else { return };
    let uid = unsafe { libc::getuid() };
    for e in dir.flatten() {
        let path = e.path();
        // ptmx — мастер-мультиплексор, не терминал; запись в него бессмысленна.
        if path.file_name().map(|n| n == "ptmx").unwrap_or(false) { continue; }
        let Ok(md) = e.metadata() else { continue };
        use std::os::unix::fs::MetadataExt;
        if md.uid() != uid { continue; }
        let Ok(mut f) = std::fs::OpenOptions::new()
            .write(true)
            .custom_flags(libc::O_NONBLOCK)
            .open(&path)
        else { continue };
        let _ = f.write_all(osc.as_bytes());
    }
}

use std::os::unix::fs::OpenOptionsExt;

/// Посчитать палитру по обоям и разложить её по местам. Зовётся из фонового
/// потока: декодирование картинки тут стоит столько же, сколько сами обои.
///
/// Возвращает посчитанную палитру — ей пользуется режим `dwall --palette`,
/// чтобы показать результат, не поднимая ни композитора, ни обоев.
pub fn apply(path: &str) -> Option<Palette> {
    // Картинку берём уменьшенной: для гистограммы хватает и 64×64, а полный
    // 4K-кадр считался бы десятки миллисекунд впустую.
    let (w, h, px) = crate::load_image(path)?;
    if w == 0 || h == 0 { return None; }
    let мелкая = crate::resize_ex(w, h, &px, 64, 64, true);

    let p = Palette::from_pixels(&мелкая);

    let dir = кэш();
    let _ = std::fs::create_dir_all(&dir);
    let _ = std::fs::write(format!("{dir}/palette.json"), p.json());
    let _ = std::fs::write(format!("{dir}/palette.sh"), p.shell());

    let g = format!("{}/.config/ghostty", crate::home());
    if std::path::Path::new(&g).is_dir() {
        let _ = std::fs::write(format!("{g}/colors"), p.ghostty());
    }

    // Лаунчер приложений. Каталог создаём сами, в отличие от ghostty: у fuzzel
    // конфига может не быть вовсе (он прекрасно работает на умолчаниях), и
    // ждать, пока пользователь заведёт его руками, значило бы никогда не
    // покрасить лаунчер. Пишем только [colors] — остальные настройки остаются
    // за fuzzel, и его умолчания мы не трогаем.
    let f = format!("{}/.config/fuzzel", crate::home());
    if std::fs::create_dir_all(&f).is_ok() {
        let _ = std::fs::write(format!("{f}/fuzzel.ini"), p.fuzzel());
    }

    // Приглашение zsh. Исходную тему НЕ трогаем — читаем её как основу и
    // пишем рядом отдельный dwall.json, на который смотрит .zshrc. Так
    // авторская раскладка остаётся у пользователя в целости, а откат сводится
    // к возврату одной строчки в .zshrc.
    let omp = format!("{}/.config/oh-my-posh", crate::home());
    let основа = format!("{omp}/soft-nord.json");
    if let Ok(текст) = std::fs::read_to_string(&основа) {
        let _ = std::fs::write(format!("{omp}/dwall.json"), p.oh_my_posh(&текст));
    }

    разослать(&p.osc());
    обновить_темы();
    Some(p)
}

/// Перерисовать темы приложений, которые не умеют палитру терминала
/// (Vesktop, Waterfox, AyuGram) — этим занимается отдельный сценарий
/// `~/.local/bin/dwall-themes`.
///
/// Запускаем и НЕ ЖДЁМ: внутри там ffmpeg (кадр обоев для фона Telegram), это
/// секунды. Ждать их в потоке палитры незачем — обои от этого не зависят.
/// Нет сценария — молча идём дальше: dwall обязан работать и без него.
fn обновить_темы() {
    let путь = format!("{}/.local/bin/dwall-themes", crate::home());
    if !std::path::Path::new(&путь).is_file() {
        return;
    }
    // Сироту не оставляем: без wait процесс-зомби висел бы до конца сессии,
    // а обои меняются часто.
    if let Ok(mut дитя) = std::process::Command::new(&путь)
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .spawn()
    {
        std::thread::spawn(move || {
            let _ = дитя.wait();
        });
    }
}

/// `dwall --palette [файл]` — пересчитать палитру и показать её.
///
/// Без файла берутся обои, показанные сейчас. Нужен и для проверки (палитра
/// считается без композитора), и по-человечески: перекрасить терминалы, не
/// трогая обои.
pub fn режим_палитры(файл: Option<String>) -> i32 {
    let Some(path) = файл.or_else(crate::load_current) else {
        eprintln!("dwall --palette: не задан файл и нет запомненных обоев");
        return 1;
    };
    let Some(p) = apply(&path) else {
        eprintln!("dwall --palette: не удалось разобрать {path}");
        return 1;
    };
    println!("обои:  {path}");
    println!("фон:   {}", hex(p.bg));
    println!("текст: {}", hex(p.fg));
    println!("акцент:{}", hex(p.accent));
    print!("ANSI:  ");
    for (i, c) in p.ansi.iter().enumerate() {
        // Каждый цвет показываем им же — видно сразу, что получилось.
        print!("\x1b[48;2;{};{};{}m  \x1b[0m", c[0], c[1], c[2]);
        if i == 7 { print!(" "); }
    }
    println!();
    println!("записано: {}/palette.json, palette.sh, ~/.config/ghostty/colors", кэш());
    0
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Тон цвета обратно из RGB — им и меряем, куда уехали опоры.
    fn тон(c: [u8; 3]) -> f32 {
        rgb2hsl(c).0
    }

    /// Разница тонов по кругу, приведённая к (-180, 180].
    fn разница(a: f32, b: f32) -> f32 {
        let mut d = a - b;
        if d > 180.0 { d -= 360.0; }
        if d <= -180.0 { d += 360.0; }
        d
    }

    /// Обои одного тона: 64×64 пикселя цвета (200,120,60) — подчёркнуто тёплые,
    /// тон около 26°.
    fn тёплые() -> Palette {
        Palette::from_pixels(&[200, 120, 60, 255].repeat(64 * 64))
    }

    /// Палитра принадлежит обоям: якорь («красный», ANSI 1) садится ровно на их
    /// тон.
    ///
    /// Раньше на этом месте стоял тест ровно обратного смысла — «синий обязан
    /// остаться синим». Он был написан под прежний закон (СДВИГ 0.28 с потолком
    /// сдвига в 22°, каждый цвет лишь подкрашивался). Закон отменён по просьбе:
    /// СДВИГ теперь 1.0, круг поворачивается к обоям целиком, и на тёплых обоях
    /// синий обязан перестать быть синим — иначе палитра не принадлежала бы
    /// картинке. Тест падал с самой той правки; проверяем то, что на самом деле
    /// должно выполняться.
    #[test]
    fn якорь_садится_на_тон_обоев() {
        let палитра = тёплые();
        let (обои, _, _) = главный_тон(&[200, 120, 60, 255].repeat(64 * 64));
        let d = разница(тон(палитра.ansi[1]), обои).abs();
        // Допуск — на округление до u8 при переводе HSL→RGB и обратно.
        assert!(d < 3.0, "якорь на тоне обоев: {d}° мимо (обои {обои}°)");
    }

    /// Шесть тонов не схлопываются в один. Это то, ради чего существует
    /// РАЗБРОС: при СДВИГ = 1.0 «тянуть каждый цвет к тону обоев» свело бы все
    /// шесть опор в одну точку круга, а светлота с насыщенностью у них общие —
    /// то есть `ls`, `git diff` и подсветка синтаксиса стали бы попиксельно
    /// одноцветными.
    #[test]
    fn шесть_тонов_не_схлопываются() {
        let палитра = тёплые();
        let цвета: Vec<[u8; 3]> = (1..=6).map(|i| палитра.ansi[i]).collect();
        for (i, a) in цвета.iter().enumerate() {
            for (j, b) in цвета.iter().enumerate().skip(i + 1) {
                assert_ne!(a, b, "ANSI {} и {} совпали попиксельно", i + 1, j + 1);
                // Ближайшие опоры (красный 0° и жёлтый 48°) после сжатия
                // расходятся на 48 × РАЗБРОС ≈ 13°; берём заведомо меньший
                // порог, чтобы тест ловил схлопывание, а не подстройку РАЗБРОСА.
                let d = разница(тон(*a), тон(*b)).abs();
                assert!(d > 8.0, "ANSI {} и {} слились: {d}°", i + 1, j + 1);
            }
        }
    }

    /// Взаимный порядок цветов на круге сохраняется, а расстояния сжимаются
    /// ровно в РАЗБРОС раз. Порядок важен сам по себе: он и делает набор
    /// узнаваемым — «зелёный» остаётся по ту же сторону от «красного», по
    /// какую был.
    #[test]
    fn круг_поворачивается_целиком_а_не_по_цветам() {
        let палитра = тёплые();
        // Опоры из from_pixels: красный, зелёный, жёлтый, синий, пурпурный,
        // голубой — в том же порядке, что ANSI 1..6.
        for (место, опора) in [(1, 0.0), (2, 120.0), (3, 48.0), (4, 220.0), (5, 300.0), (6, 180.0)] {
            let ждём = {
                let mut d: f32 = опора;
                if d > 180.0 { d -= 360.0; }
                d * РАЗБРОС
            };
            let вышло = разница(тон(палитра.ansi[место]), тон(палитра.ansi[1]));
            assert!(
                (вышло - ждём).abs() < 3.0,
                "ANSI {место}: ждали {ждём}° от якоря, вышло {вышло}°"
            );
        }
    }

    /// Яркие цвета (9..14) — те же тона, что и обычные, только светлее.
    /// Иначе `ls` рисовал бы жирный и обычный вариант разными семьями.
    #[test]
    fn яркие_повторяют_тон_обычных() {
        let палитра = тёплые();
        for место in 1..=6 {
            let d = разница(тон(палитра.ansi[место + 8]), тон(палитра.ansi[место])).abs();
            assert!(d < 3.0, "ANSI {} и {}: тона разошлись на {d}°", место, место + 8);
            let (_, _, l_об) = rgb2hsl(палитра.ansi[место]);
            let (_, _, l_ярк) = rgb2hsl(палитра.ansi[место + 8]);
            assert!(l_ярк > l_об, "ANSI {} не светлее обычного", место + 8);
        }
    }
}
